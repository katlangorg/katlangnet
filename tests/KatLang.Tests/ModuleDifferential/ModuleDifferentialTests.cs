using System.Text;

namespace KatLang.Tests;

public class ModuleDifferentialTests
{
    private const string ArtifactPath = "lean/CoreTests/ModuleDifferential.lean";

    public static TheoryData<string> CaseIds()
    {
        var ids = new TheoryData<string>();
        foreach (var fixture in ModuleDifferentialCorpus.Cases)
            ids.Add(fixture.Id);
        return ids;
    }

    [Theory]
    [MemberData(nameof(CaseIds))]
    public async Task PinnedChannelsAgreeInBothFileOrders(string id)
    {
        var fixture = ModuleDifferentialCorpus.Cases.Single(c => c.Id == id);
        var written = await ModuleDifferentialHarness.CheckAsync(fixture);
        var reversed = await ModuleDifferentialHarness.CheckAsync(fixture, reverseFiles: true);
        Assert.Equal(fixture.Exclusion is null, written is not null);
        Assert.Equal(written, reversed);
    }

    [Fact]
    public async Task GeneratedLeanArtifact_MatchesPinnedModulePrograms()
    {
        var expected = await GenerateArtifactAsync();
        var path = Path.Combine(RepoRoot.Find(), ArtifactPath);
        ArtifactRegeneration.VerifyOrRegenerate(RegenerationFlags.ModuleDifferential, ArtifactPath,
            regenerate: () => expected,
            verify: () =>
            {
                var actual = File.ReadAllText(path).ReplaceLineEndings("\n");
                Assert.True(expected == actual, SemanticExplorerLeanArtifactTests.DescribeFirstDifference(expected, actual));
            },
            afterRegenerating: "regenerate the dependent plan-retention gate artifact and build CoreTests and KatLangArityLaws");
    }

    private static async Task<string> GenerateArtifactAsync()
    {
        var builder = new StringBuilder();
        builder.Append("""
            import KatLang

            /-!
            Generated by ModuleDifferentialTests from ModuleDifferentialCorpus.
            Each guard evaluates an admitted C# tree against the hand-written expectation for its source.
            Downloads, parse diagnostics and deferred module regions are checked in C#.
            See docs/design/differential-observations.md, "Module programs".
            -/

            namespace ModuleDifferential
            open KatLang


            """.ReplaceLineEndings("\n"));
        builder.Append(LeanObsTemplate.SharedDefinitions.ReplaceLineEndings("\n"));
        builder.Append("\n\n");

        var comparable = new List<string>();
        var excluded = new List<string>();
        foreach (var fixture in ModuleDifferentialCorpus.Cases)
        {
            var program = await ModuleDifferentialHarness.CheckAsync(fixture);
            Assert.Equal(fixture.Exclusion is null, program is not null);
            builder.Append($"-- {fixture.Id} ({fixture.Rule})\n");
            foreach (var line in fixture.Source.Split('\n'))
                builder.Append("--   ").Append(line).Append('\n');

            if (program is null)
            {
                var outcome = fixture.Diagnostic is { } code ? $"{code} @ {fixture.Span}" : fixture.Expected;
                builder.Append($"-- C# only ({fixture.Exclusion}): {outcome}\n\n");
                excluded.Add(fixture.Id);
                continue;
            }

            builder.Append($"def {fixture.Id} : Expr :=\n  {program}\n");
            builder.Append($"#guard obs {fixture.Id} == {LeanAstEncoder.QuoteString(fixture.Expected)}\n");
            LeanObsTemplate.AppendErrorGuard(builder, fixture.Id, fixture.Payload);
            builder.Append('\n');
            comparable.Add(fixture.Id);
        }

        SemanticExplorerLeanArtifactTests.AppendCountGuard(builder, "comparableCaseIds", comparable, 7,
            "Encoded programs with evaluator guards.");
        SemanticExplorerLeanArtifactTests.AppendCountGuard(builder, "csharpOnlyCaseIds", excluded, 3,
            "Reviewed front-end, loader, and deferred-region exclusions.");
        builder.Append("end ModuleDifferential\n");
        return builder.ToString();
    }
}
