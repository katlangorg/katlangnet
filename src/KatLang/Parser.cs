    private void ReportError(DiagnosticCode code, string message, SourceSpan span)
        => _diagnostics.Report(code, message, span);

    /// <summary>
    /// The significant token before the current one — the reference of every physical-line
    /// decision (<see cref="IsSamePhysicalLineAsPreviousToken"/>). At the start of the
    /// document no significant token precedes, and the tokens the grammar skips must still
    /// decide nothing: a comment is never the reference, so a leading comment changes no
    /// continuation or stand-in decision. The reference is then the reported character a
    /// missing operand would claim (the nearest one before the current token, see
    /// <see cref="TakeReportedCharacterBeforeCurrent"/>), and without one the current token
    /// itself — the start of the document is no line boundary.
    /// </summary>
    private Token Previous
    {
        get
        {
            for (var idx = _pos - 1; idx >= 0; idx--)
            {
                if (!IsSkippedByGrammar(_tokens[idx].Kind))
                    return _tokens[idx];
            }

            var current = NextSignificantIndex(_pos);
            for (var idx = current - 1; idx >= 0; idx--)
            {
                if (_tokens[idx].Kind == TokenKind.Bad)
                    return _tokens[idx];
            }

            return _tokens[current];
        }
    }

    // ── Physical-line continuation policy ───────────────────────────────────
    // Q-65 grammar role first: an independent expression/declaration wins
    // across a physical newline; otherwise ordinary continuation crosses it.
    // All binary rows reuse the precedence registry. Prefix unary minus is
    // eligible only with exact attachment; detached minus and leading star
    // can continue binary arithmetic. Postfix calls/selection and Grace keep
    // their same-line/independent-expression rules. Comma belongs only to its
    // expression-list consumer. A physical line-final star (EOF included) is
    // classified by attachment (issue #183, refining Q-65): attached `A*` is a
    // spread that completes the expression, detached `A *` is multiplication
    // that leaves it incomplete; the newline decision below then applies to
    // the completed or incomplete expression unchanged. A star with a
    // same-line follower keeps the spacing-independent classification, and a
    // same-line-closed spread is then checked for attachment. Comments,
    // reported chars and blank lines do not select grammar roles or
    // reconstruct attachment.

    private readonly record struct ContinuationPolicy(
        bool CanContinueSameLine,
        bool CanContinueAcrossLine);

    // Semicolon is intentionally absent: it is not a valid continuation token.
    // It is handled outside normal continuation policy by the
    // unsupported-semicolon recovery branch in ParseExpressionListOperand,
    // which always reports a diagnostic first.
    private static ContinuationPolicy GetContinuationPolicy(TokenKind kind) => kind switch
    {
        // Comma is consumed only by expression-list grammar, never as an operator.
        TokenKind.Dot or TokenKind.Comma => new(CanContinueSameLine: true, CanContinueAcrossLine: true),
        TokenKind.LParen or TokenKind.LBrace => new(true, false),
        // A same-line '[' after a completed expression opens its postfix selector list
        // (spaces and tabs allowed; a '[' on a later line begins a new list literal).
        TokenKind.LBracket => new(true, false),
        // ':' is not KatLang syntax; the row only lets ParsePostfix report a same-line
        // retired colon selection with its migration diagnostic.
        TokenKind.Colon => new(true, false),
        TokenKind.Tilde => new(true, false),
        // `^` is parsed by ParsePower rather than the binary loop, so it is
        // absent from BinaryOperatorPrecedence and needs its own row with exactly
        // the loop operators' behavior. It has no independent prefix meaning.
        TokenKind.Caret => new(true, true),
        // Reuse the precedence registry. Independent prefix/binding eligibility
        // is decided by the grammar-priority gate, not token exceptions.
        _ when BinaryOperatorPrecedence(kind) > 0 => new(true, true),
        _ => new(false, false),
    };

    private bool MayContinueClosedExpression(TokenKind kind)
    {
        var policy = GetContinuationPolicy(kind);
        if (IsSamePhysicalLineAsPreviousToken())
            return policy.CanContinueSameLine;
        // Grammar role first: an independent expression/declaration wins across LF.
        return policy.CanContinueAcrossLine
            && !StartsDeclaration(includeCommaSpanningBindingPatterns: true)
            && !StartsIndependentExpression();
    }

    private bool StartsIndependentExpression()
        => Current.Kind == TokenKind.Minus ? IsAttachedUnaryMinus() : CanStartExpression(Current.Kind);

    private bool IsAttachedUnaryMinus()
    {
        var index = NextSignificantIndex(_pos);
        var next = _tokens[NextSignificantIndex(index + 1)];
        return _tokens[index].Kind == TokenKind.Minus
            && CanStartUnaryOperand(next.Kind)
            && IsDirectlyAttached(_tokens[index], next);
    }

    // The line primitive used by the policy. Its only direct uses outside
    // MayContinueClosedExpression are the contribution-policy decisions (may a
    // NEW item start here, and did it need a comma?): StartsNextExpressionListSlot
    // and the body loop's row-boundary check — never a continuation decision
    // about the current expression.
    private bool IsSamePhysicalLineAsPreviousToken() => Current.Line == Previous.Line;

    // True when the significant token before the current one LEADS its physical
    // line: no significant token precedes it there (comments and reported
    // characters are skipped as everywhere else). This is the Q-65 leading
    // continuation position (`1` newline `+ Good = 41`, `A` newline
    // `.Good = 41`), where a declaration head sharing the continuation token's
    // line is protected like one on the next line. A mid-line continuation token
    // (`X = a + b = c`, `X = A.b = c`) leaves the head's '=' to the same-line
    // stray-'=' diagnostic, because a declaration head starts a row.
    private bool PreviousLeadsItsPhysicalLine()
    {
        // Every token from _pos up to Current is skipped, so this is Previous.
        var previous = PreviousSignificantIndex(_pos);
        if (previous < 0)
            return false;
        var before = PreviousSignificantIndex(previous);
        return before < 0 || _tokens[before].Line != _tokens[previous].Line;
    }

    // ── Comment-skipping declaration lookahead ──────────────────────────────
    // Offset 0 is the current significant token, offset 1 the next, and so
    // on; comment tokens (and reported characters, see IsSkippedByGrammar) are
    // skipped at every step and the walk saturates at
    // end of input. Declaration headers may have comments between their
    // tokens. A trailing comment after `P =` leaves the body incomplete, while
    // a trailing comment after `P` leaves a completed name. All declaration lookaheads
    // go through this API instead of raw adjacent-token indexing, and they
    // all apply the declaration-head line rule (IsHeadToken), so a comment
    // never relaxes a newline boundary either: `P # note` newline `= 1` is
    // the row `P` followed by a stray `=`, exactly like `P` newline `= 1`.
    // It restarts at _pos on
    // every call, so it is O(offset): use it for the fixed small offsets of a
    // declaration head only, NEVER in a loop over a token run — a run scan walks
    // indices from one cursor with NextSignificantIndex instead (see
    // LookaheadThroughTildesToPropertyDef, LookaheadIsBindingPatternAssignment).
    private Token PeekSignificant(int offset)
    {
        var index = NextSignificantIndex(_pos);
        for (; offset > 0 && index < _tokens.Count - 1; offset--)
            index = NextSignificantIndex(index + 1);
        return _tokens[index];
    }

    // Index-level primitive of the significant-token API: the first index at
    // or after <paramref name="index"/> whose token the grammar sees (not a
    // comment, not a reported character), saturating at the final
    // (end-of-file) token. All declaration/clause lookahead scanning builds on
    // this instead of bespoke raw _tokens[...] skipping loops.
    private int NextSignificantIndex(int index)
    {
        _tokenSteps++;
        while (index < _tokens.Count - 1 && IsSkippedByGrammar(_tokens[index].Kind))
            index++;
        return Math.Min(index, _tokens.Count - 1);
    }

    // Every parser span is half-open and derived from token extents (Token.Span): a
    // construct runs from the start of its first token to the exclusive end of the last
    // token consumed for it. A zero-length token (end of input, the recovery marker)
    // contributes an empty extent, so no span ever pretends a missing character exists.
    private SourceSpan MakeSpan(Token start) => new(start.Span.Start, Previous.Span.End);

    private static SourceSpan TokenSpan(Token t) => t.Span;

    private SourceSpan SpanFrom(Expr start) => new(start.Span?.Start ?? Previous.Span.Start, Previous.Span.End);

    // ── Span-carrying construction (frame-size discipline) ───────────────────
    // Every node and diagnostic that carries a span is built INSIDE one of these
    // small non-inlined helpers, from the token or expression that positions it.
    // A span is a 16-byte value (20 bytes as `SourceSpan?`), and a hidden return
    // buffer plus an argument copy per construction site would otherwise live in
    // the RECURSIVE parsing frame that wrote the `{ Span = ... }` initializer:
    // measured while SourceSpan became a value type, inline construction grew the
    // recursive-descent frames by 15-60% and the calibrated 1 MiB envelope behind
    // MaxNestingDepth no longer held. Built here, the span is a temporary of a
    // short-lived leaf frame instead.
    private const System.Runtime.CompilerServices.MethodImplOptions LeafFrame =
        System.Runtime.CompilerServices.MethodImplOptions.NoInlining;

    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private void ReportErrorAt(DiagnosticCode code, string message, Token token)
        => ReportError(code, message, token.Span);

    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private void ReportErrorFrom(DiagnosticCode code, string message, Token start)
        => ReportError(code, message, MakeSpan(start));

    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private void ReportErrorFrom(DiagnosticCode code, string message, Expr start)
        => ReportError(code, message, SpanFrom(start));

    /// <summary>The diagnostic covers <paramref name="first"/> through <paramref name="last"/> (their hull).</summary>
    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private void ReportErrorAcross(DiagnosticCode code, string message, Token first, Token last)
        => ReportError(code, message, first.Span.Union(last.Span));

    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private static Expr.Num NumAt(Token token) => new(token.NumValue) { Span = token.Span };

    /// <summary>The error-recovery placeholder value, positioned at the offending token.</summary>
    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private static Expr.Num PlaceholderAt(Token token) => new(0) { Span = token.Span };

