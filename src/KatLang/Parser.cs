namespace KatLang;

/// <summary>
/// Recursive-descent parser with precedence climbing for KatLang 0.7.
/// <see cref="ParseSyntax(string)"/> produces a raw AST where all identifiers are
/// <see cref="Expr.Resolve"/> nodes.
/// Public <see cref="Parse(string)"/> overloads are compatibility wrappers that
/// delegate to <see cref="FrontEndPipeline"/> for post-parse elaboration.
/// Clause definitions <c>Name(pattern) = body</c> are collected by same-name
/// family during parsing and classified only after the whole family is known.
/// A family elaborates to ordinary <see cref="Algorithm.User"/> only when it
/// contains exactly one clause and that sole head is a recursive capture/sequence-value
/// parameter pattern. Multi-clause families and literal/mixed heads elaborate to
/// <see cref="Algorithm.Conditional"/>.
/// </summary>
public sealed class Parser
{
    private const string OutputPropertyAccessDiagnostic =
        "Output is the designated result of an algorithm and cannot be accessed through property syntax. " +
        "Call the algorithm directly instead. Instead of `Algo.Output(6)`, write `Algo(6)`.";

    private readonly IReadOnlyList<Token> _tokens;
    private readonly List<Diagnostic> _diagnostics;

    // Optional, parse-scoped observer of exact clause-family pattern comparisons. Null for every
    // production parse (no observation requested); a test measuring the indexed duplicate-detection
    // work passes one through the observed ParseSyntax overload. It only feeds the match-equivalence
    // comparer used by clause-group index sets, so it cannot affect the AST, diagnostics, or spans.
    private readonly PatternComparisonObservations? _comparisonObservations;
    private int _pos;

    // Per-parse counter for the synthetic shared-source property generated by
    // deconstruction binding patterns (`x, *y, z = RHS`). The right-hand side is
    // evaluated once into this shared property; each target then unpacks from it.
    // Reset per parser instance so the elaborated AST stays deterministic across
    // re-parses.
    private int _deconstructionCounter;

    private Parser(
        IReadOnlyList<Token> tokens,
        List<Diagnostic> diagnostics,
        PatternComparisonObservations? comparisonObservations = null)
    {
        _tokens = tokens;
        _diagnostics = diagnostics;
        _comparisonObservations = comparisonObservations;
    }

    // ── Parser recursion-depth budget ───────────────────────────────────────
    // Deeply nested surface input — parentheses, brackets, braces, calls, prefix
    // operators, right-associative power, and clause-head patterns — drives the
    // recursive-descent parser into a fatal, host-terminating StackOverflowException.
    // The fuzz depth probe measured native boundaries as small as ~329 nesting levels
    // (~330 bytes) on a 1 MiB Windows stack. This budget converts such pathological
    // input into ONE structured, source-positioned diagnostic instead of a process
    // crash. It is enforced at the two chokepoints every nested construct passes
    // through once per level — ParseUnary (all expression nesting, because
    // ParseExpression always calls ParseUnary) and ParsePatternAtom (clause-head
    // pattern nesting) — so one shared counter bounds every recursive syntax form.
    // The limit sits far above any realistic KatLang program (including the 256-
    // container-boundary generated-nesting regression test) yet safely below the
    // smallest measured native boundary (~329 structural levels ≈ counter 660 on a
    // 1 MiB Windows Debug stack; Release has more headroom). This is a C#-parser
    // robustness concern only: the Lean model does not describe surface parsing, and
    // every in-budget program parses identically (same AST, spans, and diagnostics).
    //
    // The counter increments per recursive frame, so structural nesting (which passes
    // through both ParseExpression and ParseUnary each level) counts ~2 per level,
    // while prefix/operator/pattern nesting counts ~1 per level. 580 therefore admits
    // ~289 structural levels and ~579 prefix/pattern levels — both well above the
    // 256-boundary bar and below every native crash boundary.
    internal const int MaxNestingDepth = 580;
    private int _nestingDepth;

    // Flat left-associative binary and postfix syntax is parsed iteratively, but it
    // produces a left-deep AST that the frontend's recursive visitors must traverse.
    // Keep that AST depth on the same conservative scale as the ~289 structural
    // levels admitted by MaxNestingDepth. This is per expression chain: independent
    // output rows, comma-separated slots, and list items each start from depth zero.
    internal const int MaxExpressionChainDepth = 256;
    private readonly Dictionary<Expr, int> _expressionChainDepths =
        new(ReferenceEqualityComparer.Instance);

    private abstract class ParserLimitExceededException : Exception { }
    private sealed class NestingLimitExceededException : ParserLimitExceededException { }
    private sealed class ExpressionChainLimitExceededException : ParserLimitExceededException { }

    /// <summary>
    /// Aborts the whole parse with a single structured diagnostic when the recursion
    /// budget is exceeded. Recursive callers increment <see cref="_nestingDepth"/>,
    /// call this, and decrement in a <c>finally</c>.
    /// </summary>
    private void GuardNestingDepth()
    {
        if (_nestingDepth <= MaxNestingDepth)
            return;

        ReportError(
            "Nesting is too deep for the parser to process safely. " +
            "Reduce the depth of nested parentheses, brackets, braces, calls, operators, or patterns.");
        throw new NestingLimitExceededException();
    }

    /// <summary>
    /// Records the binary/postfix depth of a newly constructed expression and aborts
    /// before a recursive frontend visitor can receive an excessively deep AST.
    /// Child depths are looked up by reference so record structural equality never
    /// recursively walks the very chain this guard is protecting.
    /// </summary>
    private Expr GuardExpressionChainDepth(
        Expr expression,
        SourceSpan operatorSpan,
        Expr firstChild,
        Expr? secondChild = null)
    {
        var childDepth = ExpressionChainDepth(firstChild);
        if (secondChild is not null)
            childDepth = Math.Max(childDepth, ExpressionChainDepth(secondChild));

        var depth = childDepth + 1;
        if (depth > MaxExpressionChainDepth)
        {
            ReportError(
                "Expression operator or postfix chain is too deep for the frontend to process safely. " +
                "Break the expression into named intermediate properties.",
                operatorSpan);
            throw new ExpressionChainLimitExceededException();
        }

        _expressionChainDepths.Add(expression, depth);
        return expression;
    }

    private int ExpressionChainDepth(Expr expression)
        => _expressionChainDepths.TryGetValue(expression, out var depth) ? depth : 0;

    // ── Entry points ─────────────────────────────────────────────────────────

    internal static SyntaxParseResult ParseSyntax(string source)
        => ParseSyntax(source, comparisonObservations: null);

    /// <summary>
    /// Raw parse that additionally records exact clause-family pattern comparisons into
    /// <paramref name="comparisonObservations"/>. Test/measurement-only entry: the observed and
    /// unobserved paths share this one implementation, so the AST, diagnostics, and spans are
    /// identical — only the passive comparison count differs.
    /// </summary>
    internal static SyntaxParseResult ParseSyntax(string source, PatternComparisonObservations? comparisonObservations)
    {
        // Always-active host-runtime backstop: reject an oversized source before allocating any
        // tokens or nodes. The configured (possibly lower) per-source limit is applied earlier by
        // the front-end and module loader with richer, context-carrying diagnostics; this hard
        // ceiling protects every direct caller of the raw syntax boundary, including source above
        // the supported maximum. Measured token, ordinary node, and diagnostic counts scale with
        // source length, so this one bound caps those counts. The formerly quadratic per-construct
        // paths (wide assignment deconstruction and large clause families) are now linear in the
        // number of targets/clauses; this remains a resource ceiling, not a blanket linear-time
        // claim for every possible construct.
        if (source.Length > SourceProcessingLimits.MaxSupportedSourceLength)
        {
            return new SyntaxParseResult(
                new Algorithm.User(null, [], [], [], []),
                [SourceProcessingDiagnostics.SourceLengthExceeded(source.Length, SourceProcessingLimits.MaxSupportedSourceLength)]);
        }

        var (tokens, lexDiags) = Lexer.Tokenize(source);
        var diagnostics = new List<Diagnostic>(lexDiags);
        var parser = new Parser(tokens, diagnostics, comparisonObservations);
        Algorithm root;
        try
        {
            root = parser.ParseAlgorithm(isParametrized: true);
            if (parser.Current.Kind != TokenKind.EndOfFile)
            {
                parser.ReportError($"Expected end of input, got '{parser.Current.Kind}'.");
            }
        }
        catch (ParserLimitExceededException)
        {
            // A parser safety budget was exceeded. Its structured diagnostic is already
            // recorded; return a placeholder root so downstream consumers stay
            // well-defined (ParseResult.HasErrors is true) and never see the unsafe tree.
            root = new Algorithm.User(null, [], [], [], []);
        }

        foreach (var violation in AlgorithmValidation.FindExplicitParameterOutputViolations(root))
        {
            diagnostics.Add(new Diagnostic(
                AlgorithmValidation.ExplicitParametersRequireOutputMessage,
                DiagnosticSeverity.Error,
                violation.Span ?? new SourceSpan(1, 1, 1, 1)));
        }

        return new SyntaxParseResult(root, diagnostics);
    }

    /// <summary>
    /// Compatibility wrapper for the default public front-end without module elaboration support.
    /// Delegates to <see cref="FrontEndPipeline"/>.
    /// </summary>
    public static ParseResult Parse(string source)
        => FrontEndPipeline.Process(source).ToParseResult();

    /// <summary>
    /// Compatibility wrapper for the full front-end pipeline with load elaboration.
    /// Delegates to <see cref="FrontEndPipeline"/>.
    /// </summary>
    /// <param name="source">KatLang source code.</param>
    /// <param name="downloadCode">
    /// Injected code fetcher: URL → source text. In WASM, pass a JS interop downloader.
    /// Calling this overload enables module elaboration; if null, a default HttpClient-based fetcher is used.
    /// </param>
    /// <param name="allowedHosts">
    /// Optional set of allowed hostnames for load directives. Defaults to katlang.org only.
    /// </param>
    public static ParseResult Parse(
        string source,
        Func<string, string>? downloadCode,
        IEnumerable<string>? allowedHosts = null)
        => FrontEndPipeline.Process(source, downloadCode, allowedHosts).ToParseResult();

    /// <summary>
    /// Full pipeline with optional configuration via <see cref="RunOptions"/>.
    /// When <paramref name="options"/> is null, or <see cref="RunOptions.DownloadCode"/> is null,
    /// module elaboration is unavailable and <c>load</c> syntax is rejected.
    /// </summary>
    public static ParseResult Parse(string source, RunOptions? options)
        => FrontEndPipeline.Process(source, options).ToParseResult();

    // ── Token access helpers ────────────────────────────────────────────────

    // Comment tokens are kept in the stream for consumers such as colorizers.
    // The parser skips them transparently so grammar rules never see them.

    private Token Current
    {
        get
        {
            while (_pos < _tokens.Count - 1 && _tokens[_pos].Kind == TokenKind.Comment)
                _pos++;
            return _tokens[_pos];
        }
    }

    private Token Advance()
    {
        var token = Current; // normalises _pos past any leading comments
        if (_pos < _tokens.Count - 1) _pos++;
        // skip any comment tokens so the next Current call lands on a real token
        while (_pos < _tokens.Count - 1 && _tokens[_pos].Kind == TokenKind.Comment)
            _pos++;
        return token;
    }

    private Token Expect(TokenKind kind)
    {
        if (Current.Kind == kind)
            return Advance();

        ReportError($"Expected '{kind}', got '{Current.Kind}'.");
        return Token.Bad(Current.Position, 0, Current.Line, Current.Column);
    }

    private void ReportError(string message)
    {
        _diagnostics.Add(new Diagnostic(
            message,
            DiagnosticSeverity.Error,
            new SourceSpan(
                Current.Line,
                Current.Column,
                Current.Line,
                Current.Column + Math.Max(Current.Length, 1) - 1)));
    }

    private void ReportError(string message, SourceSpan span)
    {
        _diagnostics.Add(new Diagnostic(
            message,
            DiagnosticSeverity.Error,
            span));
    }

    private void ReportOutputPropertyAccess(SourceSpan span)
        => ReportError(OutputPropertyAccessDiagnostic, span);

    private Token Previous
    {
        get
        {
            var idx = Math.Max(0, _pos - 1);
            while (idx > 0 && _tokens[idx].Kind == TokenKind.Comment)
                idx--;
            return _tokens[idx];
        }
    }

    // ── Physical-line continuation policy ───────────────────────────────────
    // The parser constitution: A PHYSICAL NEWLINE ENDS A CLOSED EXPRESSION.
    // One policy table governs every token that can continue a closed
    // expression; every line-sensitive parser path consults it through
    // MayContinueClosedExpression. The only cross-line whitelisted
    // continuation is a leading '.' (method-chain layout); anything inside an
    // already-open delimiter ('(' .. ')', '{' .. '}') spans lines until the
    // delimiter closes, because those tokens never reach a closed-expression
    // boundary. Call delimiters '(' and '{', indexing ':', postfix grace
    // '~', and binary operators continue on the same physical line only —
    // the trailing-operator idiom (`A -` newline `1`) works because the
    // operator itself sits on the same line; only its right operand starts a
    // new line. The star '*' is covered by the binary-operator row: a
    // same-line star continues the expression either as infix multiplication
    // or as the directly attached postfix spread marker (disambiguated in
    // ParsePostfix), while a star on a later line never continues — `a*`
    // newline `b` is a spread row followed by a `b` row, and a '*'-led line
    // is collect-marker (binding) syntax or an error. Comments are
    // semantically invisible for all of these decisions: Current/Advance/
    // Previous skip comment tokens and no rule may consult skipped comments
    // to relax a newline boundary, so `A` newline `-1` and `A // note`
    // newline `-1` parse identically.

    private readonly record struct ContinuationPolicy(
        bool CanContinueSameLine,
        bool CanContinueAcrossLine);

    // Semicolon is intentionally absent: it is not a valid continuation token.
    // It is handled outside normal continuation policy by the
    // unsupported-semicolon recovery branch in ParseExpressionListOperand,
    // which always reports a diagnostic first.
    private static ContinuationPolicy GetContinuationPolicy(TokenKind kind) => kind switch
    {
        TokenKind.Dot => new(CanContinueSameLine: true, CanContinueAcrossLine: true),
        TokenKind.LParen or TokenKind.LBrace => new(true, false),
        TokenKind.Colon => new(true, false),
        TokenKind.Tilde => new(true, false),
        _ when GetBinaryOpInfo(kind).Precedence > 0 => new(true, false),
        _ => new(false, false),
    };

    private bool MayContinueClosedExpression(TokenKind kind)
    {
        var policy = GetContinuationPolicy(kind);
        return IsSamePhysicalLineAsPreviousToken()
            ? policy.CanContinueSameLine
            : policy.CanContinueAcrossLine;
    }

    // The line primitive used by the policy. The only direct use outside
    // MayContinueClosedExpression is StartsImplicitExpressionListSeparator, which
    // is a contribution-policy decision (may a NEW expression start here?),
    // not a continuation decision about the current expression.
    private bool IsSamePhysicalLineAsPreviousToken() => Current.Line == Previous.Line;

    // ── Comment-skipping declaration lookahead ──────────────────────────────
    // Offset 0 is the current significant token, offset 1 the next, and so
    // on; comment tokens are skipped at every step and the walk saturates at
    // end of input. Declaration headers may have comments between their
    // tokens (`P // note` newline `= 1`), and comments must never change
    // what parses as a declaration — all declaration lookaheads go through
    // this API instead of raw adjacent-token indexing.
    private Token PeekSignificant(int offset)
    {
        var index = NextSignificantIndex(_pos);
        for (; offset > 0 && index < _tokens.Count - 1; offset--)
            index = NextSignificantIndex(index + 1);
        return _tokens[index];
    }

    // Index-level primitive of the significant-token API: the first
    // non-comment token index at or after <paramref name="index"/>,
    // saturating at the final (end-of-file) token. All declaration/clause
    // lookahead scanning builds on this instead of bespoke raw _tokens[...]
    // comment loops.
    private int NextSignificantIndex(int index)
    {
        while (index < _tokens.Count - 1 && _tokens[index].Kind == TokenKind.Comment)
            index++;
        return Math.Min(index, _tokens.Count - 1);
    }

    private SourceSpan MakeSpan(Token start) => new(
        start.Line, start.Column,
        Previous.Line, Previous.Column + Math.Max(Previous.Length, 1) - 1);

    private static SourceSpan TokenSpan(Token t) => new(
        t.Line, t.Column, t.Line, t.Column + Math.Max(t.Length, 1) - 1);

    private SourceSpan SpanFrom(Expr start) => new(
        start.Span?.StartLineNumber ?? Previous.Line,
        start.Span?.StartColumn ?? Previous.Column,
        Previous.Line,
        Previous.Column + Math.Max(Previous.Length, 1) - 1);

    // ── Algorithm parsing ───────────────────────────────────────────────────
    // Reads property definitions (Name = ...) and output expression lines.
    // Explicit output syntax: `Output = expr` is special output-definition syntax,
    // NOT a property assignment or clause head. It lowers to the algorithm's
    // Output list.

    private Algorithm ParseAlgorithm(bool isParametrized)
    {
        var opens = new List<Expr>();
        var hasOpenDeclaration = false;
        var properties = new List<Property>();
        // O(1) mirror of the names already in `properties`, so duplicate-declaration
        // detection is a set lookup instead of a linear scan of the growing list.
        // Scanning `properties.Any(p => p.Name == name)` once per declaration made
        // ParseAlgorithm O(P^2) in the number of top-level declarations (a source of tens
        // of thousands of `A = ...` lines spent tens of seconds here). Kept in sync at every
        // in-loop `properties.Add`; the post-loop clause-group elaboration runs after all
        // duplicate checks, so those additions do not need mirroring.
        var declaredPropertyNames = new HashSet<string>(StringComparer.Ordinal);
        var output = new List<Expr>();
        var hasExplicitOutput = false;
        var hasImplicitOutput = false;
        var sawOutputClauseDefinition = false;
        SourceSpan? explicitOutputSpan = null;
        var clauseGroups = new Dictionary<string, List<CondBranch>>();
        var clauseGroupSpans = new Dictionary<string, List<SourceSpan>>();
        var clauseGroupNameSpans = new Dictionary<string, List<SourceSpan>>();
        var clauseGroupIsPublic = new Dictionary<string, bool>();
        // Per-group match-equivalence index over branch patterns already seen. Membership is
        // O(1) amortized, so duplicate-branch detection across a whole family is O(clauses)
        // instead of the former O(clauses^2) branchList.Any(IsMatchEquivalent) scan. The
        // ordered branchList remains the source of truth for branch order, diagnostics, and
        // spans; this set is only a lookup accelerator, local to this one parse.
        var clauseGroupPatternSets = new Dictionary<string, HashSet<Pattern>>();

        void ParseClauseDefinition(bool isPublic)
        {
            if (isPublic)
            {
                var publicToken = Current;
                Advance(); // consume 'public'
                if (Current.Kind == TokenKind.Identifier && Current.StringValue == "Output")
                {
                    ReportError(
                        "'public' cannot be applied to output definitions. Use 'Output = expr' without 'public'.",
                        TokenSpan(publicToken));
                }
            }

            var name = Current.StringValue!;
            var nameToken = Current;

            if (name == "Output")
            {
                ReportError(
                    sawOutputClauseDefinition
                        ? "Output cannot be a conditional or multi-branch definition. Declare branches on the enclosing algorithm instead."
                        : "Output cannot declare explicit parameters. Declare parameters on the enclosing algorithm instead.",
                    TokenSpan(nameToken));
                sawOutputClauseDefinition = true;

                Advance(); // consume 'Output'
                Expect(TokenKind.LParen);
                _ = ParsePattern();
                Expect(TokenKind.RParen);
                Expect(TokenKind.Equals);
                _ = ParseOutputLine();
                return;
            }

            // Check for conflict: mixing normal and conditional definition
            if (declaredPropertyNames.Contains(name))
            {
                ReportError($"Property '{name}' is already defined.");
            }

            Advance(); // consume identifier
            Expect(TokenKind.LParen);
            var pattern = ParsePattern();
            Expect(TokenKind.RParen);

            ValidateCollectingParameterDeclarations(name, pattern, TokenSpan(nameToken));

            Expect(TokenKind.Equals);
            var body = ParseOutputLine();
            var clauseSpan = MakeSpan(nameToken);

            if (!clauseGroups.TryGetValue(name, out var branchList))
            {
                branchList = [];
                clauseGroups[name] = branchList;
                clauseGroupSpans[name] = [];
                clauseGroupNameSpans[name] = [];
                clauseGroupIsPublic[name] = isPublic;
                clauseGroupPatternSets[name] = new HashSet<Pattern>(Pattern.CreateMatchEquivalenceComparer(_comparisonObservations));
            }
            else if (clauseGroupIsPublic[name] != isPublic)
            {
                ReportError(
                    $"All clauses of '{name}' must use the same public modifier. Either mark every clause public or none of them.",
                    TokenSpan(nameToken));
            }

            // Check for duplicate branch pattern (match-equivalent). Add returns false exactly
            // when an earlier branch in this family carried a match-equivalent pattern — the same
            // condition the former branchList.Any(IsMatchEquivalent) scan tested, but O(1) amortized.
            if (!clauseGroupPatternSets[name].Add(pattern))
            {
                ReportError($"Duplicate branch pattern for conditional algorithm '{name}'.", clauseSpan);
            }

            branchList.Add(new CondBranch(pattern, body));
            clauseGroupSpans[name].Add(clauseSpan);
            clauseGroupNameSpans[name].Add(TokenSpan(nameToken));
        }

        while (Current.Kind != TokenKind.EndOfFile
            && Current.Kind != TokenKind.RParen
            && Current.Kind != TokenKind.RBrace)
        {
            // Skip bad tokens for error recovery
            if (Current.Kind == TokenKind.Bad)
            {
                Advance();
                continue;
            }

            // Check for invalid grace on property name: ~Name = ... or ~public Name = ...
            if (Current.Kind == TokenKind.Tilde && LookaheadThroughTildesToPropertyDef())
            {
                ReportError("Grace operator cannot be applied to property names.");
                while (Current.Kind == TokenKind.Tilde) Advance();
                // Fall through to normal property definition handling
            }

            // Open declaration: open target1, target2, ...
            if (Current.Kind == TokenKind.KeywordOpen)
            {
                if (hasOpenDeclaration)
                {
                    ReportError("Only one 'open' declaration is allowed per algorithm.");
                }
                if (properties.Count > 0 || output.Count > 0)
                {
                    ReportError("'open' declaration must appear before any properties or output expressions.");
                }
                hasOpenDeclaration = true;
                Advance(); // consume 'open'
                var openExprs = ParseOpenTargetList();
                NormalizeAndValidateOpenForms(openExprs);
                opens.AddRange(openExprs);
            }
            // public open ... → reject
            else if (Current.Kind == TokenKind.KeywordPublic && LookaheadIsPublicOpen())
            {
                ReportError("'public' cannot be applied to open declarations.");
                Advance(); // consume 'public'
                // Fall through: next iteration will parse the open declaration normally
            }
            // public Output = ... → reject (output cannot be public)
            else if (Current.Kind == TokenKind.KeywordPublic && LookaheadIsPublicOutputDef())
            {
                ReportError("'public' cannot be applied to output definitions. Use 'Output = expr' without 'public'.");
                Advance(); // consume 'public'
                // Fall through: next iteration will parse as explicit output
            }
            // Check for public property definition: public Name = ...
            else if (Current.Kind == TokenKind.KeywordPublic && LookaheadIsPublicPropertyDef())
            {
                Advance(); // consume 'public'
                var nameToken = Current;
                var name = nameToken.StringValue!;

                // Check for duplicate property definition
                if (declaredPropertyNames.Contains(name) || clauseGroups.ContainsKey(name))
                {
                    ReportError($"Property '{name}' is already defined.");
                }

                Advance(); // consume identifier
                Advance(); // consume '='
                var body = ParseOutputLine();
                properties.Add(new Property(name, body, IsPublic: true)
                {
                    DeclarationSpans = [TokenSpan(nameToken)]
                });
                declaredPropertyNames.Add(name);
            }
            // public clause definition: public Name(...) = ...
            else if (Current.Kind == TokenKind.KeywordPublic && LookaheadIsPublicClauseDefinition())
            {
                ParseClauseDefinition(isPublic: true);
            }
            // Explicit output definition: Output = expr
            else if (Current.Kind == TokenKind.Identifier && Current.StringValue == "Output" && LookaheadIsEquals())
            {
                var outputToken = Current;
                if (hasExplicitOutput)
                {
                    ReportError("Algorithm output may be defined only once.");
                }
                if (hasImplicitOutput)
                {
                    ReportError("Cannot use both explicit 'Output = ...' and implicit trailing output in the same algorithm.");
                }

                hasExplicitOutput = true;
                explicitOutputSpan ??= TokenSpan(outputToken);
                Advance(); // consume 'Output'
                Advance(); // consume '='
                // `Output = ...` is a definition, so its body is line-bounded:
                // a newline ends it and never continues it as another
                // expression-list row (an expression on a following line is a
                // separate output row parsed by the loop below, not part of the
                // `Output = ...` body). A ';' here is invalid expression syntax
                // and reports the unsupported-semicolon diagnostic; any
                // expression error recovery then attaches is recovery only, not
                // valid carry-on syntax.
                // A later implicit row is NOT an additional contribution —
                // explicit and implicit output cannot mix, so the row reports
                // the mixing diagnostic in the implicit-output branch below.
                var exprs = ParseOutputLineExprs(
                    allowNewlineImplicitExpressionListSeparator: false);
                AppendOutputContribution(output, exprs, joinWithExisting: output.Count != 0);
            }
            // Invalid Output clause definition: Output(pattern) = body
            else if (Current.Kind == TokenKind.Identifier && Current.StringValue == "Output" && LookaheadIsClauseDefinition())
            {
                var outputToken = Current;
                ReportError(
                    sawOutputClauseDefinition
                        ? "Output cannot be a conditional or multi-branch definition. Declare branches on the enclosing algorithm instead."
                        : "Output cannot declare explicit parameters. Declare parameters on the enclosing algorithm instead.",
                    TokenSpan(outputToken));
                sawOutputClauseDefinition = true;

                Advance(); // consume 'Output'
                Expect(TokenKind.LParen);
                _ = ParsePattern();
                Expect(TokenKind.RParen);
                Expect(TokenKind.Equals);
                _ = ParseOutputLine();
            }
            // Check for property definition: Identifier '='
            else if (Current.Kind == TokenKind.Identifier && LookaheadIsEquals())
            {
                var nameToken = Current;
                var name = nameToken.StringValue!;

                // Check for duplicate property definition
                if (declaredPropertyNames.Contains(name) || clauseGroups.ContainsKey(name))
                {
                    ReportError($"Property '{name}' is already defined.");
                }

                Advance(); // consume identifier
                Advance(); // consume '='
                var body = ParseOutputLine();
                properties.Add(new Property(name, body)
                {
                    DeclarationSpans = [TokenSpan(nameToken)]
                });
                declaredPropertyNames.Add(name);
            }
            // Deconstruction / collecting binding pattern: x, *y, z = RHS (including
            // the collecting-led forms `*items = RHS` and `*first, rest = RHS`). A
            // plain single `name = RHS` is handled by the property branch above.
            else if ((Current.Kind is TokenKind.Identifier or TokenKind.Star)
                && LookaheadIsBindingPatternAssignment())
            {
                ParseBindingPatternAssignment(properties, clauseGroups, declaredPropertyNames);
            }
            // Clause definition: Name(pattern) = body
            else if (Current.Kind == TokenKind.Identifier && LookaheadIsClauseDefinition())
            {
                ParseClauseDefinition(isPublic: false);
            }
            else
            {
                // Implicit output expression line, or an additional output
                // contribution. Adjacency between complete expressions is an
                // implicit expression-list separator in output contexts — root
                // output, algorithm and brace bodies, explicit parenthesized
                // groups, and call argument lists. This loop appends
                // contributions that are separated by definitions. Explicit and implicit output
                // cannot mix in either direction: an implicit row after
                // `Output = ...` reports the same diagnostic as `Output = ...`
                // after an implicit row.
                if (hasExplicitOutput)
                    ReportError("Cannot use both explicit 'Output = ...' and implicit trailing output in the same algorithm.");
                else
                    hasImplicitOutput = true;
                var exprs = ParseOutputLineExprs(allowNewlineImplicitExpressionListSeparator: true);
                AppendOutputContribution(output, exprs, joinWithExisting: output.Count != 0);
            }
        }

        // Elaborate same-name clause groups only after the full family is known.
        // This is the real ordinary-vs-conditional decision boundary: a clause family
        // is ordinary only when it contains exactly one clause and that sole
        // head is a recursive capture/sequence-value parameter pattern. For example,
        //   F(0) = 0
        //   F(x) = 1
        // must stay conditional for the whole family even though the second
        // clause would qualify in isolation.
        foreach (var (name, branches) in clauseGroups)
        {
            var spans = clauseGroupSpans[name];
            var nameSpans = clauseGroupNameSpans[name];
            var isPublic = clauseGroupIsPublic.TryGetValue(name, out var publicValue) && publicValue;
            var elaboratedClauseGroup = Algorithm.ElaborateClauseGroup(branches);

            if (elaboratedClauseGroup is Algorithm.User ordinaryAlg)
            {
                properties.Add(new Property(name, ordinaryAlg, IsPublic: isPublic)
                {
                    DeclarationSpans = nameSpans
                });
                continue;
            }

            var condAlg = (Algorithm.Conditional)elaboratedClauseGroup;

            for (var i = 0; i < condAlg.Branches.Count; i++)
            {
                if (PatternContainsCollectingParameter(condAlg.Branches[i].Pattern))
                {
                    ReportError(
                        $"Collecting bindings are only supported in ordinary explicit parameter lists for '{name}'.",
                        spans[i]);
                }
            }

            // Validate no Grace operators in true conditional branch bodies.
            foreach (var branch in condAlg.Branches)
            {
                var graceSpan = FindGraceSpan(branch.Body.Output);
                if (graceSpan is not null)
                {
                    ReportError($"Grace is not allowed in conditional branch bodies for '{name}'.", graceSpan);
                }
            }

            // Validate uniform top-level pattern arity across conditional branches.
            // Nested internal pattern structure may vary.
            // Also validate uniform top-level output arity across branches.
            if (condAlg.Branches.Count > 1)
            {
                var expectedArity = condAlg.Branches[0].Pattern.TopLevelArity();
                for (int i = 1; i < condAlg.Branches.Count; i++)
                {
                    var branchArity = condAlg.Branches[i].Pattern.TopLevelArity();
                    if (branchArity != expectedArity)
                    {
                        ReportError(
                            $"All branches of conditional algorithm '{name}' must have the same top-level pattern arity. " +
                            $"Expected {expectedArity} (from first branch), but branch {i + 1} has arity {branchArity}.",
                            spans[i]);
                    }
                }

                var expectedOutputArity = condAlg.Branches[0].TopLevelOutputArity();
                for (int i = 1; i < condAlg.Branches.Count; i++)
                {
                    var branchOutputArity = condAlg.Branches[i].TopLevelOutputArity();
                    if (branchOutputArity != expectedOutputArity)
                    {
                        ReportError(
                            $"All branches of conditional algorithm '{name}' must have the same top-level output arity. " +
                            $"Expected {expectedOutputArity} (from first branch), but branch {i + 1} has output arity {branchOutputArity}.",
                            spans[i]);
                    }
                }
            }

            properties.Add(new Property(name, condAlg, IsPublic: isPublic)
            {
                DeclarationSpans = nameSpans
            });
        }

        return new Algorithm.User(
            Parent: null,
            Parameters: [],
            Opens: opens,
            Properties: properties,
            Output: output)
        {
            IsParametrized = isParametrized,
            ExplicitOutputSpan = explicitOutputSpan
        };
    }

    private static SourceSpan? CombineSpans(SourceSpan? left, SourceSpan? right)
        => left is null
            ? right
            : right is null
                ? left
                : new SourceSpan(
                    left.StartLineNumber,
                    left.StartColumn,
                    right.EndLineNumber,
                    right.EndColumn);

    private const string UnsupportedSemicolonExpressionMessage =
        "Semicolon is not supported as an expression separator. Use comma or adjacency for separate expressions, or parentheses for one sequence value.";

    // ── Spread marker ───────────────────────────────────────────────
    // Expression spreading is written with the postfix spread marker `*`:
    // a star DIRECTLY attached to a completed expression's last token
    // (zero-width gap — no whitespace, comment, or newline between) that has
    // no valid same-line right operand after it lowers to the one unary AST
    // node SequenceSpread(expr) (shared with Lean). When a same-line
    // expression-start token follows the star, the star is infix
    // multiplication regardless of spacing (`a*b`, `a* b`, `a *b`, `a * b`
    // all multiply), so spreading before another same-line supplied item
    // requires a comma: `a*, b`. An unattached star with nothing after it on
    // its line is multiplication whose right operand continues on the next
    // line (`a *` newline `b`), while an attached line-final star is a
    // spread (`a*` newline `b` is a spread row and a `b` row). Chained
    // spread is `value**` — each directly attached star nests one more
    // unary spread node, building SequenceSpread(SequenceSpread(expr)).
    // The parser only records the written layers; evaluation applies them
    // compositionally, `value**` agreeing with `(value*)*` (each layer
    // spreads the value the previous layer's supply re-captures — see
    // Evaluator.EvalSequenceSpreadCounted).
    //
    // A spread expression is legal only as a whole expression-list slot
    // (root output rows, call argument slots, parenthesized group and
    // brace-body slots, list-literal elements, definition/`Output =` body
    // slots, and the operand of another spread), or as the receiver of the
    // fluent dot continuation `operand*.Target(...)`, which lowers to the
    // ordinary lexical call `Target(operand*, ...)` with the spread as the
    // leading argument slot. It never participates as an operand of a
    // unary/binary operator or an indexing target/selector — those
    // placements report the targeted misplaced-spread diagnostic and
    // recover by unwrapping to the spread's operand, so no embedded
    // SequenceSpread survives in the recovered tree.
    //
    // Prefix `*` is the collect marker and is COLLECTING-BINDING syntax only
    // (`*name` in binding positions). It is not an expression operator, so a
    // prefix star reaching expression position reports the targeted
    // collect-marker diagnostic and recovers to the following operand.
    // Semicolon is not a valid way to continue or join an expression;
    // `A* ; B` is unsupported-semicolon diagnostic recovery only.
    // Every SequenceSpread the parser builds goes through
    // CreateSequenceSpread (architecture-tested).
    private static Expr.SequenceSpread CreateSequenceSpread(
        Expr operand, SourceSpan? span, SourceSpan? spreadMarkerSpan)
        => new Expr.SequenceSpread(operand) { Span = span, SpreadMarkerSpan = spreadMarkerSpan };

    private void AppendOutputContribution(List<Expr> output, IReadOnlyList<Expr> exprs, bool joinWithExisting)
    {
        if (exprs.Count == 0)
            return;

        _ = joinWithExisting;
        output.AddRange(exprs);
    }

    /// <summary>
    /// Parses the open-target list after the <c>open</c> keyword. `open` is
    /// a declaration/import directive, not an output expression, so its
    /// target list is a dedicated COMMA list — never semicolon sequence syntax:
    /// `open A, B, C` opens three targets, while `;` and same-line adjacency
    /// are not separators and report a missing-comma diagnostic. The first
    /// target must begin on the same physical line as `open`. Comma keeps
    /// its normal explicit line-continuation behavior — `open A,` newline
    /// `B` and `open A` newline `, B` both continue the list — and a leading
    /// `.` continues a dotted target (`open A` newline `.B` is `open A.B`),
    /// but a plain newline never does: `open Math` newline `Math.Pi`
    /// is an open plus a report row. Each algorithm still allows at most one
    /// `open` declaration. Targets never go through generic
    /// output-precedence parsing, so no sequence construction or spread is
    /// ever built for an open target.
    /// </summary>
    private List<Expr> ParseOpenTargetList()
    {
        var targets = new List<Expr>();

        // The first target must start on the `open` line; a newline directly
        // after `open` (comments are invisible) is a missing target, and the
        // next line stays a separate statement/output row.
        if (!IsSamePhysicalLineAsPreviousToken() || !StartsOpenTargetAtom())
        {
            ReportError(
                "Expected an open target after 'open' on the same physical line.",
                TokenSpan(Previous));
            return targets;
        }

        if (ParseOpenTargetAtom() is { } first)
            targets.Add(first);

        // Comma is the only separator and may continue the list across a
        // physical newline (trailing `open A,` newline `B` or leading
        // `open A` newline `, B`), matching general comma continuation.
        while (Current.Kind == TokenKind.Comma)
        {
            var comma = Advance(); // consume ','
            if (!StartsOpenTargetAtom())
            {
                ReportError("Expected an open target after ','.", TokenSpan(comma));
                break;
            }
            if (ParseOpenTargetAtom() is { } target)
                targets.Add(target);
        }

        // Anything else on the same line after a target is a separator
        // mistake, not a following output row.
        if (IsSamePhysicalLineAsPreviousToken()
            && Current.Kind is not (TokenKind.EndOfFile or TokenKind.RParen or TokenKind.RBrace))
        {
            if (Current.Kind == TokenKind.Semicolon)
            {
                ReportError(
                    "Open target lists use ',' separators, not ';'. Write `open A, B` to open multiple targets.",
                    TokenSpan(Current));
                Advance(); // consume ';' so it is not re-reported at statement level
            }
            else
            {
                ReportError(
                    "Expected ',' between open targets. Open targets are separated by commas.",
                    TokenSpan(Current));

                // A string open target is pure sugar with no postfix
                // continuations, so a trailing star after one (`open 'url'*`)
                // never becomes a spread target — opens must not contain a
                // SequenceSpread built from a string target. Consume the star
                // run here anyway, exactly like the ';' branch above, so the
                // leftover marker is not re-parsed at statement level and
                // re-reported as a PREFIX collect-marker error, which would
                // describe binding syntax the user never wrote.
                while (Current.Kind == TokenKind.Star)
                    Advance();
            }
        }

        return targets;
    }

    // A token that can begin an open target atom. Declaration starters are
    // excluded so recovery after a dangling comma leaves a following
    // definition line intact, mirroring the adjacency rule's exclusions.
    private bool StartsOpenTargetAtom()
        => CanStartExpression(Current.Kind)
            && Current.Kind != TokenKind.KeywordOpen
            && !(Current.Kind == TokenKind.Identifier
                && (LookaheadIsEquals() || LookaheadIsClauseDefinition()))
            && !(Current.Kind == TokenKind.Tilde && LookaheadThroughTildesToPropertyDef());

    /// <summary>
    /// Parses exactly one open target atom: a single-quoted string target
    /// (desugared through <see cref="CreateLoadOpenTarget"/>), or one plain
    /// expression (resolve, argumentless dotted path, or parenthesized block —
    /// anything else is rejected by open-form validation). A spread-marked
    /// open target (`open A*`) parses to a SequenceSpread expression and is
    /// rejected by open-form validation (spread is not an open form).
    /// </summary>
    private Expr? ParseOpenTargetAtom()
    {
        if (Current.Kind == TokenKind.StringLiteral)
        {
            // String literal sugar: open 'url' → open load('url').
            var token = Advance();
            return CreateLoadOpenTarget(token.StringValue ?? "", TokenSpan(token));
        }

        // One plain expression: resolve, dotted path (a leading '.' may
        // continue it across a newline via the dot whitelist), or block
        // parenthesized block. This is the expression layer, not generic
        // output-precedence parsing — no joins, adjacency, or spread slots.
        return ParseExpression();
    }

    private static Expr CreateLoadOpenTarget(string url, SourceSpan? span)
    {
        var urlExpr = new Expr.StringLiteral(url) { Span = span };
        var loadArgs = new Algorithm.User(
            Parent: null, Parameters: [], Opens: [],
            Properties: [], Output: [urlExpr])
        { IsParametrized = false };
        // This synthetic load has no identifier token in source, so it must
        // stay spanless. Borrowing the quoted URL span would make downstream
        // source-backed semantic models report an identifier on a string token.
        var loadResolve = new Expr.Resolve("load");
        return new Expr.Call(loadResolve, loadArgs) { Span = span };
    }

    /// <summary>
    /// Checks if the token after the current identifier is '='.
    /// Used to distinguish property definitions from output expressions.
    /// </summary>
    private bool LookaheadIsEquals()
        => PeekSignificant(1).Kind == TokenKind.Equals;

    // ── Star-marker diagnostics ─────────────────────────────────────────────
    // Prefix `*name` (directly attached) is the ONLY collecting-binding
    // spelling, valid only in binding positions. Postfix `expr*` (directly
    // attached, no same-line right operand) is the ONLY spread spelling,
    // valid only as a whole expression-list slot or fluent dot-chain
    // receiver. Every other star is infix multiplication.

    private static string CollectMarkerAttachmentDiagnostic(string name) =>
        $"The collect marker `*` must be directly attached to its binding name: write `*{name}`.";

    private static string RepeatedCollectMarkerDiagnostic(string name) =>
        $"A collecting binding uses exactly one collect marker: write `*{name}`.";

    private const string CollectMarkerMissingNameDiagnostic =
        "The collect marker `*` must be followed by a binding name, as in `*items`.";

    private static string SpreadMarkerInBindingPatternDiagnostic(string name) =>
        $"Postfix `*` is the spread marker and is not valid in a binding pattern. Write `*{name}` to declare a collecting binding.";

    private const string CollectMarkerInExpressionDiagnostic =
        "Prefix `*` is the collect marker and is valid only in binding patterns (explicit parameter lists and assignment deconstruction).";

    private const string MisplacedSpreadDiagnostic =
        "A spread expression contributes items to the surrounding item supply and cannot be used as a scalar operand. Spread the whole expression instead, e.g. `(A + B)*`.";

    /// <summary>
    /// Targeted message for the indexing continuation (`A*:0`): selection
    /// needs ONE value while a spread supplies items, and the two nearby
    /// valid forms mean DIFFERENT things — `(A:0)*` selects first and then
    /// spreads the selected value, `(A*):0` captures the spread supply as one
    /// sequence value and then selects. The message names both intentions so
    /// they are not presented as interchangeable fixes.
    /// </summary>
    private const string SpreadSelectionDiagnostic =
        "Selection cannot be applied directly to a spread expression — a spread supplies items to the surrounding item supply, not one selectable value. Write `(A:0)*` to select first and then spread the selected value, or `(A*):0` to capture the spread items as one sequence value and then select; the two forms have different meanings.";

    /// <summary>
    /// Rejects a spread expression used as an operand of a larger expression
    /// (unary/binary operand, indexing target or selector). Spread is legal
    /// only as a whole expression-list slot, as the operand of another
    /// spread, or as the fluent dot-chain receiver (which lowers to a call).
    /// The default message covers scalar operand positions; the indexing
    /// continuation passes <see cref="SpreadSelectionDiagnostic"/> to
    /// distinguish select-then-spread from capture-then-select. Recovery
    /// unwraps to the innermost non-spread operand so no embedded
    /// SequenceSpread survives in the recovered tree — downstream layers
    /// keep the slot-level-only spread invariant.
    /// </summary>
    private Expr RejectMisplacedSpreadOperand(Expr expr, string diagnostic = MisplacedSpreadDiagnostic)
    {
        if (expr is not Expr.SequenceSpread spread)
            return expr;

        if (spread.Span is { } span)
            ReportError(diagnostic, span);
        else
            ReportError(diagnostic);

        var operand = spread.Operand;
        while (operand is Expr.SequenceSpread inner)
            operand = inner.Operand;
        return operand;
    }

    private readonly record struct BindingTarget(
        string Name,
        ParameterKind Kind,
        SourceSpan? NameSpan,
        SourceSpan? CollectMarkerSpan);

    /// <summary>
    /// Checks whether the tokens at the current position form a deconstruction
    /// assignment with identifier targets. A plain single <c>name =</c> is left
    /// to the ordinary property path; <c>*name =</c> is the unambiguous
    /// lone-collecting-binding form. The prefix collect marker must be
    /// directly attached to its binding name; the scan is deliberately
    /// TOLERANT of malformed marker shapes (a gap after the star, or a
    /// repeated star) so <see cref="ParseBindingPatternAssignment"/> can
    /// report the targeted attachment/malformed diagnostics — validity is
    /// enforced during parsing, never here. Targets are identifiers with an
    /// optional leading star run; anything else falls through to ordinary
    /// expression parsing.
    /// </summary>
    private bool LookaheadIsBindingPatternAssignment()
    {
        var index = NextSignificantIndex(_pos);
        var sawComma = false;
        var sawCollectMarker = false;

        while (true)
        {
            // Optional prefix collect-marker star run before the binding name.
            while (_tokens[index].Kind == TokenKind.Star)
            {
                sawCollectMarker = true;
                index = NextSignificantIndex(index + 1);
            }

            if (_tokens[index].Kind != TokenKind.Identifier)
                return false;
            index = NextSignificantIndex(index + 1);

            switch (_tokens[index].Kind)
            {
                case TokenKind.Comma:
                    sawComma = true;
                    index = NextSignificantIndex(index + 1);
                    continue;
                case TokenKind.Equals:
                    return sawComma || sawCollectMarker;
                default:
                    return false;
            }
        }
    }

    /// <summary>
    /// Parses a deconstruction assignment <c>x, *y, z = RHS</c>. The
    /// lone-collecting-binding form <c>*items = RHS</c> is also supported. The right-hand side
    /// is evaluated once and its items are bound to the targets by the shared
    /// deconstruction matcher, with one optional movable collecting binding that COLLECTS
    /// its assigned items as one exact immutable list (<c>CollectSegment</c>).
    /// A malformed marker shape (a gap between the star and its name, or a
    /// repeated star) reports a targeted diagnostic and binds the name as an
    /// ordinary fixed target — malformed recovery never creates a collecting
    /// binding.
    /// </summary>
    private void ParseBindingPatternAssignment(
        List<Property> properties,
        Dictionary<string, List<CondBranch>> clauseGroups,
        HashSet<string> declaredPropertyNames)
    {
        var targets = new List<BindingTarget>();
        while (true)
        {
            // Optional prefix collect-marker star run (the lookahead is
            // tolerant; exactly one directly attached star is valid syntax).
            Token? firstStarToken = null;
            var starCount = 0;
            while (Current.Kind == TokenKind.Star)
            {
                var starToken = Advance();
                firstStarToken ??= starToken;
                starCount++;
            }

            var nameToken = Current; // Identifier, guaranteed by the lookahead
            var name = nameToken.StringValue!;
            Advance(); // consume identifier

            var isCollectingBinding = false;
            Token? collectMarkerToken = null;
            if (starCount == 1 && IsDirectlyAttached(firstStarToken!, nameToken))
            {
                isCollectingBinding = true;
                collectMarkerToken = firstStarToken;
            }
            else if (starCount == 1)
            {
                ReportError(
                    CollectMarkerAttachmentDiagnostic(name),
                    CombineSpans(TokenSpan(firstStarToken!), TokenSpan(nameToken))!);
            }
            else if (starCount > 1)
            {
                ReportError(
                    RepeatedCollectMarkerDiagnostic(name),
                    CombineSpans(TokenSpan(firstStarToken!), TokenSpan(nameToken))!);
            }

            var kind = isCollectingBinding ? ParameterKind.Collecting : ParameterKind.Normal;
            targets.Add(new BindingTarget(
                name,
                kind,
                TokenSpan(nameToken),
                collectMarkerToken is { } markerForSpan ? TokenSpan(markerForSpan) : null));

            if (Current.Kind == TokenKind.Comma)
            {
                Advance(); // consume ','
                continue;
            }

            break;
        }

        Expect(TokenKind.Equals);
        var rhsBody = ParseOutputLine();

        if (targets.Count(static target => target.Kind == ParameterKind.Collecting) > 1)
        {
            var firstCollectingSpan = targets
                .First(static target => target.Kind == ParameterKind.Collecting)
                .NameSpan!;
            ReportError(
                "A deconstruction binding pattern may contain at most one collecting binding (`*name`).",
                firstCollectingSpan);
        }

        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var target in targets)
        {
            if (!seen.Add(target.Name)
                || declaredPropertyNames.Contains(target.Name)
                || clauseGroups.ContainsKey(target.Name))
            {
                if (target.NameSpan is { } targetNameSpan)
                    ReportError($"Property '{target.Name}' is already defined.", targetNameSpan);
            }
        }

        AddDeconstructionProperties(targets, rhsBody, properties, declaredPropertyNames);
    }

    /// <summary>
    /// Elaborates a deconstruction pattern into properties. The right-hand side is
    /// hoisted into one synthetic shared property (evaluated once), and each target
    /// becomes a property whose body applies an inline sequence-value-pattern
    /// helper to that shared source, returning its own bound name. The helper reuses
    /// the ordinary patterned-binding path: assignment deconstruction is an
    /// unpacking receiver, so a single sequence-valued right-hand side is opened and
    /// matched element-by-element (Python-style: <c>x, y, z = A</c> splits a stored
    /// sequence value <c>A</c>). Explicit <c>x, y, z = A*</c> supplies the same
    /// items. This unpacking is deconstruction-specific and does not change function
    /// calls, which still pass <c>A</c> as one argument unless <c>A*</c> is written.
    /// Synthetic constructs carry no source spans; only the target property names are
    /// source-backed declarations. The collect-marker metadata is the one additional
    /// source-backed syntax span retained on the synthetic binding pattern.
    /// </summary>
    private void AddDeconstructionProperties(
        IReadOnlyList<BindingTarget> targets,
        Algorithm rhsBody,
        List<Property> properties,
        HashSet<string> declaredPropertyNames)
    {
        var sourceName = $"$deconstruct${_deconstructionCounter++}";
        properties.Add(new Property(sourceName, rhsBody));
        declaredPropertyNames.Add(sourceName);

        var captures = targets
            .Select(static target => (ParameterPattern)new CaptureParameterPattern(target.Name, Span: null, target.Kind)
            {
                CollectMarkerSpan = target.CollectMarkerSpan,
            })
            .ToList();
        var seqPattern = new SequenceValueParameterPattern(captures);
        var explicitParameters = ParameterPattern.FlattenCaptures([seqPattern]);

        // One identity token shared by every target helper of this deconstruction. The evaluator
        // keys its run-scoped shared-bind cache on it so the N helpers bind the shared N-capture
        // pattern once per binding context instead of once per demanded target (O(N) not O(N^2)).
        var deconstructionGroup = new object();

        for (var targetIndex = 0; targetIndex < targets.Count; targetIndex++)
        {
            var target = targets[targetIndex];

            // Construct with empty Parameters and assign the shared explicitParameters through the
            // initializer. Passing them to the constructor would make it eagerly rebuild
            // ParameterPatterns via FromDeclarations (O(N) in the capture count) only for the
            // initializer to immediately overwrite it with the shared [seqPattern] — that waste,
            // repeated for each of the N sibling helpers, is an O(N^2) allocation source. Every
            // helper shares the same seqPattern and explicitParameters, so this is O(1) per helper.
            var helper = new Algorithm.User(
                Parent: null,
                Parameters: [],
                Opens: [],
                Properties: [],
                Output: [new Expr.Resolve(target.Name)])
            {
                Parameters = explicitParameters,
                ParameterPatterns = [seqPattern],
                ExplicitParameterPatterns = [seqPattern],
                ExplicitParameters = explicitParameters,
                IsParametrized = true,
                IsAssignmentDeconstructionHelper = true,
                AssignmentDeconstructionGroup = deconstructionGroup,
                AssignmentDeconstructionTargetIndex = targetIndex,
            };

            var args = new Algorithm.User(
                Parent: null,
                Parameters: [],
                Opens: [],
                Properties: [],
                Output: [new Expr.Resolve(sourceName)]);

            var propertyBody = new Algorithm.User(
                Parent: null,
                Parameters: [],
                Opens: [],
                Properties: [],
                Output: [new Expr.Call(new Expr.Block(helper), args)])
            {
                IsParametrized = true,
            };

            properties.Add(new Property(target.Name, propertyBody)
            {
                DeclarationSpans = target.NameSpan is { } targetNameSpan
                    ? [targetNameSpan]
                    : []
            });
            declaredPropertyNames.Add(target.Name);
        }
    }

    /// <summary>
    /// Exact source-offset adjacency: <paramref name="second"/> starts at the
    /// code unit where <paramref name="first"/> ends, with nothing — no
    /// whitespace, comment, or newline — between them. This is the attachment
    /// test for both star markers (prefix collect marker to its binding name,
    /// completed expression to its postfix spread marker).
    /// </summary>
    private static bool IsDirectlyAttached(Token first, Token second)
        => second.Position == first.Position + first.Length;

    /// <summary>
    /// Checks if the current tilde sequence is followed by Identifier '=' or 'public Identifier ='.
    /// Used to detect invalid grace on property definitions.
    /// </summary>
    private bool LookaheadThroughTildesToPropertyDef()
    {
        var offset = 0;
        while (PeekSignificant(offset).Kind == TokenKind.Tilde)
            offset++;
        // ~Name = ...
        if (PeekSignificant(offset).Kind == TokenKind.Identifier
            && PeekSignificant(offset + 1).Kind == TokenKind.Equals)
            return true;
        // ~public Name = ...
        return PeekSignificant(offset).Kind == TokenKind.KeywordPublic
            && PeekSignificant(offset + 1).Kind == TokenKind.Identifier
            && PeekSignificant(offset + 2).Kind == TokenKind.Equals;
    }

    /// <summary>
    /// Checks if 'public' keyword is followed by 'open' keyword.
    /// Used to detect and reject public open declarations.
    /// </summary>
    private bool LookaheadIsPublicOpen()
        => PeekSignificant(1).Kind == TokenKind.KeywordOpen;

    /// <summary>
    /// Checks if 'public' keyword is followed by 'Output' '='.
    /// Used to detect and reject public output definitions.
    /// </summary>
    private bool LookaheadIsPublicOutputDef()
    {
        var next = PeekSignificant(1);
        return next.Kind == TokenKind.Identifier
            && next.StringValue == "Output"
            && PeekSignificant(2).Kind == TokenKind.Equals;
    }

    /// <summary>
    /// Checks if 'public' keyword is followed by Identifier '='.
    /// Used to detect public property definitions.
    /// </summary>
    private bool LookaheadIsPublicPropertyDef()
        => PeekSignificant(1).Kind == TokenKind.Identifier
            && PeekSignificant(2).Kind == TokenKind.Equals;

    /// <summary>
    /// Checks if the current identifier is followed by '(' ... ')' '='.
    /// Used to detect clause definitions: <c>Name(pattern) = body</c>.
    /// Skips comment tokens during lookahead. Handles nested parentheses.
    /// </summary>
    private bool LookaheadIsClauseDefinition()
    {
        return LookaheadIsParenEqualsFrom(_pos + 1);
    }

    /// <summary>
    /// Checks if 'public' is followed by Identifier '(' ... ')' '='.
    /// Used to detect public clause definitions.
    /// </summary>
    private bool LookaheadIsPublicClauseDefinition()
    {
        var next = NextSignificantIndex(_pos + 1); // skip 'public'
        if (_tokens[next].Kind != TokenKind.Identifier)
            return false;
        return LookaheadIsParenEqualsFrom(next + 1);
    }

    /// <summary>
    /// From position <paramref name="start"/>, checks for '(' ... ')' '=' with balanced parens.
    /// Skips comment tokens during lookahead.
    /// </summary>
    private bool LookaheadIsParenEqualsFrom(int start)
    {
        var next = NextSignificantIndex(start);
        if (_tokens[next].Kind != TokenKind.LParen)
            return false;
        next++; // skip '('
        var depth = 1;
        while (depth > 0)
        {
            next = NextSignificantIndex(next);
            var kind = _tokens[next].Kind;
            if (kind == TokenKind.EndOfFile)
                return false;
            if (kind == TokenKind.LParen) depth++;
            else if (kind == TokenKind.RParen) depth--;
            next++;
        }
        next = NextSignificantIndex(next);
        return _tokens[next].Kind == TokenKind.Equals;
    }

    // ── Pattern parsing (for clause definitions) ────────────────────────────

    /// <summary>
    /// Finds the <see cref="SourceSpan"/> of the first <see cref="Expr.Grace"/> node in the list.
    /// Used to reject Grace in conditional branch bodies with accurate error location.
    /// </summary>
    private static SourceSpan? FindGraceSpan(IReadOnlyList<Expr> exprs)
    {
        foreach (var expr in exprs)
        {
            var span = FindGraceSpan(expr);
            if (span is not null)
                return span;
        }
        return null;
    }

    private static SourceSpan? FindGraceSpan(Expr expr) => expr switch
    {
        Expr.Grace g => g.Span,
        Expr.Binary(_, var l, var r) => FindGraceSpan(l) ?? FindGraceSpan(r),
        Expr.Unary(_, var o) => FindGraceSpan(o),
        Expr.Index(var t, var s) => FindGraceSpan(t) ?? FindGraceSpan(s),
        Expr.SequenceConstruct(var l, var r) => FindGraceSpan(l) ?? FindGraceSpan(r),
        Expr.SequenceSpread(var operand) => FindGraceSpan(operand),
        Expr.ListLiteral(var items) => FindGraceSpan(items),
        Expr.DotCall(var t, _, var a) => FindGraceSpan(t) ?? (a is not null ? FindGraceSpan(a.Output) : null),
        Expr.Call(var f, var a) => FindGraceSpan(f) ?? FindGraceSpan(a.Output),
        Expr.Block(var alg) => FindGraceSpan(alg.Output),
        _ => null,
    };

    private static bool PatternContainsCollectingParameter(Pattern pattern)
        => pattern switch
        {
            Pattern.Bind { ParameterKind: ParameterKind.Collecting } => true,
            Pattern.SequenceValue(var items) => items.Any(PatternContainsCollectingParameter),
            _ => false,
        };

    private void ValidateCollectingParameterDeclarations(string propertyName, Pattern pattern, SourceSpan span)
    {
        if (pattern.TryGetOrdinaryClauseParameterPatterns() is not { } parameterPatterns)
        {
            if (PatternContainsCollectingParameter(pattern))
            {
                ReportError(
                    $"Collecting bindings are only supported in ordinary explicit parameter lists for '{propertyName}'.",
                    span);
            }
            return;
        }

        if (ParameterPattern.HasMultipleCollectingCapturesAtAnyLevel(parameterPatterns))
        {
            ReportError("Only one collecting binding is allowed per pattern level.", span);
        }
        else if (ParameterPattern.HasRepeatedCaptureNameIncludingCollecting(parameterPatterns))
        {
            ReportError("Repeated parameter names cannot include collecting bindings.", span);
        }
    }

    /// <summary>
    /// Parses a clause-head pattern for ordinary recursive parameter patterns
    /// or conditional algorithm branches.
    /// Patterns are comma-separated at the top level (creating a sequence-value pattern
    /// when more than one element), with support for:
    /// - integer literals (including negative)
    /// - identifier binders
    /// - nested parenthesized sequence-value patterns
    /// </summary>
    private Pattern ParsePattern()
    {
        var items = ParsePatternItems();
        if (items.Count != 1)
            return new Pattern.SequenceValue(items);

        return items[0] is Pattern.SequenceValue ? new Pattern.SequenceValue(items) : items[0];
    }

    private List<Pattern> ParsePatternItems()
    {
        var items = new List<Pattern>();
        items.Add(ParsePatternAtom());

        while (Current.Kind == TokenKind.Comma)
        {
            Advance(); // consume ','
            items.Add(ParsePatternAtom());
        }

        return items;
    }

    /// <summary>
    /// Parses a single atomic pattern element:
    /// - number literal → Pattern.LitInt
    /// - negative number → Pattern.LitInt with negated value
    /// - identifier → Pattern.Bind
    /// - ( pattern ) -> nested sequence-value pattern
    /// Grace `~` is rejected in clause-head patterns.
    /// </summary>
    private Pattern ParsePatternAtom()
    {
        // Clause-head pattern nesting recurses through here (the nested `(pattern)`
        // case), so enforce the shared parser recursion budget once per level.
        _nestingDepth++;
        try
        {
            GuardNestingDepth();
            return ParsePatternAtomCore();
        }
        finally { _nestingDepth--; }
    }

    /// <summary>
    /// Builds a named binding pattern with optional collecting metadata.
    /// </summary>
    private static Pattern CreateBindingPattern(
        Token nameToken,
        ParameterKind kind = ParameterKind.Normal,
        SourceSpan? collectMarkerSpan = null)
        => new Pattern.Bind(nameToken.StringValue!)
        {
            NameSpan = TokenSpan(nameToken),
            ParameterKind = kind,
            CollectMarkerSpan = collectMarkerSpan,
        };

    /// <summary>
    /// Parses a collecting binding <c>*name</c> at the start of a pattern
    /// atom (the star is not yet consumed). The collect marker must be
    /// DIRECTLY attached to its binding name — a gap reports the targeted
    /// attachment diagnostic, a repeated star reports the repeated-marker
    /// diagnostic, and a star without a name reports the missing-name
    /// diagnostic. Malformed recovery binds the name as an ordinary fixed
    /// binding (or a placeholder) and never introduces a collecting binding.
    /// </summary>
    private Pattern ParseCollectingBindingPatternAtom()
    {
        var markerToken = Advance(); // consume '*'
        var markerSpan = TokenSpan(markerToken);

        // Repeated markers (`**items`): consume the run, report once, and
        // never create a collecting binding from the malformed shape.
        if (Current.Kind == TokenKind.Star)
        {
            var lastStar = markerToken;
            while (Current.Kind == TokenKind.Star)
                lastStar = Advance();

            if (Current.Kind == TokenKind.Identifier)
            {
                var repeatedNameToken = Advance();
                ReportError(
                    RepeatedCollectMarkerDiagnostic(repeatedNameToken.StringValue!),
                    CombineSpans(markerSpan, TokenSpan(repeatedNameToken))!);
                return CreateBindingPattern(repeatedNameToken);
            }

            ReportError(
                CollectMarkerMissingNameDiagnostic,
                CombineSpans(markerSpan, TokenSpan(lastStar))!);
            return new Pattern.Bind("_error_");
        }

        if (Current.Kind != TokenKind.Identifier)
        {
            ReportError(CollectMarkerMissingNameDiagnostic, markerSpan);

            // Consume one malformed same-line pattern atom where possible so a
            // following comma/closing delimiter remains available to the caller.
            // Malformed syntax must not introduce collecting-binding semantics
            // into the recovered tree.
            if (Current.Kind is not (TokenKind.Comma
                or TokenKind.RParen
                or TokenKind.RBrace
                or TokenKind.EndOfFile)
                && Current.Line == markerToken.Line)
                return ParsePatternAtom();

            return new Pattern.Bind("_error_");
        }

        var nameToken = Advance();
        var name = nameToken.StringValue!;

        if (!IsDirectlyAttached(markerToken, nameToken))
        {
            ReportError(
                CollectMarkerAttachmentDiagnostic(name),
                CombineSpans(markerSpan, TokenSpan(nameToken))!);
            // A detached marker is not a collecting binding; the name stays
            // an ordinary fixed binding in the recovered tree.
            return CreateBindingPattern(nameToken);
        }

        var hadPostfixGrace = false;
        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
        {
            hadPostfixGrace = true;
            Advance();
        }
        if (hadPostfixGrace)
            ReportError("Collecting bindings cannot use `~` reordering.", TokenSpan(nameToken));

        return CreateBindingPattern(nameToken, ParameterKind.Collecting, markerSpan);
    }

    private Pattern ParsePatternAtomCore()
    {
        switch (Current.Kind)
        {
            case TokenKind.Star:
                return ParseCollectingBindingPatternAtom();

            case TokenKind.Tilde:
                {
                    while (Current.Kind == TokenKind.Tilde) Advance(); // skip prefix tildes
                    if (Current.Kind == TokenKind.Identifier)
                    {
                        var token = Advance();
                        while (Current.Kind == TokenKind.Tilde) Advance(); // skip postfix tildes
                        ReportError("Grace is not allowed in clause-head patterns.");
                        return CreateBindingPattern(token);
                    }

                    ReportError("Grace is not allowed in clause-head patterns.");
                    // Try to parse remaining atom for recovery. `~*name` reaches
                    // the collecting-binding atom below, so the grace error keeps
                    // the collecting binding.
                    return ParsePatternAtom();
                }

            case TokenKind.Number:
                {
                    var token = Advance();
                    return new Pattern.LitInt(token.NumValue);
                }

            case TokenKind.Minus:
                {
                    Advance(); // consume '-'
                    if (Current.Kind != TokenKind.Number)
                    {
                        ReportError("Expected number after '-' in pattern.");
                        return new Pattern.Bind("_error_");
                    }
                    var token = Advance();
                    return new Pattern.LitInt(-token.NumValue);
                }

            case TokenKind.StringLiteral:
                {
                    var token = Advance();
                    return new Pattern.LitString(token.StringValue ?? "");
                }

            case TokenKind.Identifier:
                {
                    var token = Advance();
                    var name = token.StringValue!;

                    var hadPostfixGrace = false;
                    while (Current.Kind == TokenKind.Tilde)
                    {
                        hadPostfixGrace = true;
                        Advance();
                    }

                    if (hadPostfixGrace)
                        ReportError("Grace is not allowed in clause-head patterns.");

                    // Postfix `*` after a binding name is spread syntax, never
                    // binding syntax. Report the targeted marker-side diagnostic
                    // when the star is clearly meant as a marker (list-final:
                    // followed by ',', ')', '}', another '*', end of input, or a
                    // line break); a star followed by an operand-like token is
                    // left for the caller's ordinary unexpected-token handling so
                    // multiplication-shaped mistakes keep their generic error.
                    if (Current.Kind == TokenKind.Star
                        && MayContinueClosedExpression(TokenKind.Star))
                    {
                        var next = PeekSignificant(1);
                        var looksLikeMarker = next.Kind is TokenKind.Comma
                            or TokenKind.RParen
                            or TokenKind.RBrace
                            or TokenKind.Star
                            or TokenKind.EndOfFile
                            || next.Line != Current.Line;
                        if (looksLikeMarker)
                        {
                            var lastStar = Advance();
                            while (Current.Kind == TokenKind.Star
                                && MayContinueClosedExpression(TokenKind.Star))
                                lastStar = Advance(); // consume a malformed star run whole
                            ReportError(
                                SpreadMarkerInBindingPatternDiagnostic(name),
                                CombineSpans(TokenSpan(token), TokenSpan(lastStar))!);
                            return CreateBindingPattern(token);
                        }
                    }

                    return CreateBindingPattern(token);
                }

            case TokenKind.LParen:
                {
                    Advance(); // consume '('
                    var items = ParsePatternItems();
                    Expect(TokenKind.RParen);
                    // Parentheses in patterns are structural at every nesting level:
                    // (a, b) -> SequenceValue([a, b]); (x) -> SequenceValue([x]);
                    // ((a, b)) -> SequenceValue([SequenceValue([a, b])]).
                    return new Pattern.SequenceValue(items);
                }

            default:
                {
                    ReportError($"Unexpected token in pattern: '{Current.Kind}'.");
                    Advance(); // skip for recovery
                    return new Pattern.Bind("_error_");
                }
        }
    }

    // ── Output line parsing ─────────────────────────────────────────────────
    // Reads comma-separated expressions (spread slots via the attached
    // postfix spread marker `expr*`).

    /// <summary>
    /// Parses a property body as an algorithm: the comma-separated expressions
    /// become the algorithm's output list.
    /// If the body is a single algorithm-valued block expression, return its
    /// algorithm directly (enables nested property access like X.Y where
    /// X = (Y = ...)). Plain sequence values such as <c>(a, b)</c> stay wrapped
    /// as a single block output so callers can distinguish one sequence value
    /// from multiple top-level outputs.
    /// </summary>
    private Algorithm ParseOutputLine()
    {
        // Definition bodies are line-bounded: a newline ends the body and never
        // continues it as another expression-list row. An expression on a
        // following line is parsed by the surrounding output/algorithm context,
        // not absorbed into this body. Same-line adjacency, an already-open
        // delimiter, a same-line trailing/leading binary operator, and a
        // leading '.' (method-chain layout) still continue the body's single
        // expression. A ';' is invalid expression syntax and reports the
        // unsupported-semicolon diagnostic; any tokens consumed after it are
        // error recovery, not a valid continuation.
        var exprs = ParseOutputLineExprs(
            allowNewlineImplicitExpressionListSeparator: false);

        // Unwrap only algorithm-valued blocks (brace blocks, blocks with
        // declarations/opens, or elaborated module blocks). Preserve plain
        // parenthesized sequence values like (a, b) as one top-level block value.
        if (exprs.Count == 1
            && exprs[0] is Expr.Block(var innerAlg)
            && innerAlg.ShouldUnwrapSingleBlockPropertyBody())
            return innerAlg with { IsParametrized = true };

        return new Algorithm.User(
            Parent: null,
            Parameters: [],
            Opens: [],
            Properties: [],
            Output: exprs)
        {
            IsParametrized = true
        };
    }

    /// <summary>
    /// Normalizes and validates open expressions. The list arriving here
    /// comes from ParseOpenTargetList's dedicated comma-list parsing — one
    /// individual target per entry, matching Lean's per-target model. A
    /// spread-marked target (`open A*`) parses to a SequenceSpread and is
    /// rejected here by open-form validation before evaluator or runtime
    /// involvement — spread is not an open form.
    /// DotCall(obj, name, null) is the canonical form for dotted paths in opens.
    /// Rejects DotCall with args as invalid.
    /// Lean: Expr.openForm? — only Block, Resolve, and argumentless DotCall
    /// are open forms; everything else is rejected.
    /// </summary>
    private void NormalizeAndValidateOpenForms(List<Expr> exprs)
    {
        for (var i = 0; i < exprs.Count; i++)
            exprs[i] = NormalizeOpenExpr(exprs[i]);

        foreach (var expr in exprs)
        {
            if (!IsOpenForm(expr))
            {
                var kind = OpenExprKind(expr);
                ReportOpenFormError($"Invalid open form: '{kind}' is not allowed in open declarations.", expr);
            }
        }
    }

    // Open-form diagnostics must point at the offending open target, not at
    // whatever token follows the open declaration.
    private void ReportOpenFormError(string message, Expr expr)
    {
        if (expr.Span is { } span)
            ReportError(message, span);
        else
            ReportError(message);
    }

    /// <summary>
    /// Recursively normalizes an open expression:
    /// - DotCall(obj, name, null) is the canonical no-arg form (kept as-is)
    /// - DotCall(obj, name, args) → report error (call-like syntax not allowed in opens)
    /// - Recurse through the DotCall target; Block is kept as-is.
    /// A SequenceSpread target falls through unchanged (never rebuilt here,
    /// which would bypass CreateSequenceSpread) and is rejected by the
    /// open-form validation that follows.
    /// </summary>
    private Expr NormalizeOpenExpr(Expr expr)
    {
        switch (expr)
        {
            case Expr.DotCall dotCall when dotCall.Args is null:
                return new Expr.DotCall(NormalizeOpenExpr(dotCall.Target), dotCall.Name)
                {
                    Span = expr.Span,
                    MemberSpan = dotCall.MemberSpan
                };

            case Expr.DotCall(var target, var name, _):
                ReportOpenFormError(
                    $"Invalid open form: call-like dotCall '.{name}(...)' is not allowed in open declarations.",
                    expr);
                // Return as-is; validation will also flag it
                return expr;

            case Expr.Block(var alg):
                // Block in open position: normalize opens within the block's own opens
                return expr;

            default:
                return expr;
        }
    }

    /// <summary>
    /// Predicate for valid open forms at parse time.
    /// Lean: Expr.openForm? — only Block, Resolve, and argumentless DotCall
    /// post-elaboration. Spread is NOT an open form (a spread-marked target
    /// such as `open A*` is rejected here).
    /// DotCall with args is NOT a valid open form.
    /// load calls (Call(Resolve("load"), _)) are allowed as *surface* open forms because
    /// the load elaboration pass will rewrite them to Block nodes before open resolution.
    /// After elaboration, no load calls or StringLiteral nodes remain —
    /// see Lean postElabInvariant (rejects both structurally).
    /// load is NOT a core Expr constructor; it is surface syntax only.
    /// </summary>
    private static bool IsOpenForm(Expr e) => e is
        Expr.Resolve or Expr.DotCall(_, _, null) or Expr.Block
        || e.TryGetUnresolvedLoadArguments(out _);

    /// <summary>
    /// Human-readable kind string for open-form validation errors.
    /// </summary>
    private static string OpenExprKind(Expr e) => e switch
    {
        Expr.Num => "num",
        Expr.StringLiteral => "stringLiteral",
        Expr.Param => "param",
        Expr.Unary => "unary",
        Expr.Binary => "binary",
        Expr.SequenceConstruct => "sequenceConstruct",
        Expr.SequenceSpread => "spread",
        Expr.ListLiteral => "listLiteral",
        Expr.Index => "index",
        Expr.Call => "call",
        Expr.DotCall => "dotCall",
        Expr.Grace => "grace",
        Expr.NativeCall => "nativeCall",
        _ => "unknown",
    };

    /// <summary>
    /// Parses one output contribution. Comma and allowed adjacency create
    /// expression-list items. Semicolon is no longer an expression operator;
    /// when encountered here it reports a targeted diagnostic and recovers as
    /// an expression-list separator.
    /// Returns the root expression-list items consumed by the surrounding
    /// output/call context.
    /// When <paramref name="allowNewlineImplicitExpressionListSeparator"/> is
    /// true (root output and algorithm/brace bodies), an expression starting on
    /// a later physical line is an implicit expression-list separator. When
    /// false (definition bodies and explicit `Output = ...` bodies), the body is
    /// line-bounded: a newline ends it and a following expression is parsed by
    /// the surrounding output/algorithm context instead. Open target lists never
    /// use this method: `open` has its own dedicated comma-list parser
    /// (<see cref="ParseOpenTargetList"/>).
    /// </summary>
    private List<Expr> ParseOutputLineExprs(
        bool allowNewlineImplicitExpressionListSeparator = false)
    {
        return ParseExpressionListOperand(allowNewlineImplicitExpressionListSeparator);
    }

    private List<Expr> ParseExpressionListOperand(
        bool allowNewlineImplicitExpressionListSeparator)
    {
        // Spread slots need no extra handling here: an attached postfix `*`
        // parses as a postfix continuation directly to Expr.SequenceSpread.
        // A spread expression is always one whole slot — a same-line token
        // after the star that could start an expression makes the star
        // multiplication instead, so spreading before another same-line
        // supplied item requires an explicit comma (`a*, b`).
        var exprs = new List<Expr>();
        exprs.Add(ParseExpression());

        while (true)
        {
            if (Current.Kind == TokenKind.Comma)
            {
                Advance(); // consume ','
            }
            else if (Current.Kind == TokenKind.Semicolon)
            {
                // Semicolon is never valid expression syntax. Report the
                // diagnostic and consume it as error recovery (treating it like
                // an expression-list separator) so later parsing and diagnostics
                // stay useful. This is recovery only, not a supported continuation.
                ReportUnsupportedSemicolon(Current);
                Advance();
            }
            else if (!StartsImplicitExpressionListSeparator(
                allowNewlineImplicitExpressionListSeparator))
            {
                break;
            }

            exprs.Add(ParseExpression());
        }

        return exprs;
    }

    private void ReportUnsupportedSemicolon(Token token)
        => ReportError(UnsupportedSemicolonExpressionMessage, TokenSpan(token));

    /// <summary>
    /// True when the current token starts another complete expression, so the
    /// adjacency parses as an implicit expression-list separator. Same-line
    /// adjacency always qualifies; adjacency across a physical newline qualifies
    /// only in contexts that opt into multiline expression lists (root output and
    /// algorithm/brace bodies). Definition bodies and explicit `Output = ...`
    /// bodies opt out, so a newline ends them.
    /// Tokens that begin a declaration are never adjacent expressions: the
    /// algorithm loop owns those forms and their diagnostics.
    /// Implicit list separation fires only for tokens that start a new independent
    /// expression. A token that legally continues the current expression is
    /// consumed before this check runs: in particular, a '(' or '{' after a
    /// callable target on the same physical line is a call delimiter handled
    /// by <see cref="ParsePostfix"/>, so `F (1, 2)` is the call `F(1, 2)`.
    /// A physical newline never continues a closed expression into a call,
    /// so `F` newline `(1, 2)` reaches this check and separates as the
    /// expression list `F, (1, 2)`. Non-callable targets always separate:
    /// `2 (3)` is the expression list `2, 3`, never a call or multiplication.
    /// </summary>
    private bool StartsImplicitExpressionListSeparator(
        bool allowNewlineImplicitExpressionListSeparator)
    {
        if (!IsSamePhysicalLineAsPreviousToken()
            && !allowNewlineImplicitExpressionListSeparator)
        {
            return false;
        }

        if (!CanStartExpression(Current.Kind))
            return false;

        // 'open' is a declaration even though it can begin a body line.
        if (Current.Kind == TokenKind.KeywordOpen)
            return false;

        // Property definition `Name = ...`, explicit output `Output = ...`,
        // clause definition `Name(pattern) = ...`, or comma deconstruction
        // assignment `x, *y, z = ...`. The algorithm loop owns these definition
        // forms, so they end any preceding implicit output expression list.
        if (Current.Kind == TokenKind.Identifier
            && (LookaheadIsEquals()
                || LookaheadIsBindingPatternAssignment()
                || LookaheadIsClauseDefinition()))
            return false;

        // Invalid-grace property definition `~Name = ...`; keep the targeted
        // grace diagnostic from the algorithm loop.
        if (Current.Kind == TokenKind.Tilde && LookaheadThroughTildesToPropertyDef())
            return false;

        return true;
    }

    private static bool CanStartExpression(TokenKind kind) => kind switch
    {
        TokenKind.Number
        or TokenKind.StringLiteral
        or TokenKind.Identifier
        or TokenKind.Minus
        or TokenKind.KeywordNot
        or TokenKind.Tilde
        or TokenKind.LParen
        or TokenKind.LBrace
        // '[' always starts a NEW list-literal expression; it is deliberately
        // absent from the continuation policy table, so `A[1]` is the
        // adjacency expression list `A, [1]` (indexing is ':', never brackets)
        // and `F[1]` is never a call form.
        or TokenKind.LBracket
        or TokenKind.KeywordOpen => true,
        _ => false,
    };

    // Star disambiguation needs the narrower set of tokens that can actually
    // begin a star's right operand. `open` is included above because the
    // algorithm parser recognizes it as a declaration starter, but ParsePrimary
    // always rejects it in expression position. This is the ONE classifier for
    // "a star could take this as its operand": it decides spread-marker versus
    // multiplication in IsPostfixSpreadMarkerStar, and it decides whether the
    // misplaced-prefix-star recovery in ParsePrimary has an operand to resume on.
    private static bool CanStartMultiplicationOperand(TokenKind kind)
        => CanStartExpression(kind) && kind != TokenKind.KeywordOpen;

    // ── Expression parsing (precedence climbing) ────────────────────────────
    //
    // Precedence levels:
    //   1: or            (logical or, left-associative)
    //   2: xor           (logical xor, left-associative)
    //   3: and           (logical and, left-associative)
    //   4: == !=         (equality, left-associative)
    //   5: < > <= >=     (comparison, left-associative)
    //   6: + -           (additive, left-associative)
    //   7: * / div mod   (multiplicative, left-associative)
    //   8: ^             (power, right-associative)
    //   9: - not         (unary prefix)
    //  10: . : call      (postfix)

    private Expr ParseExpression(int minPrecedence = 0)
    {
        // Also a recursion chokepoint: right-associative operators (notably `^`)
        // right-recurse through ParseExpression AFTER ParseUnary has returned the
        // operand, so the ParseUnary guard alone does not bound them.
        _nestingDepth++;
        try
        {
            GuardNestingDepth();
            return ParseExpressionCore(minPrecedence);
        }
        finally { _nestingDepth--; }
    }

    private Expr ParseExpressionCore(int minPrecedence = 0)
    {
        var lhs = minPrecedence <= 9 ? ParseUnary() : ParsePostfix();

        while (true)
        {
            var (prec, op) = GetBinaryOpInfo(Current.Kind);
            if (prec < minPrecedence) break;
            // A binary operator never continues a closed expression across a
            // physical newline (write the operator before the newline to
            // continue arithmetic: `A -` newline `1` is the subtraction).
            // Comments are invisible here: `A // note` newline `-1` breaks
            // exactly like `A` newline `-1` and joins as output adjacency.
            if (!MayContinueClosedExpression(Current.Kind)) break;

            var operatorToken = Advance(); // consume operator token

            // Right-associative: ^ uses prec (not prec+1) so 2^3^4 = 2^(3^4)
            var nextMin = op is BinaryOp.Pow ? prec : prec + 1;
            var rhs = ParseExpression(nextMin);
            // CreateBinaryExpression also rejects spread operands: a spread
            // expression is a whole expression-list slot, never a binary
            // operand (`A* + B`, `1 + values*`, and `value* * 2` are errors;
            // spread the whole expression instead: `(A + B)*`). This is also
            // the documented deterministic rejection for `value**next` /
            // `value** next`: the second star has a same-line right operand,
            // so it is multiplication whose left operand is a spread.
            lhs = CreateBinaryExpression(op, lhs, rhs, operatorToken);
        }

        return lhs;
    }

    /// <summary>
    /// Builds one binary node: rejects spread operands (with unwrap
    /// recovery), constructs, and applies the chain-depth guard. Kept out of
    /// <see cref="ParseExpressionCore"/> so its call temporaries never
    /// enlarge that hot recursive frame (native stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr CreateBinaryExpression(BinaryOp op, Expr lhs, Expr rhs, Token operatorToken)
    {
        lhs = RejectMisplacedSpreadOperand(lhs);
        rhs = RejectMisplacedSpreadOperand(rhs);
        var binary = new Expr.Binary(op, lhs, rhs) { Span = SpanFrom(lhs) };
        return GuardExpressionChainDepth(binary, TokenSpan(operatorToken), lhs, rhs);
    }

    private static (int Precedence, BinaryOp Op) GetBinaryOpInfo(TokenKind kind) => kind switch
    {
        TokenKind.KeywordOr => (1, BinaryOp.Or),
        TokenKind.KeywordXor => (2, BinaryOp.Xor),
        TokenKind.KeywordAnd => (3, BinaryOp.And),
        TokenKind.EqualEqual => (4, BinaryOp.Eq),
        TokenKind.BangEqual => (4, BinaryOp.Ne),
        TokenKind.LessThan => (5, BinaryOp.Lt),
        TokenKind.GreaterThan => (5, BinaryOp.Gt),
        TokenKind.LessEqual => (5, BinaryOp.Le),
        TokenKind.GreaterEqual => (5, BinaryOp.Ge),
        TokenKind.Plus => (6, BinaryOp.Add),
        TokenKind.Minus => (6, BinaryOp.Sub),
        TokenKind.Star => (7, BinaryOp.Mul),
        TokenKind.Slash => (7, BinaryOp.Div),
        TokenKind.KeywordDiv => (7, BinaryOp.IDiv),
        TokenKind.KeywordMod => (7, BinaryOp.Mod),
        TokenKind.Caret => (8, BinaryOp.Pow),
        _ => (-1, default),
    };

    // ── Unary ───────────────────────────────────────────────────────────────

    private Expr ParseUnary()
    {
        // Recursion chokepoint for ALL expression nesting: ParseExpression always
        // enters through ParseUnary, and `-`/`not` chains self-recurse here.
        _nestingDepth++;
        try
        {
            GuardNestingDepth();

            if (Current.Kind is TokenKind.Minus or TokenKind.KeywordNot)
            {
                // CreateUnaryExpression also rejects spread operands
                // (`-values*` is an error; spread the whole expression
                // instead: `(-values)*`).
                var start = Advance(); // consume '-' / 'not'
                return CreateUnaryExpression(start, ParseUnary());
            }
            return ParsePostfix();
        }
        finally { _nestingDepth--; }
    }

    /// <summary>
    /// Builds one prefix-unary node: rejects spread operands (with unwrap
    /// recovery) and constructs. Kept out of <see cref="ParseUnary"/> so its
    /// call temporaries never enlarge that hot recursive frame (native
    /// stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr CreateUnaryExpression(Token operatorToken, Expr operand)
    {
        operand = RejectMisplacedSpreadOperand(operand);
        var op = operatorToken.Kind == TokenKind.Minus ? UnaryOp.Minus : UnaryOp.Not;
        return new Expr.Unary(op, operand) { Span = MakeSpan(operatorToken) };
    }

    // ── Postfix (dot, colon, call) ──────────────────────────────────────────

    private Expr ParsePostfix()
    {
        var lhs = ParsePrimary();

        while (true)
        {
            switch (Current.Kind)
            {
                case TokenKind.Star when MayContinueClosedExpression(TokenKind.Star)
                    && IsPostfixSpreadMarkerStar():
                    // Postfix spread marker: expr* — the star is DIRECTLY
                    // attached to the completed expression's last token and
                    // has no valid same-line right operand after it. Every
                    // other same-line star is left for the multiplicative
                    // level (`a*b`, `a* b`, `a *b`, `a * b` all multiply, and
                    // `a *` newline `b` continues as multiplication), so
                    // spreading before another same-line supplied item
                    // requires a comma: `a*, b`. Each additional attached
                    // star adds one spread layer (`value**`).
                    var starToken = Advance(); // consume the spread marker '*'
                    lhs = CreateSpreadExpression(lhs, starToken);
                    break;

                case TokenKind.Colon when MayContinueClosedExpression(TokenKind.Colon):
                    // Index: expr : selector. Same-physical-line only — a
                    // newline never continues a closed expression into
                    // postfix indexing, mirroring the call-delimiter rule. A
                    // ':'-led line is rejected by ParsePrimary with a
                    // targeted diagnostic. A spread expression is never an
                    // indexing target or selector (`A*:0` reports
                    // SpreadSelectionDiagnostic, which distinguishes
                    // select-then-spread `(A:0)*` from capture-then-select
                    // `(A*):0`).
                    var colonToken = Advance(); // consume ':'
                    lhs = ParseIndexContinuation(lhs, colonToken);
                    break;

                case TokenKind.Dot when MayContinueClosedExpression(TokenKind.Dot):
                    // Dot-call syntax: expr.Name or expr.Name(args). The
                    // leading '.' is the one whitelisted postfix continuation
                    // that may cross a physical newline (method-chain layout)
                    // — encoded in the continuation policy table.
                    var dotToken = Advance(); // consume '.'
                    if (Current.Kind != TokenKind.Identifier)
                    {
                        ReportError("Expected property name after '.'.");
                        break;
                    }
                    var propNameToken = Current;
                    var propName = propNameToken.StringValue!;
                    var memberSpan = TokenSpan(propNameToken);
                    Advance(); // consume identifier

                    if (propName == "Output")
                        ReportOutputPropertyAccess(memberSpan);

                    if (lhs is Expr.SequenceSpread)
                    {
                        if (propName == "Output")
                        {
                            // The Output diagnostic above already flagged the
                            // form; recover by unwrapping the spread layers so
                            // no Call(Output, ...) or embedded spread survives,
                            // then fall through to the ordinary dot-call build.
                            while (lhs is Expr.SequenceSpread spreadLayer)
                                lhs = spreadLayer.Operand;
                        }
                        else
                        {
                            // Fluent supply transition: `operand*.Target(...)`
                            // consumes the spread items as the leading call
                            // arguments. Lowers to the ordinary lexical call
                            // `Target(operand*, ...)`.
                            lhs = ParseSpreadReceiverContinuation(lhs, dotToken, propNameToken, memberSpan);
                            break;
                        }
                    }

                    if (IsCallArgumentStart())
                    {
                        // expr.Name(args) → DotCall(expr, Name, args)
                        // Lean: dotCall : Expr → Ident → Option Algorithm → Expr
                        var args = ParseCallArgs();
                        var dotCall = new Expr.DotCall(lhs, propName, args)
                        {
                            Span = SpanFrom(lhs),
                            MemberSpan = memberSpan
                        };
                        lhs = GuardExpressionChainDepth(dotCall, TokenSpan(dotToken), lhs);
                    }
                    else
                    {
                        // expr.Name → DotCall(expr, Name, null)
                        var dotCall = new Expr.DotCall(lhs, propName)
                        {
                            Span = SpanFrom(lhs),
                            MemberSpan = memberSpan
                        };
                        lhs = GuardExpressionChainDepth(dotCall, TokenSpan(dotToken), lhs);
                    }
                    break;

                case TokenKind.LParen or TokenKind.LBrace
                    // A call delimiter continues the callable expression only on
                    // the same physical line: `F (1, 2)` is the call `F(1, 2)`,
                    // while `F` newline `(1, 2)` is the expression list `F, (1, 2)`.
                    // Multiline calls must open the delimiter before the newline
                    // (`F(` ... `)`); an already-open argument list spans lines
                    // normally. Non-callable targets (numbers, calls, blocks,
                    // operators) do not pass this gate, so `2 (3)` stays
                    // adjacency.
                    when (lhs is Expr.Resolve or Expr.DotCall or Expr.Grace)
                        && IsCallArgumentStart():
                    // Direct call: Name(args), Name~(args), or expr.Name(args) already handled above
                    // This handles: Name(args) → Call(Resolve(Name), args)
                    var callToken = Current;
                    var callArgs = ParseCallArgs();
                    // Hook for exact builtin direct-call argument rewrites. repeat/while
                    // init arguments stay intact so the evaluator can preserve explicit
                    // state-slot boundaries.
                    callArgs = MaybeLowerBuiltinDirectCallArgs(lhs, callArgs);
                    // Validate if arity.
                    ValidateIfArity(lhs, callArgs);
                    var call = new Expr.Call(lhs, callArgs) { Span = SpanFrom(lhs) };
                    lhs = GuardExpressionChainDepth(call, TokenSpan(callToken), lhs);
                    break;

                default:
                    return lhs;
            }
        }
    }

    /// <summary>
    /// Parses the `: selector` indexing continuation and builds the index
    /// node, rejecting spread expressions as target or selector. Kept out of
    /// <see cref="ParsePostfix"/> so its locals and call temporaries never
    /// enlarge that hot recursive frame (native stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParseIndexContinuation(Expr lhs, Token colonToken)
    {
        lhs = RejectMisplacedSpreadOperand(lhs, SpreadSelectionDiagnostic);
        var selector = RejectMisplacedSpreadOperand(ParsePrimary(), SpreadSelectionDiagnostic);
        var index = new Expr.Index(lhs, selector) { Span = SpanFrom(lhs) };
        return GuardExpressionChainDepth(index, TokenSpan(colonToken), lhs, selector);
    }

    /// <summary>
    /// True when the current same-line star is the postfix SPREAD marker for
    /// the just-completed expression rather than infix multiplication: the
    /// star must be DIRECTLY attached to the expression's last token
    /// (exact source-offset adjacency — whitespace, comments, and newlines
    /// all break attachment) AND no expression-start token may follow it on
    /// the star's own physical line. When a valid same-line right operand
    /// follows, the star is multiplication regardless of spacing; when the
    /// star is unattached, it is multiplication whose right operand may
    /// continue on the next line under ordinary operator continuation.
    /// Comments after the star are invisible, exactly like every other
    /// line-sensitive decision.
    /// </summary>
    private bool IsPostfixSpreadMarkerStar()
    {
        if (!IsDirectlyAttached(Previous, Current))
            return false;
        var next = PeekSignificant(1);
        return next.Line != Current.Line || !CanStartMultiplicationOperand(next.Kind);
    }

    /// <summary>
    /// Builds one spread node for an attached postfix `*` marker: rejects
    /// nothing (spread placement is validated by the consuming positions),
    /// records the exact spread-marker span, and applies the chain-depth
    /// guard. Kept out of <see cref="ParsePostfix"/> so its call temporaries
    /// never enlarge that hot recursive frame (native stack-margin
    /// calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr CreateSpreadExpression(Expr operand, Token starToken)
    {
        var spreadNode = CreateSequenceSpread(operand, SpanFrom(operand), TokenSpan(starToken));
        return GuardExpressionChainDepth(spreadNode, TokenSpan(starToken), operand);
    }

    /// <summary>
    /// Parses the dot continuation after a spread expression — the fluent
    /// supply-transition form <c>operand*.Target(...)</c>. The spread
    /// receiver is an item SUPPLY, not a value, so <c>.Target</c> is not
    /// property access on the spread and structural receiver lookup never
    /// applies: the form lowers at parse time to the ordinary lexical call
    /// <c>Target(operand*, ...)</c> with the spread as the leading
    /// argument slot — the exact AST the non-fluent spelling builds — so
    /// both spellings share one evaluation path and the operand is
    /// evaluated exactly once. Further postfix continuations chain on the
    /// call result (<c>x.Calculate*.Target.Other</c>).
    /// Kept OUT of <see cref="ParsePostfix"/> so its locals and call
    /// temporaries never enlarge that hot recursive frame — the parser's
    /// nesting budget is calibrated against the native stack boundary.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParseSpreadReceiverContinuation(
        Expr spreadReceiver, Token dotToken, Token memberToken, SourceSpan memberSpan)
    {
        var callee = new Expr.Resolve(memberToken.StringValue!) { Span = memberSpan };

        Algorithm args;
        if (IsCallArgumentStart())
        {
            var parsedArgs = ParseCallArgs();
            args = parsedArgs is Algorithm.User userArgs
                ? userArgs with { Output = [spreadReceiver, .. userArgs.Output] }
                : new Algorithm.User(
                    Parent: null, Parameters: [], Opens: [],
                    Properties: [], Output: [spreadReceiver]);
        }
        else
        {
            args = new Algorithm.User(
                Parent: null, Parameters: [], Opens: [],
                Properties: [], Output: [spreadReceiver]);
        }

        // The leading spread argument slot always defers `if` arity to the
        // evaluator's spread expansion, exactly like `if(X*)`.
        ValidateIfArity(callee, args);
        var call = new Expr.Call(callee, args) { Span = SpanFrom(spreadReceiver) };
        return GuardExpressionChainDepth(call, TokenSpan(dotToken), spreadReceiver);
    }

    // A '(' or '{' starts call arguments only when it appears on the same
    // physical line as the callable expression's last token. Same-line
    // whitespace continues a call (`F (1, 2)`, `A.B (1)`, `values.map { ... }`);
    // a physical newline never continues a closed expression into a call
    // (`F` newline `(1, 2)` is the expression list `F, (1, 2)`). Multiline calls
    // must open the delimiter before the newline; an already-open argument
    // list or brace block spans lines normally.
    private bool IsCallArgumentStart()
        => Current.Kind is TokenKind.LParen or TokenKind.LBrace
            && MayContinueClosedExpression(Current.Kind);

    /// <summary>
    /// Parses call arguments: <c>(algorithm)</c> or <c>{algorithm}</c>.
    /// Ordinary parentheses still mean ordinary parenthesized expression syntax. For scalar and other
    /// single-expression cases, <c>((expr))</c> behaves like <c>(expr)</c>.
    /// When the inner parenthesized expression is itself a non-parametrized block
    /// value, the parser preserves the extra outer layer so dot-call receiver
    /// normalization can distinguish <c>(1, 2).count</c> from
    /// <c>((1, 2)).count</c> without changing ordinary evaluation.
    /// </summary>
    private Algorithm ParseCallArgs()
    {
        if (Current.Kind == TokenKind.LParen)
        {
            Advance(); // consume '('
            var alg = ParseAlgorithm(isParametrized: false);
            Expect(TokenKind.RParen);
            return alg;
        }
        else
        {
            // Trailing brace-block: Algo{e} → Algo({e})
            // The brace content is a parametrized algorithm that becomes a single
            // Expr.Block argument inside a non-parametrized wrapper, so the block
            // is resolvable as an algorithm by ResolveAlg(.block ...).
            var start = Current;
            Advance(); // consume '{'
            var innerAlg = ParseAlgorithm(isParametrized: true);
            Expect(TokenKind.RBrace);
            var blockExpr = new Expr.Block(innerAlg) { Span = MakeSpan(start) };
            return new Algorithm.User(
                Parent: null, Parameters: [], Opens: [],
                Properties: [], Output: [blockExpr]);
        }
    }

    // ── Primary expressions ─────────────────────────────────────────────────

    // A bare expression group is a non-parametrized parenthesized algorithm with
    // no declarations — just an expression list. Empty/empty-nested groups in this
    // shape construct empty sequence values.
    private static bool IsBareExpressionGroup(Algorithm alg)
        => alg is Algorithm.User { Parameters.Count: 0, Opens.Count: 0, Properties.Count: 0 };

    private static bool ShouldUnwrapParenthesizedPrimary(Algorithm alg)
    {
        if (alg.Properties.Count != 0 || alg.Output.Count != 1)
            return false;

        return alg.Output[0] switch
        {
            Expr.SequenceConstruct => false,
            Expr.SequenceSpread => false,
            Expr.EmptySequence => false,
            // A parenthesized reference keeps its block layer so sequence dot-call
            // receiver normalization can observe `(items).builtin` vs the bare name.
            Expr.Resolve => false,
            Expr.Block(var innerAlg) => innerAlg.IsParametrized,
            _ => true,
        };
    }

    private Expr ParsePrimary()
    {
        switch (Current.Kind)
        {
            case TokenKind.Number:
                {
                    var token = Advance();
                    return new Expr.Num(token.NumValue) { Span = TokenSpan(token) };
                }

            case TokenKind.StringLiteral:
                {
                    var token = Advance();
                    return new Expr.StringLiteral(token.StringValue ?? "") { Span = TokenSpan(token) };
                }

            case TokenKind.Identifier:
                {
                    var token = Advance();
                    // Postfix grace '~' is same-physical-line only: a '~'-led
                    // line is a prefix-grace expression of its own, never a
                    // continuation of the previous line's identifier.
                    if (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
                    {
                        var weight = 0;
                        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
                        {
                            Advance();
                            weight++;
                        }
                        return new Expr.Grace(
                            new Expr.Resolve(token.StringValue!) { Span = TokenSpan(token) },
                            weight)
                        { Span = MakeSpan(token) };
                    }
                    return new Expr.Resolve(token.StringValue!) { Span = TokenSpan(token) };
                }

            case TokenKind.Tilde:
                {
                    // Prefix grace: each ~ decrements weight
                    var startToken = Current;
                    var weight = 0;
                    while (Current.Kind == TokenKind.Tilde)
                    {
                        Advance();
                        weight--;
                    }
                    if (Current.Kind != TokenKind.Identifier)
                    {
                        ReportError("Expected identifier after '~'.");
                        Advance(); // skip for recovery
                        return new Expr.Num(0) { Span = MakeSpan(startToken) };
                    }
                    var graceToken = Advance();
                    // Postfix grace: each same-line ~ after the identifier
                    // increments weight; a '~' on a later line never continues.
                    while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
                    {
                        Advance();
                        weight++;
                    }
                    var resolve = new Expr.Resolve(graceToken.StringValue!) { Span = TokenSpan(graceToken) };
                    return weight == 0 ? resolve : new Expr.Grace(resolve, weight) { Span = MakeSpan(startToken) };
                }

            case TokenKind.LParen:
                {
                    var start = Current;
                    Advance(); // consume '('
                    var alg = ParseAlgorithm(isParametrized: false);
                    Expect(TokenKind.RParen);

                    // Empty parentheses `()` construct the empty sequence value.
                    // Repeated ordinary parentheses around it are redundant grouping
                    // and canonicalize to the same empty sequence value.
                    if (IsBareExpressionGroup(alg))
                    {
                        if (alg.Output.Count == 0)
                            return new Expr.EmptySequence(0) { Span = MakeSpan(start) };
                        if (alg.Output.Count == 1 && alg.Output[0] is Expr.EmptySequence)
                            return new Expr.EmptySequence(0) { Span = MakeSpan(start) };
                    }

                    // Ordinary parenthesized expressions usually unwrap to the inner
                    // expression. Preserve an extra non-parametrized block layer so
                    // sequence dot-call receiver normalization can observe
                    // `(items).builtin` vs `((items)).builtin`.
                    if (ShouldUnwrapParenthesizedPrimary(alg))
                        return alg.Output[0];

                    return new Expr.Block(alg) { Span = MakeSpan(start) };
                }

            case TokenKind.LBrace:
                {
                    var start = Current;
                    Advance(); // consume '{'
                    var alg = ParseAlgorithm(isParametrized: true);
                    Expect(TokenKind.RBrace);
                    return new Expr.Block(alg) { Span = MakeSpan(start) };
                }

            case TokenKind.LBracket:
                {
                    // Exact immutable list literal `[e1, ..., en]`. The bracket
                    // content is a pure expression list (spread slots included) —
                    // never an algorithm context, so declarations are not legal
                    // inside brackets and `[]`/`[x]`/`[[x]]` all stay distinct
                    // (no `()`-style canonicalization or singleton unwrap).
                    // An already-open '[' spans physical lines like '(' and '{'.
                    var start = Current;
                    Advance(); // consume '['
                    List<Expr> items = Current.Kind == TokenKind.RBracket
                        ? []
                        : ParseExpressionListOperand(allowNewlineImplicitExpressionListSeparator: true);
                    Expect(TokenKind.RBracket);
                    return new Expr.ListLiteral(items) { Span = MakeSpan(start) };
                }

            case TokenKind.KeywordOpen:
                {
                    var token = Current;
                    ReportError("'open' is a declaration and cannot be used in expression position.");
                    Advance(); // skip for recovery
                    return new Expr.Num(0) { Span = TokenSpan(token) }; // error placeholder
                }

            case TokenKind.Star:
                {
                    // A prefix '*' reaching expression position is the collect
                    // marker used outside a binding pattern (`x = *values`,
                    // `F(*items)` as a call) or a stray star with no left
                    // operand. Report once for the whole star run, then recover
                    // with the following same-line operand where possible so
                    // `x = *values` degrades to `x = values` and later
                    // declarations keep parsing.
                    var starToken = Current;
                    ReportError(CollectMarkerInExpressionDiagnostic, TokenSpan(starToken));
                    Advance(); // consume '*'
                    while (Current.Kind == TokenKind.Star)
                        Advance(); // consume a malformed star run whole, one diagnostic

                    if (CanStartMultiplicationOperand(Current.Kind)
                        && IsSamePhysicalLineAsPreviousToken())
                        return ParseUnary(); // recovery: the operand the star was attached to

                    return new Expr.Num(0) { Span = TokenSpan(starToken) }; // error placeholder
                }

            case TokenKind.Semicolon:
                {
                    var token = Current;
                    ReportUnsupportedSemicolon(token);
                    Advance(); // skip for recovery
                    return new Expr.Num(0) { Span = TokenSpan(token) };
                }

            case TokenKind.Colon:
                {
                    // A ':' reaching primary position has no expression to index.
                    // The common cause is a line starting with ':' — indexing is
                    // postfix and same-line only.
                    var token = Current;
                    ReportError("Unexpected ':'. Indexing is postfix and must follow the indexed expression on the same physical line, as in 'Pair:0'.");
                    Advance(); // skip for recovery
                    return new Expr.Num(0) { Span = TokenSpan(token) }; // error placeholder
                }

            default:
                {
                    var token = Current;
                    ReportError($"Unexpected token: '{Current.Kind}'.");
                    Advance(); // skip for recovery
                    return new Expr.Num(0) { Span = TokenSpan(token) }; // error placeholder
                }
        }
    }

    /// <summary>
    /// Parser hook for exact builtin direct-call argument lowering.
    /// repeat/while initial-state arguments are intentionally left intact here:
    /// the evaluator preserves each explicit init argument as one state slot.
    /// </summary>
    private static Algorithm MaybeLowerBuiltinDirectCallArgs(Expr callee, Algorithm args)
        => args;

    /// <summary>
    /// Validates that <c>if(...)</c> has exactly 3 arguments.
    /// For non-<c>if</c> callees, does nothing.
    /// When any top-level argument slot is an explicit spread
    /// (<c>expr*</c>), the expanded argument count is only known at
    /// evaluation time, so this static gate is skipped and the evaluator's
    /// spread expansion decides arity — exactly like every other builtin.
    /// This keeps direct <c>if(X*)</c> consistent with a user wrapper such
    /// as <c>MyIF(a, b, c) = if(a, b, c)</c> called as <c>MyIF(X*)</c>.
    /// Without a spread the friendly parse-time diagnostic is preserved, so
    /// <c>if(X)</c>, <c>if(1, 2)</c>, and <c>if()</c> still fail here.
    /// </summary>
    private void ValidateIfArity(Expr callee, Algorithm args)
    {
        if (callee is Expr.Resolve("if"))
        {
            if (args.Output.Any(static arg => arg is Expr.SequenceSpread))
                return;

            var argCount = args.Output.Count;
            if (argCount != 3)
            {
                ReportError($"Builtin 'if' expects 3 arguments: condition, whenTrue, whenFalse. Got {argCount}.");
            }
        }
    }

