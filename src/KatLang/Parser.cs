        "A spread expression contributes items to the surrounding item supply and cannot be used as a scalar operand. Spread the whole expression instead, e.g. `(A + B)*`.";

    /// <summary>
    /// The <see cref="MisplacedSpreadDiagnostic"/> variant for `A *` newline `B*`: the
    /// first line's final `*` is DETACHED from its left operand, so it is multiplication
    /// that leaves the expression incomplete (issue #183: a line-final star is classified
    /// by attachment), and the second line's spread became its scalar right operand.
    /// Names the cause and the two repairs: attach the marker for a spread row, or drop
    /// the right operand's marker for multiplication.
    /// </summary>
    private const string LineFinalStarContinuationDiagnostic =
        "The `*` ending an earlier line is separated from its left operand, so it is multiplication that continued onto this line, making this spread expression its right operand. A spread cannot be a scalar operand. For separate spread rows, attach the marker to its operand (`A*`). For multiplication, remove the right operand's spread marker (`A * B`); the operands may be on different lines.";

    /// <summary>
    /// Rejects a spread expression used as an operand of a larger expression
    /// (a unary, binary or comparison operand, or a whole interpolation hole). Spread
    /// is legal only as a whole expression-list slot — a selector slot of a postfix
    /// selection included (<c>Data[Indexes*]</c>) — as the operand of another spread, or
    /// as the fluent dot-chain receiver (which lowers to a call). Recovery
    /// unwraps to the innermost non-spread operand so no embedded
    /// SequenceSpread survives in the recovered tree — downstream layers
    /// keep the slot-level-only spread invariant.
    /// </summary>
    private Expr RejectMisplacedSpreadOperand(Expr expr, string diagnostic = MisplacedSpreadDiagnostic)
    {
        if (expr is not Expr.SequenceSpread spread)
            return expr;

        if (spread.Span is { } span)
            ReportError(DiagnosticCode.MisplacedSpread, diagnostic, span);
        else
            ReportError(DiagnosticCode.MisplacedSpread, diagnostic);

        var operand = spread.Operand;
        while (operand is Expr.SequenceSpread inner)
            operand = inner.Operand;
        return operand;
    }

    private readonly record struct BindingTarget(
        string Name,
        ParameterKind Kind,
        SourceSpan NameSpan,
        SourceSpan? CollectMarkerSpan);

    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private static BindingTarget BindingTargetAt(string name, ParameterKind kind, Token nameToken, Token? collectMarkerToken)
        => new(name, kind, nameToken.Span, collectMarkerToken?.Span);

    // Last FAILED binding-pattern scan: [start, break) with the breaking token
    // index exclusive. Sound to reuse because the scan is a forward DFA over the
    // immutable token stream (indexed absolutely; the parser only advances):
    // every identifier/star position strictly inside a
    // failed region is a binding-name/collect-marker position of that same
    // failed scan, so a fresh scan from it follows the identical transitions to
    // the identical breaking token and fails the same way. (A success cannot
    // hide inside a failed region: accepting at an interior `=` needs a comma
    // or collect marker before it, which the ORIGINAL scan — having traversed
    // at least as much of the region — also had, so it would have accepted
    // there too.) The breaking token itself is excluded: a scan STARTING at it
    // is a different parse (`a b, c = 1` fails from `a` at `b`, succeeds from
    // `b`). The memo only ever short-circuits a FALSE answer, and it is what
    // keeps repeated boundary checks over one identifier-comma run linear —
    // without it, every target of the multiline continuation `open a1,`
    // newline `a2,` newline ... newline `an` would rescan the remaining run,
    // turning that long open list quadratic.
    private int _bindingPatternScanFailStart = -1;
    private int _bindingPatternScanFailBreak = -1;

    /// <summary>
    /// Checks whether the tokens at the current position form a deconstruction
    /// assignment with identifier targets. A plain single <c>name =</c> is left
    /// to the ordinary property path; <c>*name =</c> is the unambiguous
    /// lone-collecting-binding form. The prefix collect marker must be
    /// directly attached to its binding name; the scan is deliberately
    /// TOLERANT of malformed marker shapes (a gap after the star, or a
    /// repeated star) so <see cref="ParseBindingPatternAssignment"/> can
    /// report the targeted attachment/malformed diagnostics — validity is
    /// enforced during parsing, never here. Targets are identifiers with an
    /// optional leading star run; anything else falls through to ordinary
    /// expression parsing.
    /// </summary>
    private bool LookaheadIsBindingPatternAssignment()
        => LookaheadIsBindingPatternAssignmentFrom(NextSignificantIndex(_pos));

    /// <summary>
    /// Index form of <see cref="LookaheadIsBindingPatternAssignment"/>: the
    /// same memoized scan, started at the significant token at
    /// <paramref name="start"/>.
    /// </summary>
    private bool LookaheadIsBindingPatternAssignmentFrom(int start)
    {
        if (start >= _bindingPatternScanFailStart && start < _bindingPatternScanFailBreak)
            return false;

        // The declaration-head line rule (IsHeadToken): the whole binding-pattern
        // head — stars, names, commas, and the '=' — shares the first token's
        // physical line. The scan fails at the first token on a later line, so
        // the failed-region memo below stays sound: every start inside the
        // region lies on that same line and would fail at the same token.
        var headLine = _tokens[start].Line;
        var index = start;
        var sawComma = false;
        var sawCollectMarker = false;

        while (true)
        {
            // Optional prefix collect-marker star run before the binding name.
            while (_tokens[index].Kind == TokenKind.Star && IsHeadToken(index, headLine))
            {
                sawCollectMarker = true;
                index = NextSignificantIndex(index + 1);
            }

            if (_tokens[index].Kind != TokenKind.Identifier || !IsHeadToken(index, headLine))
                return FailBindingPatternScan(start, index);
            index = NextSignificantIndex(index + 1);

            if (!IsHeadToken(index, headLine))
                return FailBindingPatternScan(start, index);

            switch (_tokens[index].Kind)
            {
                case TokenKind.Comma:
                    sawComma = true;
                    index = NextSignificantIndex(index + 1);
                    continue;
                case TokenKind.Equals:
                    return sawComma || sawCollectMarker
                        || FailBindingPatternScan(start, index);
                default:
                    return FailBindingPatternScan(start, index);
            }
        }
    }

    /// <summary>Records the failed scan region for the memo above; always false.</summary>
    private bool FailBindingPatternScan(int start, int breakIndex)
    {
        _bindingPatternScanFailStart = start;
        _bindingPatternScanFailBreak = breakIndex;
        return false;
    }

    /// <summary>
    /// Parses a deconstruction assignment <c>x, *y, z = RHS</c>. The
    /// lone-collecting-binding form <c>*items = RHS</c> is also supported. The right-hand side
    /// is evaluated once and its items are bound to the targets by the shared
    /// deconstruction matcher, with one optional movable collecting binding that COLLECTS
    /// its assigned items as one list (the evaluator's collector cell, <c>Evaluator.CollectorCell</c>).
    /// A malformed marker shape (a gap between the star and its name, or a
    /// repeated star) reports a targeted diagnostic and binds the name as an
    /// ordinary fixed target — malformed recovery never creates a collecting
    /// binding.
    /// <paramref name="declarationsAllowed"/> is the enclosing body context
    /// (see <see cref="ParseAlgorithmBodyParts"/>): deconstruction declares
    /// properties, so inside a parenthesized body the binding pattern reports
    /// the property-in-parentheses diagnostic. <paramref name="writtenRowIndex"/> is the
    /// number of output rows the enclosing body has written so far — the structural
    /// written-order key of the hoisted right-hand side
    /// (<see cref="Algorithm.User.AssignmentDeconstructionRowIndex"/>).
    /// </summary>
    private void ParseBindingPatternAssignment(
        List<Property> properties,
        Dictionary<string, ClauseGroupBuilder> clauseGroups,
        HashSet<string> declaredPropertyNames,
        bool declarationsAllowed,
        int writtenRowIndex)
    {
        var targets = new List<BindingTarget>();
        while (true)
        {
            // Optional prefix collect-marker star run (the lookahead is
            // tolerant; exactly one directly attached star is valid syntax).
            Token? firstStarToken = null;
            var starCount = 0;
            while (Current.Kind == TokenKind.Star)
            {
                var starToken = Advance();
                firstStarToken ??= starToken;
                starCount++;
            }

            var nameToken = Current; // Identifier, guaranteed by the lookahead
            var name = nameToken.StringValue!;
            Advance(); // consume identifier

            var isCollectingBinding = false;
            Token? collectMarkerToken = null;
            if (starCount == 1 && IsDirectlyAttached(firstStarToken!, nameToken))
            {
                isCollectingBinding = true;
                collectMarkerToken = firstStarToken;
            }
            else if (starCount == 1)
            {
                ReportErrorAcross(
                    DiagnosticCode.InvalidCollectMarker,
                    CollectMarkerAttachmentDiagnostic(name),
                    firstStarToken!, nameToken);
            }
            else if (starCount > 1)
            {
                ReportErrorAcross(
                    DiagnosticCode.InvalidCollectMarker,
                    RepeatedCollectMarkerDiagnostic(name),
                    firstStarToken!, nameToken);
            }

            var kind = isCollectingBinding ? ParameterKind.Collecting : ParameterKind.Normal;
            targets.Add(BindingTargetAt(name, kind, nameToken, collectMarkerToken));

            if (Current.Kind == TokenKind.Comma)
            {
                Advance(); // consume ','
                continue;
            }

            break;
        }

        if (!declarationsAllowed)
        {
            // The span covers the whole binding pattern, first marker/name
            // through the last binding name.
            var first = targets[0];
            ReportError(
                DiagnosticCode.DeclarationInParentheses,
                PropertyDeclarationInParenthesesDiagnostic,
                CombineSpans(first.CollectMarkerSpan ?? first.NameSpan, targets[^1].NameSpan));
        }

        Expect(TokenKind.Equals);
        var rhsBody = ParseOutputLine(preserveWrittenBlock: true);

        if (targets.Count(static target => target.Kind == ParameterKind.Collecting) > 1)
        {
            // The first collecting binding stays the diagnostic subject; its
            // span covers the whole `*name`, marker included.
            var firstCollecting = targets
                .First(static target => target.Kind == ParameterKind.Collecting);
            ReportError(
                DiagnosticCode.InvalidCollectingBinding,
                "A deconstruction binding pattern may contain at most one collecting binding (`*name`).",
                CombineSpans(firstCollecting.CollectMarkerSpan, firstCollecting.NameSpan) ?? firstCollecting.NameSpan);

            // The recovered pattern keeps that first collecting binding; every later
            // one becomes an ordinary fixed target, so the synthetic shared pattern
            // never carries a shape a valid deconstruction cannot have (see
            // KeepFirstCollectingBindingPerLevel for clause heads).
            var sawCollecting = false;
            for (var i = 0; i < targets.Count; i++)
            {
                if (targets[i].Kind != ParameterKind.Collecting)
                    continue;
                if (sawCollecting)
                    targets[i] = targets[i] with { Kind = ParameterKind.Normal, CollectMarkerSpan = null };
                sawCollecting = true;
            }
        }

        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var target in targets)
        {
            if (!seen.Add(target.Name)
                || declaredPropertyNames.Contains(target.Name)
                || clauseGroups.ContainsKey(target.Name))
            {
                ReportError(
                    DiagnosticCode.DuplicateProperty,
                    $"Property '{target.Name}' is already defined.",
                    target.NameSpan);
            }
        }

        AddDeconstructionProperties(targets, rhsBody, properties, declaredPropertyNames, writtenRowIndex);
    }

    /// <summary>
    /// Elaborates a deconstruction pattern into properties. The right-hand side is
    /// hoisted into one synthetic shared property (evaluated once), and each target
    /// becomes a property whose body applies an inline helper to that shared source,
    /// returning its own bound name. Assignment deconstruction is the UNPACKING
    /// RECEIVER, not a written structural pattern: every helper's single parameter
    /// pattern is ONE shared <see cref="UnpackingParameterPattern"/> over the written
    /// targets, which demands the right-hand side as an ordinary VALUE (so a right-hand
    /// side without output is that missing output) and binds the targets as one flat
    /// pattern list (fixed prefix and suffix, at most one collector) against its
    /// ONE-LEVEL items: a lone sequence or list value is opened one level and any other
    /// value is one item (Python-style: <c>x, y, z = A</c> splits a stored sequence or
    /// list <c>A</c>, and <c>x, *rest = 1</c> binds <c>rest = []</c>). It has no delimiter
    /// that could select a value kind, so it opens both kinds alike; the kind-specific
    /// structural patterns never do. Explicit <c>x, y, z = A*</c> supplies the same items.
    /// This unpacking is deconstruction-specific and does not change ordinary calls,
    /// which still pass <c>A</c> as one argument unless <c>A*</c> is written.
    /// Synthetic constructs carry no source spans; only the target property names are
    /// source-backed declarations. The collect-marker metadata is the one additional
    /// source-backed syntax span retained on the synthetic binding pattern.
    /// </summary>
    private void AddDeconstructionProperties(
        IReadOnlyList<BindingTarget> targets,
        Algorithm rhsBody,
        List<Property> properties,
        HashSet<string> declaredPropertyNames,
        int writtenRowIndex)
    {
        var sourceName = $"$deconstruct${_deconstructionCounter++}";
        // The hoisted right-hand side is marked with its written position so the front end
        // elaborates its rows as rows of the enclosing body, in written order (see
        // Algorithm.User.AssignmentDeconstructionRowIndex).
        properties.Add(new Property(
            sourceName,
            rhsBody is Algorithm.User rhsUser
                ? rhsUser with { AssignmentDeconstructionRowIndex = writtenRowIndex }
                : rhsBody));
        declaredPropertyNames.Add(sourceName);

        var captures = targets
            .Select(static target => (ParameterPattern)new CaptureParameterPattern(
                new ParameterDeclaration(target.Name, Span: null, target.Kind)
                {
                    CollectMarkerSpan = target.CollectMarkerSpan,
                }))
            .ToList();
        // Every target helper shares ONE explicit pattern list holding ONE unpacking receiver
        // over the N written targets. Parameters/Params derive from it on demand, so
        // constructing a helper is O(1) in the capture count, and every walker meets the one
        // shared receiver node once.
        IReadOnlyList<ParameterPattern> helperPatterns = [new UnpackingParameterPattern(captures)];

        // One identity token shared by every target helper of this deconstruction. The evaluator
        // keys its run-scoped shared-bind cache on it so the N helpers bind the shared N-capture
        // pattern once per binding context instead of once per demanded target (O(N) not O(N^2)).
        var deconstructionGroup = new AssignmentDeconstructionGroup(helperPatterns);

        for (var targetIndex = 0; targetIndex < targets.Count; targetIndex++)
        {
            var target = targets[targetIndex];

            var helper = new Algorithm.User(
                Parent: null,
                ParameterPatterns: helperPatterns,
                Opens: [],
                Properties: [],
                Output: [new Expr.Resolve(target.Name)])
            {
                HasExplicitParameterList = true,
                AssignmentDeconstructionTarget = new AssignmentDeconstructionTarget(deconstructionGroup, targetIndex),
            };

            OutputBundle args = [new Expr.Resolve(sourceName)];

            var propertyBody = new Algorithm.User(
                Parent: null,
                ParameterPatterns: [],
                Opens: [],
                Properties: [],
                Output: [new Expr.Call(new Expr.AlgorithmExpr(helper), args)]);

            properties.Add(new Property(target.Name, propertyBody)
            {
                DeclarationSpans = [target.NameSpan]
            });
            declaredPropertyNames.Add(target.Name);
        }
    }

    /// <summary>
    /// Exact source-offset adjacency: <paramref name="second"/> starts at the
    /// code unit where <paramref name="first"/> ends, with nothing — no
    /// whitespace, comment, or newline — between them. This is the ONE
    /// attachment test of the marker attachment law: the prefix collect
    /// marker to its binding name (`*name`), the postfix spread marker to
    /// its operand's last token (`value*`, checked only after the star has
    /// been classified as a spread — see <see cref="IsPostfixSpreadMarkerStar"/>
    /// and <see cref="ParseSpreadMarkerContinuation"/>), every Grace marker
    /// to the name or neighbouring marker it belongs to (`~x`, `x~`), and the
    /// `.~` member-Grace pair, and the attached prefix unary-minus role.
    /// Ordinary binary operators never consult it.
    /// </summary>
    private static bool IsDirectlyAttached(Token first, Token second)
        => second.Position == first.Position + first.Length;

    /// <summary>
    /// The one written-Grace law: `~` decorates exactly one bare
    /// parameter/name occurrence (`~x` / `x~`). Every other operand shape —
    /// prefix on a non-name, and a postfix run after a completed compound
    /// expression such as `(x + y)~`, `f(x)~`, `x.y~`, `[x]~`, or `5~` —
    /// reports this diagnostic.
    /// </summary>
    private const string GraceEligibilityMessage =
        "Grace `~` can only be applied to a parameter or name occurrence.";

    /// <summary>
    /// The marker attachment law for Grace: every marker of a prefix run is
    /// directly attached to the next marker or to the name, and every marker
    /// of a postfix run to the name or to the previous marker (`~x`, `x~`,
    /// `~~x`, `~x~`). A gap anywhere in the occurrence (`~ x`, `x ~`,
    /// `~ ~x`) reports this diagnostic once, over the whole occurrence, and
    /// the recovered tree keeps the plain name: a detached marker decorates
    /// nothing, mirroring the collect marker's never-a-collecting-binding
    /// recovery.
    /// </summary>
    private static string GraceMarkerAttachmentDiagnostic(string name) =>
        $"The Grace marker `~` must be directly attached to the name it decorates: write `~{name}` or `{name}~`.";

    /// <summary>
    /// Consumes one same-line postfix Grace run after a bare name (the name
    /// token already consumed, <paramref name="lastToken"/> being the name or
    /// the last marker consumed so far), accumulating <paramref name="weight"/>
    /// and clearing <paramref name="attached"/> at the first gap. Returns the
    /// last consumed token so callers can span their diagnostics.
    /// </summary>
    private Token ConsumePostfixGraceRun(Token lastToken, ref int weight, ref bool attached)
    {
        var detachedPostfix = false;
        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
        {
            detachedPostfix |= !IsDirectlyAttached(lastToken, Current);
            attached &= !detachedPostfix;
            lastToken = Advance();
            weight++;
        }

        // Only a malformed POSTFIX run owns the following boundary (`x ~ y`).
        // A detached prefix has already recovered its name (`~ x`), so a later
        // item in `~ x y` still needs its own separator diagnostic at `y`.
        if (detachedPostfix)
            OwnSameLineItem(Current);

        return lastToken;
    }

    /// <summary>
    /// Builds the graced occurrence of a bare
    /// name, or reports the attachment law and recovers to the plain name when
    /// any marker of the occurrence was detached. Kept out of
    /// <see cref="ParsePrimary"/> so its locals never enlarge that hot
    /// recursive frame (native stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr CreateGracedName(Token firstToken, Token nameToken, Token lastToken, int weight, bool attached)
    {
        var resolve = ResolveAt(nameToken);
        if (!attached)
        {
            ReportErrorAcross(
                DiagnosticCode.InvalidGraceMarker,
                GraceMarkerAttachmentDiagnostic(nameToken.StringValue!),
                firstToken, lastToken);
            return resolve;
        }

        // Cancelling written markers still need the binding-effectiveness check.
        // A genuinely unmarked name stays plain; elaboration strips every marker.
        return firstToken == nameToken && lastToken == nameToken
            ? resolve
            : GraceFrom(resolve, weight, firstToken);
    }

    /// <summary>
    /// Parses the same-line postfix Grace run after an already-consumed bare
    /// name (`x~`, `x~~`): the postfix half of the one-name Grace law, with
    /// the attachment law enforced by <see cref="CreateGracedName"/>. Kept out
    /// of <see cref="ParsePrimary"/> so its locals never enlarge that hot
    /// recursive frame (native stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParsePostfixGraceOnName(Token nameToken)
    {
        var weight = 0;
        var attached = true;
        var lastToken = ConsumePostfixGraceRun(nameToken, ref weight, ref attached);
        return CreateGracedName(nameToken, nameToken, lastToken, weight, attached);
    }

    /// <summary>
    /// Reports the one-name Grace law for a same-line postfix marker run that
    /// follows a completed COMPOUND operand, consuming exactly that run. A
    /// bare name consumes its own postfix run in <see cref="ParsePrimary"/>,
    /// so a run reaching <see cref="ParsePostfix"/> is never eligible. The
    /// run is physical-line-local: it starts at the current marker (already
    /// proven to be on the operand's line) and stops before the first token
    /// on a later line, so a marker that begins the next row is never
    /// consumed here and the caller resumes on whatever follows — an
    /// ordinary dot edge, a same-line operand (a recovery-owned item that the
    /// separator rule does not report again), or the next row. The
    /// diagnostic spans the run itself, first marker through last. Kept out
    /// of <see cref="ParsePostfix"/> so its locals never enlarge that hot
    /// recursive frame (native stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private void RejectPostfixGraceRunOnCompoundOperand()
    {
        var firstTilde = Current;
        var lastTilde = firstTilde;
        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
            lastTilde = Advance();
        ReportErrorAcross(
            DiagnosticCode.InvalidGraceMarker,
            GraceEligibilityMessage,
            firstTilde, lastTilde);
        // The rejected run owns the boundary after it: `f(x)~ c` reports the
        // Grace law once and leaves `c` as a recovery-owned item, never a
        // second separator-rule diagnostic.
        OwnSameLineItem(Current);
    }

    /// <summary>
    /// Parses a `~`-led primary: prefix Grace on the ONE bare name that
    /// follows the marker run on the run's own physical line, then any
    /// same-line postfix markers after that name (`~x~` nets to weight 0 and
    /// retains its marker until effectiveness validation). The whole run is physical-line-local — a
    /// marker on a later line is never consumed as part of this run, and a
    /// name on a later line never becomes its operand — so `~` newline `~a`
    /// reports the first line's lone marker and leaves `~a` intact as the next
    /// row's own prefix-grace expression. A run not followed by a same-line
    /// name reports the one-name Grace law over the run (first marker
    /// through last). Recovery consumes nothing beyond the run: the token
    /// after it — on this line or the next — is left for ordinary parsing
    /// (`F(1)~` newline `-1` keeps a `-1` row, never a `1` row), and the
    /// consumed run itself is the progress that keeps the caller moving; the
    /// placeholder operand carries the run's span.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParsePrefixGracePrimary()
    {
        var firstTilde = Current;
        var lastTilde = Advance(); // the run always owns its first marker
        var weight = -1;
        // The attachment law (GraceMarkerAttachmentDiagnostic): every marker
        // is directly attached to the next marker or to the name.
        var attached = true;
        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
        {
            attached &= IsDirectlyAttached(lastTilde, Current);
            lastTilde = Advance();
            weight--;
        }

        if (Current.Kind != TokenKind.Identifier || !IsSamePhysicalLineAsPreviousToken())
        {
            ReportErrorAcross(
                DiagnosticCode.InvalidGraceMarker,
                GraceEligibilityMessage,
                firstTilde, lastTilde);
            // The lone run owns the boundary after it (`~ 5` reports the Grace
            // law once; `5` is not additionally a separator error).
            OwnSameLineItem(Current);
            return PlaceholderFrom(firstTilde);
        }

        attached &= IsDirectlyAttached(lastTilde, Current);
        var nameToken = Advance();
        // Postfix grace: each same-line marker after the name increments the
        // weight; a marker on a later line never continues, including one
        // immediately before an ordinary dot.
        var lastToken = ConsumePostfixGraceRun(nameToken, ref weight, ref attached);
        return CreateGracedName(firstTilde, nameToken, lastToken, weight, attached);
    }

    /// <summary>
    /// Checks if the current tilde sequence is followed by Identifier '=' or 'public Identifier ='.
    /// Used to detect invalid grace on property definitions. The run and the
    /// declaration head share one physical line: a marker run followed by a
    /// declaration on a later line is the lone marker of ITS line (reported by
    /// <see cref="ParsePrefixGracePrimary"/>), and the declaration stays intact.
    /// <para>Linear in the run (bug-hunt B5a, K2-R3). The scan walks token indices
    /// through <see cref="NextSignificantIndex"/> from ONE cursor — never
    /// <see cref="PeekSignificant"/>, which restarts at <c>_pos</c> and is
    /// O(offset) per call, so calling it for offset 0..k over a k-marker run made
    /// one row-start run cost O(k²) — and its verdict is memoized by the run's
    /// first significant token index, so the declaration-boundary consumers (the
    /// algorithm loop and <see cref="StartsDeclaration"/>) scan one run at most
    /// once between them: a run costs O(k) in total, never O(k) per consult. The
    /// verdict is a pure function of the immutable token array from that index,
    /// so the memo can never go stale. Lookahead answers, diagnostics, spans, and
    /// the produced tree are exactly those of the offset walk.</para>
    /// </summary>
    private bool LookaheadThroughTildesToPropertyDef()
        => LookaheadThroughTildesToPropertyDefFrom(NextSignificantIndex(_pos));

    /// <summary>
    /// Index form of <see cref="LookaheadThroughTildesToPropertyDef"/>: the
    /// same memoized scan, started at the significant token at
    /// <paramref name="start"/>.
    /// </summary>
    private bool LookaheadThroughTildesToPropertyDefFrom(int start)
    {
        if (start == _graceRunScanStart)
            return _graceRunScanVerdict;

        var line = _tokens[start].Line;
        var index = start;
        while (_tokens[index].Kind == TokenKind.Tilde && _tokens[index].Line == line)
            index = NextSignificantIndex(index + 1);

        // The declaration-head line rule (IsHeadToken): the markers, the name,
        // and the '=' all share the first marker's physical line.
        var verdict = false;
        if (_tokens[index].Line == line)
        {
            var next = NextSignificantIndex(index + 1);
            if (_tokens[index].Kind == TokenKind.Identifier)
            {
                // ~Name = ...
                verdict = _tokens[next].Kind == TokenKind.Equals && IsHeadToken(next, line);
            }
            else if (_tokens[index].Kind == TokenKind.KeywordPublic
                && _tokens[next].Kind == TokenKind.Identifier
                && _tokens[next].Line == line)
            {
                // ~public Name = ...
                var equals = NextSignificantIndex(next + 1);
                verdict = _tokens[equals].Kind == TokenKind.Equals && IsHeadToken(equals, line);
            }
        }

        _graceRunScanStart = start;
        _graceRunScanVerdict = verdict;
        return verdict;
    }

    /// <summary>
    /// Checks if 'public' keyword is followed by 'open' keyword on the same
    /// physical line (the declaration-head line rule, see <see cref="IsHeadToken"/>).
    /// Used to detect and reject public open declarations.
    /// </summary>
    private bool LookaheadIsPublicOpen()
        => IsPublicOpenAt(NextSignificantIndex(_pos));

    /// <summary>Index form of <see cref="LookaheadIsPublicOpen"/> for the 'public' at <paramref name="publicIndex"/>.</summary>
    private bool IsPublicOpenAt(int publicIndex)
    {
        var next = NextSignificantIndex(publicIndex + 1); // skip 'public'
        return _tokens[next].Kind == TokenKind.KeywordOpen && IsHeadToken(next, _tokens[publicIndex].Line);
    }

    /// <summary>
    /// Checks if 'public' keyword is followed by Identifier '=' on the same
    /// physical line (the declaration-head line rule, see <see cref="IsHeadToken"/>).
    /// Used to detect public property definitions.
    /// </summary>
    private bool LookaheadIsPublicPropertyDef()
        => IsPublicPropertyDefAt(NextSignificantIndex(_pos));

    /// <summary>Index form of <see cref="LookaheadIsPublicPropertyDef"/> for the 'public' at <paramref name="publicIndex"/>.</summary>
    private bool IsPublicPropertyDefAt(int publicIndex)
    {
        var next = NextSignificantIndex(publicIndex + 1); // skip 'public'
        return _tokens[next].Kind == TokenKind.Identifier
            && IsHeadToken(next, _tokens[publicIndex].Line)
            && LookaheadIsEqualsFrom(next);
    }

    /// <summary>
    /// Checks if the current identifier is followed by '(' ... ')' '='.
    /// Used to detect clause definitions: <c>Name(pattern) = body</c>.
    /// Skips comment tokens during lookahead. Handles nested parentheses and
    /// applies the declaration-head line rule.
    /// </summary>
    private bool LookaheadIsClauseDefinition()
        => LookaheadIsParenEqualsAfterName(_pos);

    /// <summary>
    /// Whether the current row begins with a reserved Boolean literal written as a
    /// declaration head — <c>true =</c>, <c>false(pattern) =</c>, optionally after
    /// <c>public</c> — under the ordinary declaration-head line rule
    /// (<see cref="IsHeadToken"/>). The literals are keywords, never names, so such a
    /// head can never be a declaration; recognizing it lets the parser name the
    /// mistake instead of reporting a stray <c>'='</c>.
    /// </summary>
    private bool IsReservedLiteralDeclarationHead()
        => IsReservedLiteralDeclarationHeadAt(NextSignificantIndex(_pos));

    /// <summary>
    /// Index form of <see cref="IsReservedLiteralDeclarationHead"/>: the reserved-literal
    /// head (optionally after <c>public</c>) that begins at <paramref name="index"/>.
    /// </summary>
    private bool IsReservedLiteralDeclarationHeadAt(int index)
    {
        var headLine = _tokens[index].Line;
        if (_tokens[index].Kind == TokenKind.KeywordPublic)
        {
            index = NextSignificantIndex(index + 1);
            if (!IsHeadToken(index, headLine))
                return false;
        }

        return _tokens[index].Kind is TokenKind.KeywordTrue or TokenKind.KeywordFalse
            && (LookaheadIsEqualsFrom(index) || LookaheadIsParenEqualsAfterName(index));
    }

    /// <summary>
    /// Reports a reserved Boolean literal used as a declaration name AT the literal, then
    /// skips the malformed head (the literal, any clause pattern list, and its '=') so the
    /// body after '=' parses as an ordinary output row; the diagnosed head owns the
    /// boundary before that row.
    /// </summary>
    private void ReportReservedLiteralDeclaration()
    {
        if (Current.Kind == TokenKind.KeywordPublic)
            Advance(); // the modifier is not the mistake; the literal is
        var spelling = Current.Kind == TokenKind.KeywordTrue ? "true" : "false";
        ReportError(
            DiagnosticCode.UnexpectedToken,
            $"'{spelling}' is the reserved Boolean literal, not a name: it cannot be declared as a property, clause, or parameter, and it cannot be shadowed.");
        // Skip exactly the head the lookahead recognized: the literal, then a clause
        // head's properly nested pattern list through ITS ')' (never stopping at an
        // '=' inside it, never crossing a closer an enclosing construct owns), then '='.
        var literalIndex = NextSignificantIndex(_pos);
        var headEnd = TryFindClauseHeadClose(literalIndex, out var closeIndex) ? closeIndex : literalIndex;
        while (NextSignificantIndex(_pos) <= headEnd)
            Advance();
        if (Current.Kind == TokenKind.Equals)
            Advance();
        OwnSameLineItem(Current);
    }

    /// <summary>
    /// Checks if 'public' is followed by Identifier '(' ... ')' '=' (the name
    /// on the modifier's physical line, then the ordinary clause-head rule).
    /// Used to detect public clause definitions.
    /// </summary>
    private bool LookaheadIsPublicClauseDefinition()
        => IsPublicClauseDefinitionAt(NextSignificantIndex(_pos));

    /// <summary>Index form of <see cref="LookaheadIsPublicClauseDefinition"/> for the 'public' at <paramref name="publicIndex"/>.</summary>
    private bool IsPublicClauseDefinitionAt(int publicIndex)
    {
        var next = NextSignificantIndex(publicIndex + 1); // skip 'public'
        if (_tokens[next].Kind != TokenKind.Identifier || !IsHeadToken(next, _tokens[publicIndex].Line))
            return false;
        return LookaheadIsParenEqualsAfterName(next);
    }

    /// <summary>
    /// Checks for a clause head after the name at <paramref name="nameIndex"/>:
    /// '(' ... ')' '=' with balanced parens, skipping comment tokens. The
    /// declaration-head line rule applies (see <see cref="IsHeadToken"/>): the
    /// '(' shares the name's physical line and the '=' shares the ')'s line,
    /// while the pattern list inside the open parentheses may span lines like
    /// every already-open delimiter (`F(a,` newline `b) = a + b`).
    /// </summary>
    private bool LookaheadIsParenEqualsAfterName(int nameIndex)
        => TryFindClauseHeadClose(nameIndex, out _);

    // Reusable expected-closer stack of the clause-head scan (cleared per scan; the
    // scan never re-enters itself), so the lookahead allocates nothing per call.
    private readonly List<TokenKind> _clauseHeadClosers = [];

    /// <summary>
    /// The clause-head scan behind <see cref="LookaheadIsParenEqualsAfterName"/>: true
    /// when <c>( … ) =</c> follows the name at <paramref name="nameIndex"/> under the
    /// declaration-head line rule, with <paramref name="closeIndex"/> the index of the
    /// head's own <c>)</c>. The region between the parentheses must CLOSE WITHIN
    /// ITSELF: every delimiter opened inside it closes inside it with its own kind. A
    /// mismatched closer makes this no head: the prospective head itself is an open
    /// construct even at the root, so no closer inside it is a top-level stray.
    /// Ordinary delimited parsing then applies ExpectCloser's ownership law. Every
    /// recognized head is therefore a properly nested region (see ParseClauseDefinition).
    /// </summary>
    private bool TryFindClauseHeadClose(int nameIndex, out int closeIndex)
    {
        closeIndex = -1;
        var next = NextSignificantIndex(nameIndex + 1);
        if (_tokens[next].Kind != TokenKind.LParen || !IsHeadToken(next, _tokens[nameIndex].Line))
            return false;

        var closers = _clauseHeadClosers;
        closers.Clear();
        closers.Add(TokenKind.RParen);
        while (true)
        {
            next = NextSignificantIndex(next + 1);
            var kind = _tokens[next].Kind;
            switch (kind)
            {
                case TokenKind.EndOfFile:
                    return false;
                case TokenKind.LParen:
                    closers.Add(TokenKind.RParen);
                    continue;
                case TokenKind.LBracket:
                    closers.Add(TokenKind.RBracket);
                    continue;
                case TokenKind.LBrace:
                    closers.Add(TokenKind.RBrace);
                    continue;
                case TokenKind.RParen or TokenKind.RBracket or TokenKind.RBrace:
                    if (closers[^1] != kind)
                    {
                        // The prospective HEAD is itself an open construct, including
                        // at the root. Let ordinary delimited parsing resolve the mismatch;
                        // scanning past it could steal a later declaration into this head.
                        return false;
                    }

                    closers.RemoveAt(closers.Count - 1);
                    if (closers.Count != 0)
                        continue;
                    break;
                case TokenKind.InterpolatedStringStart:
                    // A whole interpolated string is ONE atom of the region: its holes may
                    // hold delimiters that never balance against the head's (`"{ ) }"`).
                    next = InterpolationPartner(next);
                    continue;
                case TokenKind.InterpolationHoleClose
                    or TokenKind.InterpolatedStringEnd
                    or TokenKind.InterpolatedStringText
                    or TokenKind.InterpolationHoleOpen:
                    // A string or hole boundary: the scan started inside an interpolation
                    // hole, and a head can never extend past the hole that contains it.
                    return false;
                default:
                    continue;
            }

            break;
        }

        var equals = NextSignificantIndex(next + 1);
        if (_tokens[equals].Kind != TokenKind.Equals || !IsHeadToken(equals, _tokens[next].Line))
            return false;

        closeIndex = next;
        return true;
    }

    // ── Pattern parsing (for clause definitions) ────────────────────────────

    // Lexical error starts are recorded in source order (every one, whether or not its
    // diagnostic was stored). A recovered number/string token is no more trustworthy for
    // family comparison than a parser placeholder. Binary search avoids rescanning all
    // lexical errors for every clause in a long malformed file.
    private bool HasLexicalErrorInHead(Token first, Token last)
    {
        var low = 0;
        var high = _lexicalErrorStarts.Count;
        while (low < high)
        {
            var middle = low + (high - low) / 2;
            if (_lexicalErrorStarts[middle].CompareTo(first.Span.Start) < 0)
                low = middle + 1;
            else
                high = middle;
        }

        return low < _lexicalErrorStarts.Count
            && _lexicalErrorStarts[low].CompareTo(last.Span.End) < 0;
    }

    // Like $deconstruct$ names, these are unique per parse and impossible to write
    // as source identifiers. Their absent spans keep them out of editor symbols;
    // no downstream consumer classifies recovery by a magic source spelling.
    private Pattern.Bind RecoveryBinder() => new($"$recovery${_recoveryBinderCounter++}") { IsRecoveryPlaceholder = true };

    private static bool PatternContainsCollectingParameter(Pattern pattern)
        => pattern switch
        {
            Pattern.Bind { ParameterKind: ParameterKind.Collecting } => true,
            Pattern.SequenceValue(var items) => items.Any(PatternContainsCollectingParameter),
            Pattern.ListValue(var items) => items.Any(PatternContainsCollectingParameter),
            _ => false,
        };

    /// <summary>
    /// Confines the rest of a recognized clause head to its own region: when the
    /// pattern grammar stopped before the head's <c>)</c> (the index the dispatch
    /// lookahead found, <see cref="TryFindClauseHeadClose"/>), the leftover is reported
    /// ONCE — unless the head already reported an error — and skipped, so the head's <c>)</c> and <c>=</c> are
    /// found where they were written, the body stays the clause's body, and nothing
    /// inside the head leaks to the enclosing scope. The region is properly nested, so
    /// the skip never crosses a closer an enclosing construct is waiting for.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private void SynchronizeToClauseHeadClose(int closeIndex, long headDiagnosticsStart)
    {
        if (NextSignificantIndex(_pos) >= closeIndex)
            return;

        if (_diagnostics.ReportedCount == headDiagnosticsStart)
        {
            ReportError(
                DiagnosticCode.UnexpectedToken,
                $"Expected {DescribeTokenKind(TokenKind.RParen)} but found {DescribeTokenKind(Current.Kind)}.");
        }

        while (NextSignificantIndex(_pos) < closeIndex)
            Advance();
    }

    /// <summary>
    /// Reports collecting-binding misuse in an ordinary clause head at the clause's name
    /// token and returns the pattern the recovered tree keeps. A head with more than one
    /// collecting binding at a pattern level keeps the FIRST at each level; the later
    /// ones become ordinary fixed bindings, exactly as a malformed collect marker never
    /// creates a collecting binding — so no recovered tree carries a parameter shape a
    /// valid program cannot have (the callable binding plans behind editor signatures
    /// and evaluation reject such a shape outright). Collecting bindings in a
    /// conditional family are reported once, per branch, by the family validation.
    /// </summary>
    private Pattern ValidateCollectingParameterDeclarations(Pattern pattern, Token nameToken)
    {
        var recovered = KeepFirstCollectingBindingPerLevel(pattern);
        if (!ReferenceEquals(recovered, pattern))
        {
            ReportErrorAt(
                DiagnosticCode.InvalidCollectingBinding,
                MultipleCollectingBindingsPerLevelDiagnostic,
                nameToken);
            return recovered;
        }

        if (pattern.TryGetOrdinaryClauseParameterPatterns() is not { } parameterPatterns)
            return pattern;

        if (ParameterPattern.HasRepeatedCaptureNameIncludingCollecting(parameterPatterns))
        {
            ReportErrorAt(
                DiagnosticCode.InvalidCollectingBinding,
                RepeatedNameIncludesCollectingDiagnostic,
                nameToken);
        }

        return pattern;
    }

    /// <summary>
    /// The recovery shape of a pattern with several collecting bindings at one level:
    /// the first collecting binding of every structural level (sequence or list) is kept,
    /// every later one becomes an ordinary fixed binding (its collect marker dropped).
    /// Recursion depth is the pattern's nesting, which the parser's recursion budget bounds.
    /// </summary>
    private static Pattern KeepFirstCollectingBindingPerLevel(Pattern pattern)
    {
        var items = pattern switch
        {
            Pattern.SequenceValue(var sequenceItems) => sequenceItems,
            Pattern.ListValue(var listItems) => listItems,
            _ => null,
        };
        if (items is null)
            return pattern;

        var kept = new List<Pattern>(items.Count);
        var levelHasCollecting = false;
        var changed = false;
        foreach (var item in items)
        {
            switch (item)
            {
                case Pattern.Bind { ParameterKind: ParameterKind.Collecting } collecting when levelHasCollecting:
                    kept.Add(collecting with { ParameterKind = ParameterKind.Normal, CollectMarkerSpan = null });
                    changed = true;
                    break;
                case Pattern.Bind { ParameterKind: ParameterKind.Collecting }:
                    levelHasCollecting = true;
                    kept.Add(item);
                    break;
                default:
                    var child = KeepFirstCollectingBindingPerLevel(item);
                    kept.Add(child);
                    changed |= !ReferenceEquals(child, item);
                    break;
            }
        }

        if (!changed)
            return pattern;
        return pattern is Pattern.ListValue ? new Pattern.ListValue(kept) : new Pattern.SequenceValue(kept);
    }

    /// <summary>
    /// Parses a clause-head pattern for ordinary recursive parameter patterns
    /// or conditional algorithm branches. The head's items are comma-separated; the
    /// head's own argument list is a top-level <see cref="Pattern.SequenceValue"/> when it
    /// has more than one item or its lone item is a structural pattern (so <c>F((x, y))</c>
    /// is <c>SequenceValue[SequenceValue[x, y]]</c> and <c>F([x])</c> is
    /// <c>SequenceValue[ListValue[x]]</c>), and the lone item itself otherwise. Items are:
    /// - number literals (including negative), string and Boolean literals
    /// - identifier binders (fixed or collecting)
    /// - nested SEQUENCE patterns <c>(p1, …, pn)</c> and LIST patterns <c>[p1, …, pn]</c>,
    ///   including the empty <c>()</c> and <c>[]</c>
    /// </summary>
    private Pattern ParsePattern()
    {
        var items = ParsePatternItems();
        if (items.Count != 1)
            return new Pattern.SequenceValue(items);

        return items[0] is Pattern.SequenceValue or Pattern.ListValue ? new Pattern.SequenceValue(items) : items[0];
    }

    private List<Pattern> ParsePatternItems()
    {
        var items = new List<Pattern>();
        items.Add(ParsePatternAtom());

        while (true)
        {
            if (Current.Kind == TokenKind.Comma)
                Advance(); // consume ','
            else if (!StartsUnseparatedPatternItem())
                break;

            items.Add(ParsePatternAtom());
        }

        return items;
    }

    /// <summary>
    /// SYN-07A for parameter-pattern lists — the ONE boundary decision of
    /// <see cref="ParsePatternItems"/> (clause heads <c>F(a, b) = …</c> and
    /// nested sequence-value patterns <c>(x, *y)</c>): true when the current
    /// token begins another pattern item on the SAME physical line as the
    /// pattern just parsed, without the comma the list requires. The item is
    /// reported at its first token — the pattern-worded report of the
    /// <see cref="DiagnosticCode.UnseparatedSameLineItem"/> family — and then
    /// admitted as the next pattern of THIS list, so <c>F(a b) = a + b</c>
    /// recovers as the clause head <c>F(a, b)</c>: its <c>)</c> and <c>=</c>
    /// are then found where they were written, the body stays F's body, and
    /// nothing leaks into the enclosing scope as unrelated rows or implicit
    /// parameters. A boundary a pattern-atom recovery already owns
    /// (<see cref="OwnSameLineItem"/>) is admitted silently, exactly like the
    /// expression-list rule. A token on a later line is never admitted here:
    /// parameter lists have no newline separator, so it reaches the ordinary
    /// closing-delimiter check unchanged. What can begin a pattern item is
    /// the atom grammar's own starter set (<see cref="CanStartPatternAtom"/>,
    /// a nested sequence or list pattern included), with one refinement for the
    /// star: a star that no operand can follow is
    /// a (misplaced) spread marker on the pattern before it, never the collect
    /// marker of a next binding — the same classifier the atom grammar and the
    /// expression-level star decision use — so it is left to the closing
    /// delimiter path and keeps the marker diagnostics the pattern grammar
    /// owns (<c>F(a *)</c>, <c>F(1*)</c>). A star an operand follows begins a
    /// collecting binding missing its comma (<c>F(a *b)</c> recovers as
    /// <c>F(a, *b)</c>), and the marker grammar then reports a detached or
    /// nameless marker on its own (<c>F(a * b)</c>, <c>F(a *2)</c>).
    /// </summary>
    private bool StartsUnseparatedPatternItem()
    {
        if (!IsSamePhysicalLineAsPreviousToken() || !CanStartPatternAtom(Current.Kind))
            return false;

        if (Current.Kind == TokenKind.Star && !CanStartUnaryOperand(PeekSignificant(1).Kind))
            return false;

        ReportUnseparatedSameLineItem(Current, UnseparatedPatternItemMessage);
        return true;
    }

    /// <summary>
    /// THE pattern-atom starter set: exactly the token kinds
    /// <see cref="ParsePatternAtomCore"/> parses as the beginning of a pattern
    /// item (its non-default arms). The switch's default arm guards the
    /// relation in the fail-loud direction — a starter without an arm throws —
    /// and <c>SameLineSeparatorTests</c> pins the classification of every
    /// <see cref="TokenKind"/>, so the predicate and the grammar cannot drift
    /// apart. Deliberately narrower than <see cref="CanStartExpression"/>: a
    /// pattern has no <c>not</c> or block form (its <c>[</c> begins a LIST pattern, never
    /// a list expression).
    /// </summary>
    private static bool CanStartPatternAtom(TokenKind kind) => kind switch
    {
        TokenKind.Star          // collecting binding `*name`
        or TokenKind.Tilde      // rejected Grace, recovered to its name
        or TokenKind.Number
        or TokenKind.Minus      // negative literal
        or TokenKind.StringLiteral
        or TokenKind.InterpolatedStringStart // rejected: a pattern needs fixed text
        or TokenKind.KeywordTrue   // Boolean literal pattern
        or TokenKind.KeywordFalse
        or TokenKind.Identifier
        or TokenKind.LParen      // nested sequence pattern
        or TokenKind.LBracket => true, // nested list pattern
        _ => false,
    };

    /// <summary>
    /// Parses a single atomic pattern element:
    /// - number literal → Pattern.LitInt
    /// - negative number → Pattern.LitInt with negated value
    /// - identifier → Pattern.Bind
    /// - ( pattern ) -> nested SEQUENCE pattern (<c>()</c> is the empty sequence pattern;
    ///   one non-collecting item is the invalid singleton, <see cref="DiagnosticCode.SingletonSequencePattern"/>)
    /// - [ pattern ] -> nested LIST pattern (<c>[]</c> is the empty list pattern)
    /// Grace `~` is rejected in clause-head patterns.
    /// </summary>
    private Pattern ParsePatternAtom()
    {
        // Clause-head pattern nesting recurses through here (the nested `(pattern)`
        // case), so enforce the shared parser recursion budget once per level.
        using var level = EnterNestingLevel();
        return ParsePatternAtomCore();
    }

    /// <summary>
    /// Builds a named binding pattern with optional collecting metadata.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private static Pattern CreateBindingPattern(
        Token nameToken,
        ParameterKind kind = ParameterKind.Normal,
        Token? collectMarkerToken = null)
        => new Pattern.Bind(nameToken.StringValue!)
        {
            NameSpan = nameToken.Span,
            ParameterKind = kind,
            CollectMarkerSpan = collectMarkerToken?.Span,
        };

    /// <summary>
    /// The CONTEXTUAL <c>meta</c> modifier (CallReference S1, October 2026): the identifier
    /// <c>meta</c> directly followed, on the same line, by another pattern item is the modifier of
    /// that item, never a parameter named <c>meta</c> — <c>F(meta)</c>, <c>F(meta, x)</c> and
    /// <c>meta = 3</c> keep declaring an ordinary name, while <c>Capture(meta operation)</c> declares
    /// the META parameter <c>operation</c>. Every other identifier stays an ordinary binder.
    /// </summary>
    private bool StartsMetaModifier()
        => Current.Kind == TokenKind.Identifier
            && string.Equals(Current.StringValue, MetaModifierKeyword, StringComparison.Ordinal)
            && PeekSignificant(1) is var next
            && next.Line == Current.Line
            && CanStartPatternAtom(next.Kind);

    /// <summary>The contextual META modifier's spelling.</summary>
    internal const string MetaModifierKeyword = "meta";

    /// <summary>
    /// The one message of a misplaced <c>meta</c> modifier (<see cref="DiagnosticCode.InvalidMetaParameter"/>),
    /// shared with the pre-evaluation violation <c>PreEvaluationAstViolation.InvalidMetaParameter</c>.
    /// Lean: <c>invalidMetaParameterMessage</c>.
    /// </summary>
    internal const string InvalidMetaParameterDiagnostic =
        "`meta` may modify only a plain, fixed parameter name written once at the top level of an ordinary parameter list.";

    /// <summary>
    /// Parses <c>meta item</c> (the modifier recognized by <see cref="StartsMetaModifier"/>): a plain
    /// binder becomes a META binder (<see cref="ParameterKind.Meta"/>). Any other item — a collecting
    /// binding, a nested sequence or list pattern, a literal — is reported as
    /// <see cref="DiagnosticCode.InvalidMetaParameter"/> over the modifier and the item, and the item
    /// is kept as written without the modifier (recovery never creates a META binder the rule refuses).
    /// </summary>
    private Pattern ParseMetaBindingPatternAtom()
    {
        var metaToken = Advance(); // consume 'meta'
        var item = ParsePatternAtom();
        if (item is Pattern.Bind { ParameterKind: ParameterKind.Normal, IsRecoveryPlaceholder: false } binder)
            return binder with { ParameterKind = ParameterKind.Meta };

        ReportErrorAcross(DiagnosticCode.InvalidMetaParameter, InvalidMetaParameterDiagnostic, metaToken, Previous);
        return item;
    }

    /// <summary>
    /// Reports a misplaced META binder in an ordinary clause head — inside a structural pattern, or
    /// with a name the head binds again (<see cref="ParameterPattern.FindMetaViolation"/>) — at the
    /// clause's name token, and returns the pattern the recovered tree keeps: every META binder of a
    /// refused head becomes an ordinary binder, so no recovered tree carries a META capture the rule
    /// refuses. A head that is no ordinary parameter list (it holds a literal) is a clause family,
    /// whose META binders the family validation reports.
    /// </summary>
    private Pattern ValidateMetaParameterDeclarations(Pattern pattern, Token nameToken)
    {
        if (pattern.TryGetOrdinaryClauseParameterPatterns() is not { } parameterPatterns
            || ParameterPattern.FindMetaViolation(parameterPatterns) is null)
            return pattern;

        ReportErrorAt(DiagnosticCode.InvalidMetaParameter, InvalidMetaParameterDiagnostic, nameToken);
        return WithoutMetaBinders(pattern);
    }

    /// <summary>The pattern with every META binder demoted to an ordinary binder (error recovery only).</summary>
    private static Pattern WithoutMetaBinders(Pattern pattern)
        => pattern switch
        {
            Pattern.Bind { ParameterKind: ParameterKind.Meta } binder => binder with { ParameterKind = ParameterKind.Normal },
            Pattern.SequenceValue(var items) => new Pattern.SequenceValue(items.Select(WithoutMetaBinders).ToList()),
            Pattern.ListValue(var items) => new Pattern.ListValue(items.Select(WithoutMetaBinders).ToList()),
            _ => pattern,
        };

    /// <summary>
    /// Parses a collecting binding <c>*name</c> at the start of a pattern
    /// atom (the star is not yet consumed). The collect marker must be
    /// DIRECTLY attached to its binding name — a gap reports the targeted
    /// attachment diagnostic, a repeated star reports the repeated-marker
    /// diagnostic, and a star without a name reports the missing-name
    /// diagnostic. Malformed recovery binds the name as an ordinary fixed
    /// binding (or a placeholder) and never introduces a collecting binding.
    /// </summary>
    private Pattern ParseCollectingBindingPatternAtom()
    {
        var markerToken = Advance(); // consume '*'

        // Repeated markers (`**items`): consume the run, report once, and
        // never create a collecting binding from the malformed shape.
        if (Current.Kind == TokenKind.Star)
        {
            var lastStar = markerToken;
            while (Current.Kind == TokenKind.Star)
                lastStar = Advance();

            if (Current.Kind == TokenKind.Identifier)
            {
                var repeatedNameToken = Advance();
                ReportErrorAcross(
                    DiagnosticCode.InvalidCollectMarker,
                    RepeatedCollectMarkerDiagnostic(repeatedNameToken.StringValue!),
                    markerToken, repeatedNameToken);
                return CreateBindingPattern(repeatedNameToken);
            }

            ReportErrorAcross(
                DiagnosticCode.InvalidCollectMarker,
                CollectMarkerMissingNameDiagnostic,
                markerToken, lastStar);
            return RecoveryBinder();
        }

        if (Current.Kind != TokenKind.Identifier)
        {
            ReportErrorAt(DiagnosticCode.InvalidCollectMarker, CollectMarkerMissingNameDiagnostic, markerToken);

            // Consume one malformed same-line pattern atom where possible so a
            // following comma/closing delimiter remains available to the caller.
            // Malformed syntax must not introduce collecting-binding semantics
            // into the recovered tree.
            if (Current.Kind is not (TokenKind.Comma or TokenKind.EndOfFile)
                && !IsClosingDelimiter(Current.Kind)
                && Current.Line == markerToken.Line)
                return ParsePatternAtom();

            return RecoveryBinder();
        }

        var nameToken = Advance();
        var name = nameToken.StringValue!;

        if (!IsDirectlyAttached(markerToken, nameToken))
        {
            ReportErrorAcross(
                DiagnosticCode.InvalidCollectMarker,
                CollectMarkerAttachmentDiagnostic(name),
                markerToken, nameToken);
            // A detached marker is not a collecting binding; the name stays
            // an ordinary fixed binding in the recovered tree.
            return CreateBindingPattern(nameToken);
        }

        var hadPostfixGrace = false;
        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
        {
            hadPostfixGrace = true;
            Advance();
        }
        if (hadPostfixGrace)
            ReportErrorAt(
                DiagnosticCode.InvalidGraceMarker,
                "Collecting bindings cannot use `~` reordering.",
                nameToken);

        return CreateBindingPattern(nameToken, ParameterKind.Collecting, markerToken);
    }

    private Pattern ParsePatternAtomCore()
    {
        switch (Current.Kind)
        {
            case TokenKind.Star:
                return ParseCollectingBindingPatternAtom();

            case TokenKind.Tilde:
                {
                    var firstTilde = Current;
                    var lastGraceToken = Current;
                    while (Current.Kind == TokenKind.Tilde && Current.Line == firstTilde.Line)
                        lastGraceToken = Advance(); // skip prefix tildes
                    if (Current.Kind == TokenKind.Identifier && Current.Line == firstTilde.Line)
                    {
                        var token = Advance();
                        lastGraceToken = token;
                        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
                            lastGraceToken = Advance(); // skip postfix tildes
                        ReportErrorAcross(
                            DiagnosticCode.InvalidGraceMarker,
                            "Grace is not allowed in clause-head patterns.",
                            firstTilde, lastGraceToken);
                        return CreateBindingPattern(token);
                    }

                    // No identifier follows: the diagnostic covers the marker
                    // run itself; the recovered atom reports its own errors.
                    ReportErrorAcross(
                        DiagnosticCode.InvalidGraceMarker,
                        "Grace is not allowed in clause-head patterns.",
                        firstTilde, lastGraceToken);
                    // A lone run before a pattern boundary (`F(~) = 1`, `F(~, a)`) is
                    // the whole malformed atom: its diagnostic owns the boundary.
                    if (Current.Kind is TokenKind.Comma or TokenKind.EndOfFile || IsClosingDelimiter(Current.Kind))
                        return RecoveryBinder();
                    // Try to parse remaining atom for recovery. `~*name` reaches
                    // the collecting-binding atom below, so the grace error keeps
                    // the collecting binding.
                    return ParsePatternAtom();
                }

            case TokenKind.Number:
                {
                    var token = Advance();
                    return new Pattern.LitInt(token.NumValue);
                }

            case TokenKind.Minus:
                {
                    var minus = Advance(); // consume '-'
                    if (Current.Kind != TokenKind.Number)
                    {
                        ReportError(DiagnosticCode.UnexpectedToken, "Expected number after '-' in pattern.");
                        // The diagnosed token owns this boundary: `F(-x)`
                        // reports the missing number once, and `x` is not
                        // additionally an unseparated pattern item.
                        OwnSameLineItem(Current);
                        return RecoveryBinder();
                    }
                    var token = Advance();
                    if (!IsDirectlyAttached(minus, token))
                    {
                        ReportErrorAt(DiagnosticCode.UnexpectedToken,
                            "A negative pattern's '-' must be directly attached to its number: write '-2'.", minus);
                        return RecoveryBinder();
                    }
                    return new Pattern.LitInt(-token.NumValue);
                }

            case TokenKind.StringLiteral:
                {
                    // A single-quoted literal, or a double-quoted one with no hole (its
                    // payload is the decoded text): the same literal pattern either way.
                    var token = Advance();
                    return new Pattern.LitString(token.StringValue ?? "");
                }

            case TokenKind.InterpolatedStringStart:
                // A pattern is fixed text; a string with a hole is computed when evaluated.
                RejectInterpolatedStringHere(InterpolatedPatternDiagnostic);
                return RecoveryBinder();

            case TokenKind.KeywordTrue:
            case TokenKind.KeywordFalse:
                {
                    // The reserved Boolean literals are literal patterns, never binders:
                    // `F(true) = …` matches the Boolean value `true` only.
                    var token = Advance();
                    return new Pattern.LitBool(token.Kind == TokenKind.KeywordTrue);
                }

            case TokenKind.Identifier when StartsMetaModifier():
                return ParseMetaBindingPatternAtom();

            case TokenKind.Identifier:
                {
                    var token = Advance();
                    var name = token.StringValue!;

                    Token? lastPostfixTilde = null;
                    while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
                        lastPostfixTilde = Advance();

                    if (lastPostfixTilde is not null)
                        ReportErrorAcross(
                            DiagnosticCode.InvalidGraceMarker,
                            "Grace is not allowed in clause-head patterns.",
                            token, lastPostfixTilde);

                    // Postfix `*` after a binding name is spread syntax, never
                    // binding syntax. Report the targeted marker-side diagnostic
                    // when the star is clearly meant as a marker — nothing that
                    // could begin a unary-level operand follows it (the ONE
                    // operand classifier the expression-level star decision also
                    // uses; a pattern has no multiplication, so the expression
                    // level's line-final star law has no pattern role); a star
                    // followed by an operand-like token is left to the caller:
                    // the pattern list reads it as the collect marker of a next
                    // binding missing its comma (StartsUnseparatedPatternItem,
                    // `F(a *b)`), and the marker grammar then reports a detached
                    // or nameless marker on its own (`F(a * b)`, `F(a *2)`).
                    if (Current.Kind == TokenKind.Star
                        && MayContinueClosedExpression(TokenKind.Star))
                    {
                        var looksLikeMarker = !CanStartUnaryOperand(PeekSignificant(1).Kind);
                        if (looksLikeMarker)
                        {
                            var lastStar = Advance();
                            while (Current.Kind == TokenKind.Star
                                && MayContinueClosedExpression(TokenKind.Star))
                                lastStar = Advance(); // consume a malformed star run whole
                            ReportErrorAcross(
                                DiagnosticCode.InvalidCollectMarker,
                                SpreadMarkerInBindingPatternDiagnostic(name),
                                token, lastStar);
                            return CreateBindingPattern(token);
                        }
                    }

                    return CreateBindingPattern(token);
                }

            case TokenKind.LParen:
                {
                    var open = Advance(); // consume '('
                    var itemsDiagnosticsStart = _diagnostics.ReportedCount;
                    // `()` is the empty SEQUENCE pattern: it matches only the empty sequence.
                    var items = Current.Kind == TokenKind.RParen ? [] : ParsePatternItems();
                    var close = Current;
                    Expect(TokenKind.RParen);
                    // Parentheses in patterns are structural at every nesting level and select
                    // the SEQUENCE kind: (a, b) -> SequenceValue([a, b]);
                    // ((a, b)) -> SequenceValue([SequenceValue([a, b])]). THE SINGLETON RULE: a
                    // sequence pattern of exactly one non-collecting item describes a one-item
                    // sequence, which no value is — `(x)`, `((a, b))`, `([x])` are rejected (a
                    // cleanly parsed group only, so a malformed item never cascades), while the
                    // collector-only `(*xs)` is valid. The recovered tree keeps the group as
                    // written (the program is never evaluated).
                    if (Pattern.IsSingletonSequenceItems(items)
                        && _diagnostics.ReportedCount == itemsDiagnosticsStart
                        && close.Kind == TokenKind.RParen)
                    {
                        ReportErrorAcross(
                            DiagnosticCode.SingletonSequencePattern,
                            SingletonSequencePatternDiagnostic,
                            open,
                            close);
                    }

                    return new Pattern.SequenceValue(items);
                }

            case TokenKind.LBracket:
                {
                    Advance(); // consume '['
                    // Brackets in patterns select the LIST kind: [x] -> ListValue([x]) matches a
                    // one-element list; `[]` is the empty list pattern.
                    var items = Current.Kind == TokenKind.RBracket ? [] : ParsePatternItems();
                    Expect(TokenKind.RBracket);
                    return new Pattern.ListValue(items);
                }

            default:
                {
                    if (CanStartPatternAtom(Current.Kind))
                        throw new InvalidOperationException($"Pattern-atom starter {Current.Kind} has no ParsePatternAtomCore arm.");

                    return RecoverMalformedPatternAtom();
                }
        }
    }

    /// <summary>
    /// Recovery for a token that cannot begin a pattern item inside a recognized clause
    /// head (a properly nested region, see <see cref="TryFindClauseHeadClose"/>). The
    /// atom becomes a unique spanless recovery binder, which declares no source name,
    /// and recovery never leaves the head: a closing delimiter is reported and left in
    /// place — the head's own <c>)</c> or a nested pattern group's closes its construct
    /// (<c>F() = 1</c> reports once instead of consuming the head's <c>)</c>); an opening
    /// <c>{</c> is reported and skipped together with the rest of its group, which the
    /// head encloses (<c>F({a, b}) = …</c> keeps its <c>)</c>, its <c>=</c>, and its body);
    /// any other token is reported and skipped alone. A missing item a reported character
    /// stands in (<c>F(x, @) = x</c>: only a closer, a comma, or the end of input follows
    /// it) is that character: the lexer already reported it, so the binder is filled
    /// without a second report and the head is still recorded as recovered.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private Pattern.Bind RecoverMalformedPatternAtom()
    {
        var token = Current;
        if ((IsClosingDelimiter(token.Kind) || token.Kind is TokenKind.EndOfFile or TokenKind.Comma)
            && TakeReportedCharacterBeforeCurrent() is not null)
        {
            return RecoveryBinder();
        }

        ReportError(DiagnosticCode.UnexpectedToken, $"Unexpected {DescribeTokenKind(token.Kind, includeArticle: false)} in a pattern.");
        if (IsClosingDelimiter(token.Kind) || token.Kind == TokenKind.EndOfFile)
            return RecoveryBinder();

        if (token.Kind is TokenKind.LBrace)
        {
            var depth = 0;
            do
            {
                // An interpolation hole's close belongs to the hole that holds this pattern,
                // never to the skipped group; and a whole interpolated string is one
                // depth-neutral unit, whatever delimiters its holes hold.
                if (Current.Kind == TokenKind.InterpolationHoleClose)
                    break;
                if (Current.Kind == TokenKind.InterpolatedStringStart)
                {
                    AdvancePastInterpolatedString();
                    continue;
                }

                if (Current.Kind is TokenKind.LParen or TokenKind.LBracket or TokenKind.LBrace)
                    depth++;
                else if (IsClosingDelimiter(Current.Kind))
                    depth--;
                Advance();
            }
            while (depth > 0 && Current.Kind != TokenKind.EndOfFile);
            OwnSameLineItem(Current);
            return RecoveryBinder();
        }

        SkipForRecovery(); // the token after it is a recovery-owned boundary
        return RecoveryBinder();
    }

    // ── Output line parsing ─────────────────────────────────────────────────
    // Reads comma-separated expressions (spread slots via the attached
    // postfix spread marker `expr*`).

    /// <summary>
    /// Parses a property body as an algorithm: the comma-separated expressions
    /// become the algorithm's output list.
    /// If the body is a single algorithm-valued block expression, return its
    /// algorithm directly (enables nested property access like X.Y where
    /// X = { Y = ... }). Plain sequence values such as <c>(a, b)</c> stay wrapped
    /// as a single block output so callers can distinguish one sequence value
    /// from multiple top-level outputs.
    /// Assignment deconstruction preserves a written block inside its shared RHS wrapper.
    /// </summary>
    private Algorithm ParseOutputLine(bool preserveWrittenBlock = false)
    {
        // Definition bodies end before an independent next-line expression,
        // which is parsed by the surrounding output/algorithm context.
        // Grammar-eligible continuation can still extend the body. An explicit comma, an already-open
        // delimiter, a grammar-eligible trailing/leading binary operator, and a
        // leading '.' (method-chain layout) still continue the body. A second
        // same-line item without a comma is the SYN-07A separator error and is
        // RECOVERED INTO THIS BODY as its next slot (`P = a b` keeps `b` in P),
        // never leaked to the enclosing scope as an output row. A ';' is
        // invalid expression syntax and reports the unsupported-semicolon
        // diagnostic; any tokens consumed after it are error recovery, not a
        // valid continuation.
        var exprs = ParseExpressionListOperand(allowNewlineSeparator: false);

        // Unwrap only scope-owning algorithm expressions (brace blocks and
        // recovery blocks with declarations/opens): `X = { ... }` merges the
        // brace algorithm into the property body. A plain parenthesized
        // capture such as `X = (a, b)` stays one captured value boundary —
        // the distinction is now structural (AlgorithmExpr vs Capture).
        if (!preserveWrittenBlock && exprs.Count == 1
            && exprs[0] is Expr.AlgorithmExpr(var innerAlg))
            return innerAlg;

        return new Algorithm.User(
            Parent: null,
            ParameterPatterns: [],
            Opens: [],
            Properties: [],
            Output: exprs);
    }

    /// <summary>
    /// Normalizes and validates open expressions. The list arriving here
    /// comes from ParseOpenTargetList's dedicated comma-list parsing — one
    /// individual target per entry, matching Lean's per-target model. An
    /// explicitly same-line-closed spread-marked target (`open A*, B`) parses
    /// to a SequenceSpread and is rejected here by open-form validation before
    /// evaluator or runtime involvement — spread is not an open form. So is
    /// an attached line-final `open A*` (issue #183: an attached line-final
    /// star is a spread), while a detached line-final `open A *` is an
    /// incomplete multiplication.
    /// DotCall(obj, name, null) is the canonical form for dotted paths in opens.
    /// Rejects DotCall with args as invalid.
    /// Lean: Expr.openForm? — only Block, Resolve, and argumentless DotCall
    /// are open forms; everything else is rejected — and resolveAlgForOpen
    /// recurses through a dotted path's receiver, so the form is checked ALL the
    /// way down: the head of the receiver chain must itself be an open form.
    /// </summary>
    private void NormalizeAndValidateOpenForms(List<Expr> exprs)
    {
        for (var i = 0; i < exprs.Count; i++)
            exprs[i] = NormalizeOpenExpr(exprs[i]);

        // An open target is an open form all the way down (MOD-02): for a dotted path the
        // HEAD of its receiver chain must name an algorithm too — a name, a `{ ... }` block,
        // or a `load` module — so `open 5.N`, `open F(1).N`, `open (A, B).N` and
        // `open [A].N` are as invalid as `open 5`, `open F(1)`, `open (A, B)` and `open [A]`,
        // and are reported at the offending head. Normalization already reported and
        // recovered every argument-bearing edge and Grace marker, so every step between
        // the target and its head is an argumentless dot edge.
        foreach (var expr in exprs)
        {
            var head = expr.OpenTargetHead();
            if (head is Expr.Capture)
            {
                // A surviving multi-slot or spread group is a VALUE boundary, not an
                // algorithm: `open` consumes algorithm/namespace identity, and
                // a capture never exposes the identity of what it encloses.
                ReportOpenFormError(CapturedOpenTargetDiagnostic, head);
            }
            else if (!IsOpenForm(head))
            {
                var kind = OpenExprKind(head);
                ReportOpenFormError($"Invalid open form: '{kind}' is not allowed in open declarations.", head);
            }
        }
    }

    internal const string CapturedOpenTargetDiagnostic =
        "Invalid open form: a parenthesized group is a captured value, not an algorithm. Open the algorithm directly (open M) or use a `{ ... }` block.";

    // Open-form diagnostics must point at the offending open target, not at
    // whatever token follows the open declaration.
    private void ReportOpenFormError(string message, Expr expr)
    {
        if (expr.Span is { } span)
            ReportError(DiagnosticCode.BadOpenForm, message, span);
        else
            ReportError(DiagnosticCode.BadOpenForm, message);
    }

    /// <summary>
    /// Recursively normalizes an open expression:
    /// - DotCall(obj, name, null) is the canonical no-arg form (kept as-is)
    /// - DotCall(obj, name, args) → report error (call-like syntax not allowed in opens)
    /// - Recurse through the DotCall target and stored fallback/name occurrence;
    ///   AlgorithmExpr/Capture nodes are kept as-is.
    /// A SequenceSpread target falls through unchanged (never rebuilt here,
    /// which would bypass CreateSequenceSpread) and is rejected by the
    /// open-form validation that follows.
    /// </summary>
    private Expr NormalizeOpenExpr(Expr expr)
    {
        switch (expr)
        {
            case Expr.Grace grace:
                // Grace annotates implicit parameter ORDER; an open target
                // consumes structural algorithm identity, where no parameter
                // inference exists, so a grace-marked target is not an open
                // form. This covers written prefix/postfix Grace on a target
                // occurrence (`open ~A`, `open A~`, `open A~.B`) and prefix
                // Grace on a dot member occurrence (`open A.~B`). Recovery
                // unwraps the individual name occurrence, so no Grace node
                // ever survives open elaboration.
                ReportOpenFormError(
                    "Invalid open form: 'grace' is not allowed in open declarations.",
                    grace);
                return NormalizeOpenExpr(grace.Inner);

            case Expr.DotCall dotCall when dotCall.Args is null:
                return dotCall with
                {
                    Target = NormalizeOpenExpr(dotCall.Target),
                    LexicalFallback = dotCall.LexicalFallback is { } fallback
                        ? NormalizeOpenExpr(fallback)
                        : null,
                };

            case Expr.DotCall dotCall:
                ReportOpenFormError(
                    $"Invalid open form: call-like dotCall '.{dotCall.Name}(...)' is not allowed in open declarations.",
                    expr);
                // Recovery: the argumentless path the target names (`open A.X()` recovers
                // as `open A.X`), so the one report above is the whole diagnosis and the
                // open-form validation that follows sees a valid form — never a second
                // report for the same target.
                return NormalizeOpenExpr(dotCall with { Args = null });

            case Expr.AlgorithmExpr or Expr.Capture:
                // Inline algorithm targets stay as-is and are valid open
                // forms. A capture target — a group with several slots or a
                // lone spread slot (`open (A, B)`, `open (A*)`; a redundant
                // group such as `open (M)` is simply `open M` by the time it
                // is parsed) — also stays as-is structurally, but the
                // open-form validation that follows rejects it: a capture is a
                // value boundary, not an algorithm.
                return expr;

            default:
                return expr;
        }
    }

    /// <summary>
    /// Predicate for valid open forms at parse time.
    /// Lean: Expr.openForm? — only AlgorithmExpr, Resolve, and
    /// argumentless DotCall post-elaboration. Spread is NOT an open form (a
    /// spread-marked target such as `open A*, B` is rejected here), and a
    /// Capture is NOT an open form (`open (M, M)` is a captured value target,
    /// rejected with the targeted captured-open diagnostic above).
    /// DotCall with args is NOT a valid open form.
    /// load calls (Call(Resolve("load"), _)) are allowed as *surface* open forms because
    /// the load elaboration pass will rewrite them to AlgorithmExpr nodes before open
    /// resolution. After elaboration, no load calls or StringLiteral nodes remain —
    /// see Lean postElabInvariant (rejects both structurally).
    /// load is NOT a core Expr constructor; it is surface syntax only.
    /// </summary>
    // An open target consumes structural algorithm identity, so only
    // argumentless dot paths qualify. Grace on either the receiver or member
    // occurrence is reported and unwrapped by NormalizeOpenExpr first.
    private static bool IsOpenForm(Expr e)
        => e.IsCoreOpenForm() || e.TryGetUnresolvedLoadArguments(out _);

    /// <summary>
    /// Human-readable kind string for open-form validation errors.
    /// </summary>
    private static string OpenExprKind(Expr e) => e switch
    {
        Expr.Num => "num",
        Expr.StringLiteral => "stringLiteral",
        Expr.InterpolatedString => "interpolatedString",
        Expr.BoolLiteral => "boolLiteral",
        Expr.Param => "param",
        Expr.Unary => "unary",
        Expr.Binary => "binary",
        Expr.Comparison => "comparison",
        Expr.SequenceConstruct => "sequenceConstruct",
        Expr.SequenceSpread => "spread",
        Expr.ListLiteral => "listLiteral",
        Expr.Index => "index",
        Expr.Call => "call",
        Expr.DotCall => "dotCall",
        Expr.Grace => "grace",
        Expr.NativeCall => "nativeCall",
        Expr.EmptySequence => "empty sequence",
        _ => "unknown",
    };

    /// <summary>
    /// Parses one output contribution: an expression list whose slots are
    /// separated by commas and, when <paramref name="allowNewlineSeparator"/>
    /// is true (root output, algorithm/brace bodies, parenthesized groups,
    /// argument lists, list literals), by physical newlines. When it is false
    /// (definition bodies) the body is line-bounded: a newline ends it and a
    /// following expression is parsed by the surrounding output/algorithm
    /// context instead. A second slot beginning on the SAME physical line
    /// without a comma is the SYN-07A separator error
    /// (<see cref="DiagnosticCode.UnseparatedSameLineItem"/>): it is reported
    /// and then recovered as the next slot of THIS list, so the structure the
    /// programmer most plausibly meant survives for later diagnostics and
    /// tooling, and a definition body never leaks an expression into the
    /// enclosing scope. Semicolon is not an expression operator; when
    /// encountered here it reports its own targeted diagnostic and recovers as
    /// a separator. Returns the expression-list items consumed by the
    /// surrounding output/call context. Open target lists never use this
    /// method: `open` has its own dedicated comma-list parser
    /// (<see cref="ParseOpenTargetList"/>).
    /// </summary>
    private List<Expr> ParseExpressionListOperand(bool allowNewlineSeparator)
    {
        // Spread slots need no extra handling here: a postfix `*` that same-line
        // syntax closes (a comma, a closer, a fluent dot), or that ends its
        // physical line ATTACHED to its operand (issue #183), parses as a postfix
        // continuation directly to Expr.SequenceSpread. A spread expression is
        // always one whole slot — a same-line operand makes the star
        // multiplication — so spreading before another item on the same line
        // requires an explicit comma (`a*, b`), while an attached line-final
        // spread completes its slot and the next line begins the next one
        // wherever newline separators are allowed (`a*` newline `b`). A DETACHED
        // line-final star (`a *` newline `b`) is multiplication instead.
        var exprs = new List<Expr>();
        exprs.Add(ParseExpression());

        while (true)
        {
            if (Current.Kind == TokenKind.Comma)
            {
                // Q-65: a leading comma explicitly continues this expression list,
                // including a simple definition body. Independent newline slots
                // still require allowNewlineSeparator; comma never changes that gate.
                if (!MayContinueClosedExpression(TokenKind.Comma))
                    break;
                Advance(); // consume ','
            }
            else if (Current.Kind == TokenKind.Semicolon)
            {
                // Semicolon is never valid expression syntax. Report the
                // diagnostic and consume it as error recovery (treating it like
                // an expression-list separator) so later parsing and diagnostics
                // stay useful. This is recovery only, not a supported continuation:
                // unlike a written comma it never claims a declaration head, a
                // closer, or the end of input as its next slot — `A = 1;` newline
                // `B = 2` keeps `B` a declaration of the enclosing scope.
                ReportUnsupportedSemicolon(Current);
                Advance();
                if (!CanStartExpression(Current.Kind)
                    || StartsDeclaration(includeCommaSpanningBindingPatterns: true))
                {
                    OwnSameLineItem(Current);
                    break;
                }
            }
            else if (!StartsNextExpressionListSlot(allowNewlineSeparator))
            {
                break;
            }

            exprs.Add(ParseExpression());
        }

        return exprs;
    }

    private void ReportUnsupportedSemicolon(Token token)
        => ReportErrorAt(DiagnosticCode.UnsupportedSemicolon, UnsupportedSemicolonExpressionMessage, token);

    /// <summary>
    /// True when the current token starts the next slot of the expression list
    /// being parsed. A slot that begins on a later physical line is admitted
    /// silently only in contexts that opt into multiline expression lists
    /// (<paramref name="allowNewlineSeparator"/>); definition bodies opt out,
    /// so an independent newline slot ends them. A slot that begins on the SAME physical line as
    /// the closed expression before it is the SYN-07A separator error: it is
    /// reported at its first token and then admitted anyway (recovery as a
    /// slot boundary), so whitespace never silently creates structure and the
    /// list keeps the shape the programmer wrote.
    /// Tokens that begin a declaration never start a slot: the algorithm loop
    /// owns those forms, their diagnostics, and the same-line row check.
    /// Only tokens that start a new independent expression reach this decision.
    /// A token that legally continues the current expression is consumed
    /// before this check runs: a '(' or '{' after a callable target on the
    /// same physical line is a call delimiter handled by
    /// <see cref="ParsePostfix"/> (`F (1, 2)` is the call `F(1, 2)`), a
    /// binary operator follows the central continuation policy (`F(1 -2)` is the one
    /// argument `1 - 2`), and a leading '.' continues a dot chain across
    /// lines. A physical newline never continues a closed expression into a
    /// call, so `F` newline `(1, 2)` reaches this check and separates as the
    /// expression list `F, (1, 2)`; non-callable targets never become calls,
    /// so `2 (3)` reaches it too — and is the separator error.
    /// </summary>
    private bool StartsNextExpressionListSlot(bool allowNewlineSeparator)
    {
        if (!IsSamePhysicalLineAsPreviousToken() && !allowNewlineSeparator)
            return false;

        if (!CanStartExpression(Current.Kind))
            return false;

        // Tokens that begin a declaration never start a slot: the algorithm
        // loop owns those forms and their diagnostics. The binding-pattern arm
        // is always included here — an expression list's commas are consumed
        // BEFORE this check runs, so any comma run after the candidate belongs
        // to the candidate's own form.
        if (StartsDeclaration(includeCommaSpanningBindingPatterns: true))
            return false;

        if (IsSamePhysicalLineAsPreviousToken())
        {
            // SYN-07A: whitespace never separates two slots. Report at the
            // second item's first token and recover it as the next slot.
            ReportUnseparatedSameLineItem(Current);
            return true;
        }

        return true;
    }

    /// <summary>
    /// THE declaration-starter relation for boundary decisions: true when the
    /// tokens at the current position begin a declaration the algorithm loop
    /// owns — an <c>open</c> declaration, a property definition
    /// <c>Name = ...</c>, a deconstruction binding pattern
    /// <c>x, *y, z = ...</c> (including the collect-marker-led form
    /// <c>*items = ...</c>), a clause definition <c>Name(pattern) = ...</c>,
    /// the invalid-grace property prefix <c>~Name = ...</c>, a
    /// <c>public</c>-led head, or a reserved-literal head (<c>true = …</c>,
    /// <c>false(x) = …</c>) — exactly the forms the loop dispatches as
    /// declarations. Every boundary consumer stops before this relation — the
    /// slot-boundary rule (<see cref="StartsNextExpressionListSlot"/>),
    /// semicolon recovery, open-target recovery
    /// (<see cref="StartsOpenTargetAtom"/>), the star classifier
    /// (<see cref="IsPostfixSpreadMarkerStar"/>), and operand recovery
    /// (<see cref="RecoverAtOperandStart"/>) — so a following declaration stays
    /// intact and its diagnostics stay owned by the algorithm loop; encoding the
    /// set once keeps the decisions from drifting apart (the open-target copy
    /// historically missed the binding-pattern form and tore <c>x, y = 1</c>
    /// apart, and operand recovery must refuse EXACTLY the heads the list loop
    /// stops at, or the loop would re-admit a head the operand parse refused).
    ///
    /// <para><paramref name="includeCommaSpanningBindingPatterns"/> gates the
    /// ONE arm whose lookahead scans across commas (the deconstruction
    /// binding pattern). It is a consumer-position question, not a second
    /// copy of the relation: the slot-boundary rule always includes it (its
    /// expression list consumes commas before the boundary check, so trailing
    /// commas always belong to the candidate), while open-target recovery
    /// includes it after a separator comma or on a later physical line. The
    /// first target on the open line retains the open list's own comma syntax;
    /// an already-owed target that starts a declaration leaves that head intact.
    /// (<c>open A,</c> newline <c>x, y = 1</c> keeps the whole
    /// deconstruction).</para>
    ///
    /// <para>`public` cannot start an expression (<see cref="CanStartExpression"/>),
    /// so the slot-boundary and open-target consumers stop before consulting its arm;
    /// operand recovery is reached AT a `public` after a dangling operator, and its arm
    /// keeps `1 +` newline `public Good = 41` a public declaration. The Star arm is
    /// unreachable through the expression-start filters (including the star
    /// classifier's operand filter) except in operand recovery, and keeps the relation
    /// faithful to the algorithm loop's own declaration dispatch.</para>
    /// </summary>
    private bool StartsDeclaration(bool includeCommaSpanningBindingPatterns)
        => StartsDeclarationAt(NextSignificantIndex(_pos), includeCommaSpanningBindingPatterns);

    /// <summary>
    /// Index form of <see cref="StartsDeclaration"/>: the same relation
    /// evaluated at the significant token at <paramref name="index"/> instead
    /// of the current position. Same-line star classification and operand
    /// recovery consult this relation so a declaration head is never read as
    /// an operand. A physical line-final star never consults it: attachment
    /// alone classifies that star (issue #183), whatever the next line begins —
    /// an attached `A*` completes its row before a following declaration, and a
    /// detached `A *` leaves the declaration to operand recovery.
    /// </summary>
    private bool StartsDeclarationAt(int index, bool includeCommaSpanningBindingPatterns)
    {
        var kind = _tokens[index].Kind;
        return kind == TokenKind.KeywordOpen
            || (kind == TokenKind.Identifier
                && (LookaheadIsEqualsFrom(index)
                    || (includeCommaSpanningBindingPatterns && LookaheadIsBindingPatternAssignmentFrom(index))
                    || LookaheadIsParenEqualsAfterName(index)))
            || (kind == TokenKind.Star
                && includeCommaSpanningBindingPatterns
                && LookaheadIsBindingPatternAssignmentFrom(index))
            || (kind == TokenKind.Tilde && LookaheadThroughTildesToPropertyDefFrom(index))
            || (kind == TokenKind.KeywordPublic
                && (IsPublicOpenAt(index)
                    || IsPublicPropertyDefAt(index)
                    || IsPublicClauseDefinitionAt(index)
                    || IsReservedLiteralDeclarationHeadAt(index)))
            || (kind is TokenKind.KeywordTrue or TokenKind.KeywordFalse
                && IsReservedLiteralDeclarationHeadAt(index));
    }

    private static bool CanStartExpression(TokenKind kind) => kind switch
    {
        TokenKind.Number
        or TokenKind.StringLiteral
        // The opening quote of a double-quoted string with a hole: an operand like any string.
        or TokenKind.InterpolatedStringStart
        or TokenKind.KeywordTrue
        or TokenKind.KeywordFalse
        or TokenKind.Identifier
        or TokenKind.Minus
        or TokenKind.KeywordNot
        or TokenKind.Tilde
        or TokenKind.LParen
        or TokenKind.LBrace
        // '[' starts a NEW list-literal expression at the start of an expression or a
        // slot and on a later physical line; a same-line '[' after a completed
        // expression is consumed by ParsePostfix as postfix selection before the slot
        // rule sees it (`A[1]`, `A [1]` select), while `A, [1]` and `A` newline `[1]`
        // stay the two-slot expression list, and `F[1]` selects from F — never a call.
        or TokenKind.LBracket
        or TokenKind.KeywordOpen => true,
        _ => false,
    };

    // Star disambiguation needs the narrower set of tokens that can actually
    // begin a star's right operand. `open` is included above because the
    // algorithm parser recognizes it as a declaration starter, but ParsePrimary
    // always rejects it in expression position. `not` is included above because
    // it starts an expression, but only at its own tier BELOW the comparisons
    // (NotPrecedence), so it can never begin a multiplication's right operand:
    // a same-line star followed by `not` keeps its invalid-slot recovery;
    // a line-final star is classified by attachment alone, never through a
    // next-line follower (issue #183). This is the
    // ONE classifier for "a star could take this as its operand": it decides
    // spread-marker versus multiplication in IsPostfixSpreadMarkerStar, and it
    // decides whether the misplaced-prefix-star recovery in ParsePrimary has an
    // operand to resume on.
    private static bool CanStartUnaryOperand(TokenKind kind)
        => CanStartExpression(kind) && kind is not (TokenKind.KeywordOpen or TokenKind.KeywordNot);

    // ── Expression parsing (precedence climbing) ────────────────────────────
    //
    // Precedence levels:
    //   1: or            (logical or, left-associative)
    //   2: xor           (logical xor, left-associative)
    //   3: and           (logical and, left-associative)
    //   4: not           (prefix; the ONE prefix operator inside the binary
    //                     ladder. Comparisons bind tighter than `not`, and
    //                     `not` binds tighter than `and`/`xor`/`or`, so
    //                     `not x > 3` is `not (x > 3)` and `not a and b` is
    //                     `(not a) and b`. Parsed by the prefix arm of
    //                     ParseExpressionCore: the operand climbs from the
    //                     comparison level, so `not` can never be a bare operand
    //                     of a tighter operator — `1 + not x`, `a == not b`,
    //                     and `2 ^ not x` are diagnosed and need `(not …)`.)
    //   5: < > <= >= == != (the ONE comparison tier: all six operators CHAIN.
    //                     Consecutive unparenthesized comparison operators at
    //                     one level form ONE Expr.Comparison node with
    //                     adjacent-pair semantics — `a < b == c` compares a
    //                     with b and b with c — never a nested tree, and a
    //                     parenthesized comparison is an ordinary operand that
    //                     never merges into the surrounding chain.)
    //   6: + -           (additive, left-associative)
    //   7: * / div mod   (multiplicative, left-associative)
    //   8: -             (unary prefix minus)
    //   9: ^             (power, right-associative; parsed by ParsePower, not
    //                     the binary loop. Binds tighter than unary minus on
    //                     the LEFT only: the base is postfix-level, while the
    //                     exponent re-enters the unary level — `-2 ^ 2` is
    //                     `-(2 ^ 2)`, `2 ^ -2` stays valid.)
    //  10: . : call      (postfix)

    private Expr ParseExpression(int minPrecedence = 0)
    {
        // Also a recursion chokepoint: every expression level enters here once
        // before descending into the unary/power/postfix layers. (The
        // right-associative `^` recursion is bounded separately: its exponent
        // re-enters ParseUnary, whose entry charge stays live across that
        // recursion — see ParsePower.)
        using var level = EnterNestingLevel();
        return ParseExpressionCore(minPrecedence);
    }

    /// <summary>
    /// The precedence of prefix <c>not</c> inside the binary ladder: above the
    /// logical operators (<c>and</c> is 3) and below the comparisons (5). A
    /// <c>not</c> is admitted exactly when the surrounding level asks for at most
    /// this precedence, and its operand climbs from the comparison level up.
    /// </summary>
    private const int NotPrecedence = 4;

    /// <summary>
    /// The ONE precedence of all six comparison operators. Consecutive comparison
    /// operators at this level extend one <see cref="Expr.Comparison"/> chain.
    /// </summary>
    private const int ComparisonPrecedence = 5;

    private Expr ParseExpressionCore(int minPrecedence = 0)
    {
        Expr lhs;
        if (Current.Kind == TokenKind.KeywordNot && minPrecedence <= NotPrecedence)
        {
            // Prefix `not` at its own tier: the operand is everything that binds
            // tighter than `not` — a comparison chain, its arithmetic, a power —
            // so `not x > 3` is `not (x > 3)` and `not a < b < c` negates the
            // whole chain; a following `and`/`xor`/`or` is then applied to the
            // negation by the loop below. Chains (`not not x`) re-enter this arm
            // through the operand's own level. A `not` where the level demands
            // something tighter (`1 + not x`) falls through to ParseUnary and is
            // diagnosed in ParsePrimary.
            var start = Advance(); // consume 'not'
            lhs = CreateUnaryExpression(start, ParseExpression(NotPrecedence));
        }
        else
        {
            lhs = ParseUnary();
        }

        // The links of the comparison chain being extended at this level, or null
        // while no chain is open (one reference-sized local: the frame stays lean).
        List<ComparisonLink>? links = null;
        while (true)
        {
            var prec = BinaryOperatorPrecedence(Current.Kind);
            if (prec < minPrecedence) break;
            // Grammar-priority continuation uses the ONE syntactic policy.
            // An attached leading minus starts an independent expression;
            // a detached minus can use the preceding binary left operand.
            if (!MayContinueClosedExpression(Current.Kind)) break;

            var operatorToken = Advance(); // consume operator token

            // Binary operators in this loop are left-associative; comparisons
            // accumulate one flat chain. Both parse each right operand above
            // their own tier. `^` lives in ParsePower below the unary level.
            var rhs = ParseExpression(prec + 1);
            if (prec == ComparisonPrecedence)
            {
                // ONE comparison tier: consecutive comparison operators at this
                // level extend ONE chain — `a < b == c` compares a with b and b
                // with c — and never nest, because the right operand climbs from
                // the additive tier and can never absorb a comparison operator.
                // The chain closes at the first token that cannot continue it,
                // so a PARENTHESIZED comparison arriving
                // as `lhs` (`(a < b) == c`) starts a new chain with the group
                // as its first operand instead of merging into it. Spread
                // operands are rejected exactly as for binary operators.
                links = ExtendComparisonChain(links, ref lhs, operatorToken, rhs);
                if (!IsComparisonOperator(Current.Kind) || !MayContinueClosedExpression(Current.Kind))
                {
                    lhs = CreateComparisonExpression(lhs, links, operatorToken);
                    links = null;
                }

                continue;
            }

            // CreateBinaryExpression also rejects spread operands: a spread
            // expression is a whole expression-list slot, never a binary
            // operand (`A* + B`, `1 + values*`, and `value* * 2` are errors;
            // spread the whole expression instead: `(A + B)*`). This is also
            // the documented deterministic rejection for `value**next` and
            // `value** next` (and the detached `value* *` newline `next`): the
            // second star has a right operand, so it is multiplication whose
            // left operand is a spread. An attached line-final `value**` is two
            // spread layers instead, and `next` on the following line its own row.
            lhs = CreateBinaryExpression(BinaryOpOf(operatorToken.Kind), lhs, rhs, operatorToken);
        }

        return lhs;
    }

    /// <summary>
    /// Opens (first link) or extends the comparison chain at the current level with
    /// one more <c>op operand</c> link. Opening the chain rejects a spread FIRST
    /// operand before the link's operand, so diagnostics stay in written order;
    /// every link operand is rejected as it is appended. Kept out of
    /// <see cref="ParseExpressionCore"/> so its temporaries never enlarge that hot
    /// recursive frame (native stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private List<ComparisonLink> ExtendComparisonChain(
        List<ComparisonLink>? links,
        ref Expr first,
        Token operatorToken,
        Expr operand)
    {
        if (links is null)
        {
            first = RejectMisplacedSpreadOperand(first);
            links = new List<ComparisonLink>(2);
        }

        links.Add(new ComparisonLink(ComparisonOpOf(operatorToken.Kind), RejectMisplacedSpreadOperand(operand)));
        return links;
    }

    /// <summary>
    /// Closes one comparison chain: constructs the node over its first operand and
    /// links and applies the chain-depth guard. <paramref name="operatorToken"/> is the
    /// chain's LAST operator, the position a chain-depth rejection is reported at.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr CreateComparisonExpression(Expr first, List<ComparisonLink> links, Token operatorToken)
        => GuardComparisonChainDepth(ComparisonFrom(first, links), operatorToken);

    /// <summary>
    /// Builds one binary node: rejects spread operands (with unwrap
    /// recovery), constructs, and applies the chain-depth guard. Kept out of
    /// <see cref="ParseExpressionCore"/> so its call temporaries never
    /// enlarge that hot recursive frame (native stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr CreateBinaryExpression(BinaryOp op, Expr lhs, Expr rhs, Token operatorToken)
    {
        lhs = RejectMisplacedSpreadOperand(lhs);
        // A spread right operand of a `*` whose operand starts on a LATER line is the
        // one place the line-final star law (issue #183: a DETACHED line-final star is
        // multiplication) turns two intended spread rows (`A *` newline `B*`) into a
        // multiplication with a spread operand: the detached line-final star continued
        // as multiplication onto the next row. The
        // structured code is the ordinary misplaced-spread rejection; only the
        // explanation names the cause and distinguishes the possible repairs.
        rhs = RejectMisplacedSpreadOperand(
            rhs,
            op == BinaryOp.Mul && rhs is Expr.SequenceSpread && IsLineFinalOperator(operatorToken)
                ? LineFinalStarContinuationDiagnostic
                : MisplacedSpreadDiagnostic);
        var binary = BinaryFrom(op, lhs, rhs);
        return GuardExpressionChainDepth(binary, operatorToken, lhs, rhs);
    }

    /// <summary>
    /// True when the operand written after <paramref name="operatorToken"/> begins on a
    /// later physical line — the operator is the last significant token of its line.
    /// Decided from the TOKEN stream (the operand's first significant token), never from
    /// the operand node's span: a grouped operand such as <c>(</c> newline <c>B)</c>
    /// begins at its parenthesis whatever span the unwrapped node carries (a bare name
    /// keeps its identifier span, see <see cref="WithGroupExtent"/>). The operator is a
    /// real lexer token, so its index is recovered by a binary search over the strictly
    /// increasing token positions; only the rare misplaced-spread rejection pays for it.
    /// </summary>
    private bool IsLineFinalOperator(Token operatorToken)
    {
        var low = 0;
        var high = _tokens.Count - 1;
        while (low < high)
        {
            var middle = low + ((high - low) >> 1);
            if (_tokens[middle].Position < operatorToken.Position)
                low = middle + 1;
            else
                high = middle;
        }

        var operandIndex = NextSignificantIndex(low + 1);
        return _tokens[operandIndex].Line > operatorToken.Line;
    }

    // The precedence of every operator token the precedence-climbing loop
    // handles, or -1. `^` (TokenKind.Caret) is deliberately absent: power binds
    // tighter than the prefix-unary tier on the left, so it is parsed by
    // ParsePower between the unary and postfix levels, never by the loop. Its
    // physical-line continuation behavior is kept identical to the loop's
    // binary operators through its own ContinuationPolicy row. `not` is absent
    // as well: it is the prefix tier 4 of this ladder (NotPrecedence), handled
    // by the prefix arm of ParseExpressionCore, so the comparison level and
    // everything above it are numbered from 5. All six comparison operators
    // share ComparisonPrecedence: they are ONE chainable tier, not two.
    private static int BinaryOperatorPrecedence(TokenKind kind) => kind switch
    {
        TokenKind.KeywordOr => 1,
        TokenKind.KeywordXor => 2,
        TokenKind.KeywordAnd => 3,
        TokenKind.EqualEqual or TokenKind.BangEqual
            or TokenKind.LessThan or TokenKind.GreaterThan
            or TokenKind.LessEqual or TokenKind.GreaterEqual => ComparisonPrecedence,
        TokenKind.Plus or TokenKind.Minus => 6,
        TokenKind.Star or TokenKind.Slash or TokenKind.KeywordDiv or TokenKind.KeywordMod => 7,
        _ => -1,
    };

    private static bool IsComparisonOperator(TokenKind kind)
        => BinaryOperatorPrecedence(kind) == ComparisonPrecedence;

    /// <summary>The comparison operator a comparison-tier token spells.</summary>
    private static ComparisonOp ComparisonOpOf(TokenKind kind) => kind switch
    {
        TokenKind.EqualEqual => ComparisonOp.Eq,
        TokenKind.BangEqual => ComparisonOp.Ne,
        TokenKind.LessThan => ComparisonOp.Lt,
        TokenKind.GreaterThan => ComparisonOp.Gt,
        TokenKind.LessEqual => ComparisonOp.Le,
        TokenKind.GreaterEqual => ComparisonOp.Ge,
        _ => throw new InvalidOperationException($"Token kind '{kind}' is not a comparison operator."),
    };

    /// <summary>The binary operator a non-comparison loop token spells.</summary>
    private static BinaryOp BinaryOpOf(TokenKind kind) => kind switch
    {
        TokenKind.KeywordOr => BinaryOp.Or,
        TokenKind.KeywordXor => BinaryOp.Xor,
        TokenKind.KeywordAnd => BinaryOp.And,
        TokenKind.Plus => BinaryOp.Add,
        TokenKind.Minus => BinaryOp.Sub,
        TokenKind.Star => BinaryOp.Mul,
        TokenKind.Slash => BinaryOp.Div,
        TokenKind.KeywordDiv => BinaryOp.IDiv,
        TokenKind.KeywordMod => BinaryOp.Mod,
        _ => throw new InvalidOperationException($"Token kind '{kind}' is not a binary operator of the precedence-climbing loop."),
    };

    // ── Unary ───────────────────────────────────────────────────────────────

    private Expr ParseUnary()
    {
        // Recursion chokepoint for ALL expression nesting: every non-`not`
        // expression level enters through ParseUnary, `-` chains self-recurse
        // here, and the right-associative `^` exponent re-enters here from
        // ParsePower while this frame's charge is still live — that held
        // charge is what bounds power chains (one live unit per `^` level; see
        // ParsePower). A `not` chain charges the same one unit per level
        // through ParseExpression's prefix arm instead.
        using var level = EnterNestingLevel();

        if (Current.Kind == TokenKind.Minus)
        {
            // CreateUnaryExpression also rejects spread operands
            // (`-values*` is an error; spread the whole expression
            // instead: `(-values)*`).
            //
            // The operand recursion re-enters the whole unary level,
            // whose non-prefix arm is ParsePower — so `^` binds tighter
            // than unary minus on the left (`-2 ^ 2` is `-(2 ^ 2)`;
            // write `(-2) ^ 2` to raise the negated base). `not` is NOT a
            // unary-tier operator: it is tier 4 of the binary ladder
            // (ParseExpressionCore), below the comparisons, so a `not`
            // reaching this level is diagnosed by ParsePrimary.
            var start = Advance(); // consume '-'
            if (Current.Kind == TokenKind.EndOfFile || !IsDirectlyAttached(start, Current))
            {
                // A directly adjacent reported character can fill an owed
                // missing operand; it never reconstructs attachment to a real
                // token after a gap, and the source stays lexically erroneous.
                if ((Current.Kind == TokenKind.EndOfFile || IsClosingDelimiter(Current.Kind))
                    && TakeReportedCharacterBeforeCurrent(requiredLine: start.Line) is { } standIn
                    && IsDirectlyAttached(start, standIn))
                    return CreateUnaryExpression(start, PlaceholderAt(standIn));
                ReportErrorAt(DiagnosticCode.UnexpectedToken,
                    "Unary '-' must be directly attached to its operand: write '-2' for negation. Binary subtraction needs a preceding left operand.", start);
                if (Current.Kind == TokenKind.EndOfFile || IsClosingDelimiter(Current.Kind)
                    || StartsDeclaration(includeCommaSpanningBindingPatterns: true))
                {
                    OwnSameLineItem(Current);
                    return new Expr.Num(0) { Span = new SourceSpan(start.Span.End, start.Span.End) };
                }
                // A malformed prefix never becomes an attached unary node.
                // Ordinary operand recovery still preserves declarations/closers.
                return ParseUnary();
            }
            return CreateUnaryExpression(start, ParseUnary());
        }
        return ParsePower();
    }

    /// <summary>
    /// Builds one prefix-unary node: rejects spread operands (with unwrap
    /// recovery) and constructs. Kept out of <see cref="ParseUnary"/> so its
    /// call temporaries never enlarge that hot recursive frame (native
    /// stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr CreateUnaryExpression(Token operatorToken, Expr operand)
    {
        operand = RejectMisplacedSpreadOperand(operand);
        var op = operatorToken.Kind == TokenKind.Minus ? UnaryOp.Minus : UnaryOp.Not;
        return UnaryFrom(op, operand, operatorToken);
    }

    // ── Power (binds tighter than prefix unary on the left) ─────────────────

    /// <summary>
    /// Parses the power level: a postfix base optionally followed by
    /// <c>^ exponent</c>. Grammar: <c>PowerExpr = PostfixExpr [ "^" UnaryExpr ]</c>.
    ///
    /// <para>The layer sits BETWEEN the unary and postfix levels so that `^`
    /// binds tighter than prefix `-` on the LEFT only: the base is
    /// postfix-level (`-2 ^ 2` parses in ParseUnary as `-(2 ^ 2)`; write
    /// `(-2) ^ 2` to raise the negated base), while the exponent re-enters
    /// <see cref="ParseUnary"/>, keeping unary exponents valid (`2 ^ -2`) and
    /// `^` right-associative (`2 ^ 3 ^ 2` is `2 ^ (3 ^ 2)`, because the
    /// exponent's own unary level ends in another ParsePower).</para>
    ///
    /// <para>Physical-line rule: leading and trailing `^` continue through the
    /// shared grammar-priority policy. It cannot start an independent expression;
    /// the existing right-associative precedence is unchanged.</para>
    ///
    /// <para>Nesting accounting: deliberately NO charge of its own. The
    /// exponent recursion re-enters ParseUnary while the current ParseUnary
    /// frame's entry charge is still live, so a `^` chain holds one live unit
    /// per level across two live frames (ParseUnary + ParsePower) — the same
    /// live-unit-per-level cost the former ParseExpression(8) right-recursion
    /// had (ParseExpression + ParseExpressionCore), which keeps the
    /// established power boundary intact: the 256-link expression-chain limit
    /// is still reached before the recursion budget
    /// (ParserNestingDepthTests.PowerBoundary_UsesTheEstablishedExpressionChainMaximum).
    /// Charging here would double-charge every `^` level and shift that
    /// boundary.</para>
    /// </summary>
    private Expr ParsePower()
    {
        var lhs = ParsePostfix();
        if (Current.Kind != TokenKind.Caret || !MayContinueClosedExpression(TokenKind.Caret))
            return lhs;

        var operatorToken = Advance(); // consume '^'
        var rhs = ParseUnary();
        // CreateBinaryExpression applies the shared spread-operand rejection
        // and the expression-chain depth guard, exactly as for the operators
        // of the precedence-climbing loop.
        return CreateBinaryExpression(BinaryOp.Pow, lhs, rhs, operatorToken);
    }

    // ── Postfix (dot, selection, call) ──────────────────────────────────────

    private Expr ParsePostfix()
    {
        var lhs = ParsePrimary();

        while (true)
        {
            switch (Current.Kind)
            {
                case TokenKind.Star when MayContinueClosedExpression(TokenKind.Star)
                    && IsPostfixSpreadMarkerStar():
                    // The star has an explicit same-line closure, or it ends its
                    // physical line attached to its operand (issue #183: an
                    // attached line-final star completes the expression; a
                    // detached one is left to multiplication). Each additional
                    // spread-classified star nests one ordinary spread node.
                    lhs = ParseSpreadMarkerContinuation(lhs);
                    break;

                case TokenKind.LBracket when MayContinueClosedExpression(TokenKind.LBracket)
                    && Current.Position != _ownedSameLineItemPosition:
                    // Postfix selection: expr[s1, ..., sn]. The '[' must be on the
                    // same physical line as the receiver's final token (spaces and
                    // tabs allowed; a '[' on a later line begins a new list literal);
                    // the selector list is an ordinary expression list that may span
                    // lines once the bracket is open. Every completed postfix-level
                    // expression is a receiver — a name, a call result, a group, a
                    // capture, a list, a number, a string, a block, a dot edge — and
                    // chained brackets descend (`Grid[0][1]`). A star before the
                    // bracket is never a spread receiver: '[' begins a multiplication
                    // operand, so `A*[0]` is `A * [0]` (the star arm above leaves it).
                    // A selection is never a call target (the call gate below admits
                    // only callable references), so `A[0](1)` is the separator error.
                    // A '[' that a recovery already owns stays that recovery's next
                    // slot, never a selection of the recovered operand.
                    lhs = ParseSelectionContinuation(lhs);
                    break;

                case TokenKind.Colon when MayContinueClosedExpression(TokenKind.Colon)
                    && !IsAtInterpolationHoleLevel:
                    // The RETIRED colon selection `expr:selector` (October 2026): it is
                    // reported with its migration diagnostic and recovered as the
                    // equivalent selection, so later rows keep parsing and tooling keeps
                    // a truthful tree. A ':' at interpolation-hole level is the hole's
                    // own report (no format specifiers).
                    lhs = ParseRetiredColonSelection(lhs);
                    break;

                case TokenKind.Tilde when MayContinueClosedExpression(TokenKind.Tilde):
                    // Recovery only. A bare name consumes its same-line
                    // postfix-Grace run in ParsePrimary, so a same-line tilde
                    // reaching this loop is attached to a completed COMPOUND
                    // operand (`f(x)~`, `(x)~`, `[1]~`, `5~`), on which Grace
                    // is not defined. Report once over the whole run and
                    // discard every marker in it; the loop then resumes
                    // ordinarily: a following dot still builds the ordinary
                    // dot edge (`(x + y)~.t` keeps a graceless DotCall), a
                    // same-line operand is a recovery-owned item that the
                    // separator rule does not report again (`f(x)~ c` is
                    // never the prefix-grace slot `~c` — write `f(x), ~c`),
                    // and a token on the next physical line stays the start
                    // of the next row: the run never becomes prefix Grace on
                    // a later line's name.
                    RejectPostfixGraceRunOnCompoundOperand();
                    break;

                case TokenKind.Dot when MayContinueClosedExpression(TokenKind.Dot):
                    // Dot-call syntax: expr.Name or expr.Name(args). The
                    // dot is the one POSTFIX continuation that may cross a
                    // physical newline (method-chain layout); calls, selection
                    // and postfix Grace stay same-line — all encoded in the
                    // continuation policy table.
                    var dotToken = Advance(); // consume '.'
                    lhs = ParseDotCallContinuation(lhs, dotToken);
                    break;

                case TokenKind.LParen or TokenKind.LBrace
                    // A call delimiter continues the callable expression only on
                    // the same physical line: `F (1, 2)` is the call `F(1, 2)`,
                    // while `F` newline `(1, 2)` is the expression list `F, (1, 2)`.
                    // Multiline calls must open the delimiter before the newline
                    // (`F(` ... `)`); an already-open argument list spans lines
                    // normally. Only a callable REFERENCE is a call target (SYN-09):
                    // a name, a graced name, or an ARGUMENTLESS dot edge — the member
                    // reference `(Box.G)(2)` is the member call (DOT-09). A computed
                    // result never is: numbers, calls, blocks, operators, and an
                    // argument-bearing dot edge (`X.Mk(1)()`, `R.M(a){ … }` — a call
                    // result, exactly like `Mk(1)()`) do not pass this gate, so
                    // `2 (3)` reaches the expression-list boundary and is the SYN-07A
                    // separator error — never a call and never multiplication.
                    when (lhs is Expr.Resolve or Expr.DotCall { Args: null } or Expr.Grace)
                        && IsCallArgumentStart():
                    // Direct call: Name(args), Name~(args), or expr.Name(args) already handled above
                    // This handles: Name(args) → Call(Resolve(Name), args)
                    var callToken = Current;
                    // The parser is purely syntactic: argument bundles carry the
                    // ORIGINAL written expressions for every callee, builtins
                    // included — builtin semantics belong to elaboration and the
                    // evaluator/registry, never to argument parsing.
                    var callArgs = ParseCallArgs();
                    // The complete call span: callee through the consumed ')'.
                    // No callee spelling is inspected here. Arity belongs to the
                    // callable that lexical resolution SELECTS, which only the
                    // evaluator knows, so `if(1, 2)` is diagnosed exactly like
                    // `count(1, 2, 3)`: at the binding boundary, against the
                    // resolved signature, reported on this same call span.
                    var call = CallFrom(lhs, callArgs, lhs);
                    lhs = GuardExpressionChainDepth(call, callToken, lhs);
                    break;

                default:
                    return lhs;
            }
        }
    }

    /// <summary>
    /// Parses the postfix selector list <c>[s1, ..., sn]</c> after a completed receiver and builds
    /// the selection node. The bracket content is the list literal's production — an ordinary
    /// expression list: zero or more slots separated by commas (or newlines once the bracket is
    /// open), explicit spread slots included (<c>Data[Indexes*]</c>), the separator rule inside
    /// (<c>Data[0 1]</c>), owned-closer recovery, and the cumulative nesting budget. The chain
    /// depth is the receiver's: selector slots are delimited and each starts at depth zero. Kept
    /// out of <see cref="ParsePostfix"/> so its locals never enlarge that hot recursive frame.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParseSelectionContinuation(Expr lhs)
    {
        var openBracket = Advance(); // consume '['
        List<Expr> selectors;
        using (EnterDelimitedProduction(TokenKind.RBracket, SelectionNestingSurcharge))
        {
            selectors = Current.Kind == TokenKind.RBracket
                ? []
                : ParseExpressionListOperand(allowNewlineSeparator: true);
        }

        ExpectCloser(TokenKind.RBracket);
        var selection = SelectionFrom(lhs, OutputBundle.From(selectors));
        return GuardExpressionChainDepth(selection, openBracket, lhs);
    }

    /// <summary>
    /// The migration diagnostic of the RETIRED colon selection.
    /// </summary>
    private const string RetiredColonSelectionMessage =
        "':' selection is not KatLang syntax. Select with postfix brackets on the receiver's line: write 'Pair[0]' for 'Pair:0', 'Grid[0][1]' for 'Grid:0:1', and 'Data()[0]' for 'Data():0'.";

    /// <summary>
    /// Reports a same-line retired colon selection <c>expr:selector</c> with
    /// <see cref="DiagnosticCode.RetiredColonSelection"/> and recovers it as the selection it
    /// meant: the old selector PRIMARY (a name, a prefix-Grace name, number, string, Boolean, group,
    /// list or block on the same line) becomes the one selector slot, so <c>Pair:0</c> recovers to <c>Pair[0]</c>.
    /// When no selector primary follows on the line the ':' alone is reported and the receiver is
    /// kept. A spread receiver (<c>A*:0</c>: the star before a ':' classifies as a spread marker)
    /// is unwrapped silently, so the colon is the source's one diagnostic.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParseRetiredColonSelection(Expr lhs)
    {
        var colonToken = Advance(); // consume ':'
        while (lhs is Expr.SequenceSpread spread)
            lhs = spread.Operand;

        if (!IsSamePhysicalLineAsPreviousToken() || !CanStartRetiredColonSelector(Current.Kind))
        {
            ReportErrorAt(DiagnosticCode.RetiredColonSelection, RetiredColonSelectionMessage, colonToken);
            return lhs;
        }

        var selector = ParsePrimary();
        ReportRetiredColonSelection(colonToken);
        var selection = SelectionFrom(lhs, [selector]);
        return GuardExpressionChainDepth(selection, colonToken, lhs);
    }

    /// <summary>The retired colon diagnostic spanning the ':' through its old selector (the last consumed token).</summary>
    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private void ReportRetiredColonSelection(Token colonToken)
        => ReportError(DiagnosticCode.RetiredColonSelection, RetiredColonSelectionMessage, MakeSpan(colonToken));

    /// <summary>The tokens that began the retired colon form's selector PRIMARY (<c>xs:~i</c> included).</summary>
    private static bool CanStartRetiredColonSelector(TokenKind kind)
        => kind is TokenKind.Identifier or TokenKind.Number or TokenKind.StringLiteral
            or TokenKind.InterpolatedStringStart or TokenKind.KeywordTrue or TokenKind.KeywordFalse
            or TokenKind.LParen or TokenKind.LBracket or TokenKind.LBrace or TokenKind.Tilde;

    /// <summary>
    /// THE star classifier: true when the current star, after a completed expression, is
    /// the postfix spread marker, false when it is binary multiplication. Purely
    /// syntactic — no value, name, type, or arity participates.
    /// <para>A star that is the FINAL significant token of its physical line — EOF, a
    /// later-line token, closer, or declaration next, across trailing comments and blank
    /// lines — is classified by ATTACHMENT (issue #183 refinement of Q-65, decided
    /// 2026-10-14): an attached <c>expr*</c> is the spread marker and COMPLETES the
    /// expression, so the canonical newline rule then lets the next line begin an
    /// independent row or declaration (<c>A*</c> newline <c>B</c> is two rows); a detached
    /// <c>expr *</c> is multiplication that leaves the expression INCOMPLETE, so it continues
    /// onto the next line (<c>A *</c> newline <c>B</c> is <c>A * B</c>) and a declaration
    /// there is protected by operand recovery. Attachment is the exact source-offset
    /// adjacency of <see cref="IsDirectlyAttached"/> to the token the preceding expression
    /// ends with (<see cref="OperandEndBeforeStar"/>: the operand's last token, a reported
    /// character standing in as the operand, or the previous star of a run) — positions,
    /// never token adjacency after skipped tokens are removed: a reported character between
    /// the operand and the star leaves it detached (<c>A@*</c>), while comments, blank lines,
    /// and reported characters AFTER the star change nothing.</para>
    /// <para>A star with a same-line follower keeps the spacing-independent rule: same-line
    /// operand syntax multiplies (<c>A*B</c>, <c>A* B</c>, <c>A *B</c>, <c>A * B</c>, and
    /// <c>A*[0]</c>), while explicit comma/closer/fluent-dot/chained-spread syntax closes a
    /// spread, whose attachment <see cref="ParseSpreadMarkerContinuation"/> then checks
    /// (<c>F(A *)</c> is the malformed marker). Existing same-line malformed follower
    /// recovery remains diagnostic-only.</para>
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private bool IsPostfixSpreadMarkerStar()
    {
        var starIndex = NextSignificantIndex(_pos);
        var nextIndex = NextSignificantIndex(starIndex + 1);
        var next = _tokens[nextIndex];
        // Issue #183 (refining Q-65): a physical line-final star (EOF included) is
        // classified by attachment — attached spreads and completes, detached multiplies.
        if (next.Kind == TokenKind.EndOfFile || next.Line != _tokens[starIndex].Line)
            return IsDirectlyAttached(OperandEndBeforeStar(starIndex), _tokens[starIndex]);
        if (!CanStartUnaryOperand(next.Kind))
            return true;
        if (StartsDeclarationAt(nextIndex, includeCommaSpanningBindingPatterns: true))
            return true;

        // A Grace run followed by a dot cannot begin a multiplication RHS:
        // Grace needs a bare name. Keep the spread and let postfix recovery
        // reject the annotation on that non-name operand. Inspect the whole
        // run structurally, so `x*~.F`, `x*~ .F`, and `x*~~.F` recover alike;
        // attachment must never classify a star that has a same-line follower.
        if (next.Kind != TokenKind.Tilde)
            return false;
        do
        {
            nextIndex = NextSignificantIndex(nextIndex + 1);
        }
        while (_tokens[nextIndex].Kind == TokenKind.Tilde);
        return _tokens[nextIndex].Kind == TokenKind.Dot;
    }

    /// <summary>
    /// The token the completed expression before the star at <paramref name="starIndex"/> ENDS
    /// with — the reference of the postfix star's attachment test. That is the significant
    /// token before the star (the operand's last token, or the previous star of a run), except
    /// when the token directly before the star is a reported character that the operand
    /// recovery claimed as the operand itself (<c>X = @*</c>, <see cref="TakeReportedCharacterBeforeCurrent"/>):
    /// the grammar's significant-token view skips it, yet it IS the operand, so the star's
    /// attachment is measured against it. Exact source offsets still decide: an unclaimed
    /// reported character between an operand and its star (<c>A@*</c>) leaves the star detached.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private Token OperandEndBeforeStar(int starIndex)
    {
        if (starIndex > 0
            && _tokens[starIndex - 1] is { Kind: TokenKind.Bad } rawBefore
            && rawBefore.Position == _lastReportedCharacterFill)
            return rawBefore;
        return Previous;
    }

    /// <summary>
    /// Builds one spread node for an attached postfix `*` marker: rejects
    /// nothing (spread placement is validated by the consuming positions),
    /// records the exact spread-marker span, and applies the chain-depth
    /// guard. Kept out of <see cref="ParsePostfix"/> so its call temporaries
    /// never enlarge that hot recursive frame (native stack-margin
    /// calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr CreateSpreadExpression(Expr operand, Token starToken)
    {
        var spreadNode = SequenceSpreadFrom(operand, starToken);
        return GuardExpressionChainDepth(spreadNode, starToken, operand);
    }

    /// <summary>
    /// Consumes the postfix spread marker that
    /// <see cref="IsPostfixSpreadMarkerStar"/> has already classified as a
    /// spread (the current star) and enforces the marker attachment law: the
    /// marker must be DIRECTLY attached to the completed expression's last
    /// token (<see cref="IsDirectlyAttached"/> — the same source-offset
    /// adjacency the collect marker and Grace require). A star with a
    /// same-line follower was classified WITHOUT consulting attachment, so its
    /// attachment is checked only here, AFTER classification: `values *,` and
    /// `F(values *)` are malformed markers, never multiplication. A physical
    /// line-final star was classified BY attachment (issue #183), so it
    /// reaches this method attached unless it continues a malformed run:
    /// `values*` newline `other` is the spread row `values*` followed by the
    /// row `other`, while `values *` newline `other` never arrives here — it
    /// is the multiplication `values * other`. A detached marker decorates
    /// nothing: the diagnostic spans the operand through the last consumed
    /// star, the whole SAME-LINE run of further spread-classified stars is
    /// consumed with it (one diagnostic per malformed run; an attached
    /// line-final star ends the run, `values **` at the end of a line
    /// included), and the recovered tree keeps the plain operand — no
    /// <see cref="Expr.SequenceSpread"/> is built from a detached marker,
    /// mirroring the collect marker's never-a-collecting-binding recovery.
    /// Kept out of <see cref="ParsePostfix"/> so its locals never enlarge that
    /// hot recursive frame (native stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParseSpreadMarkerContinuation(Expr operand)
    {
        var operandEnd = OperandEndBeforeStar(NextSignificantIndex(_pos));
        var starToken = Advance(); // consume the spread marker '*'
        if (IsDirectlyAttached(operandEnd, starToken))
            return CreateSpreadExpression(operand, starToken);

        // Detached marker: consume the rest of the malformed same-line run
        // (further stars that would themselves be spread markers), report
        // once, and recover to the operand itself. The run never crosses a
        // physical line: after an attached line-final star of the run, a star
        // on the next line is classified on its own.
        while (Current.Kind == TokenKind.Star
            && IsSamePhysicalLineAsPreviousToken()
            && IsPostfixSpreadMarkerStar())
        {
            Advance();
        }

        ReportErrorFrom(
            DiagnosticCode.InvalidSpreadMarker,
            SpreadMarkerAttachmentDiagnostic(operand),
            operand);
        // The malformed run owns the boundary after it: whatever follows a
        // detached star on the same line is explained by this diagnostic, not
        // by a second separator-rule diagnostic.
        OwnSameLineItem(Current);
        return operand;
    }

    /// <summary>
    /// Parses one dot edge after its '.' token has been consumed:
    /// <c>expr.Name</c> and <c>expr.Name(args)</c>. Ordinary written Grace
    /// composes at either name occurrence: <c>expr~.Name</c> arrives with
    /// postfix Grace already wrapped around <paramref name="lhs"/>, while
    /// <c>expr.~Name</c> stores prefix Grace around the fallback/name
    /// occurrence. Every spelling builds the SAME ordinary continuation: an
    /// <see cref="Expr.DotCall"/> storing its lexical-fallback identity as
    /// <c>Resolve(Name)</c> spanned at the member identifier (front-end
    /// elaboration may rewrite it to <c>Param(Name)</c>), or the fluent
    /// supply-transition call for a spread receiver. Grace affects only the
    /// individual semantic name occurrence it decorates; the executable
    /// dot-edge semantics are identical after elaboration. Kept out of
    /// <see cref="ParsePostfix"/> so its locals and call
    /// temporaries never enlarge that recursive frame (native stack-margin
    /// calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParseDotCallContinuation(Expr lhs, Token dotToken)
    {
        // Prefix Grace on the member/fallback occurrence. The first marker is
        // recognized when it is attached to the dot; once that syntax has
        // begun, repeated markers use the ordinary prefix accumulation law,
        // and the marker attachment law applies as for every prefix run: the
        // markers are contiguous and the last one is attached to the member
        // name (`a.~t`, `a.~~t`; never `a.~ t`), a gap reporting the
        // attachment diagnostic and recovering to the plain member.
        // A declaration head cannot supply a member name after a trailing dot
        // (the head begins the next line) or a LEADING dot (Q-65: the head shares
        // the dot's line). A mid-line dot is no row start: `X = A.b = 3` keeps
        // the member `b` and the same-line stray-'=' diagnostic. Check before
        // Grace so rejected heads keep their own marker and diagnostic ownership.
        if ((!IsSamePhysicalLineAsPreviousToken() || PreviousLeadsItsPhysicalLine())
            && StartsDeclaration(includeCommaSpanningBindingPatterns: true))
        {
            if (TakeReportedCharacterBeforeCurrent() is null)
            {
                ReportErrorAt(
                    DiagnosticCode.UnexpectedToken,
                    !IsSamePhysicalLineAsPreviousToken()
                        ? "Expected property name after '.'. The next line begins a declaration, which never continues an expression."
                        : "Expected property name after '.'. A declaration head cannot be a dot member.",
                    dotToken);
            }
            OwnSameLineItem(Current);
            return lhs;
        }

        Token? memberGraceStart = null;
        var memberGraceWeight = 0;
        var memberGraceAttached = true;
        if (Current.Kind == TokenKind.Tilde && IsDirectlyAttached(dotToken, Current))
        {
            memberGraceStart = Current;
            var lastMarker = dotToken; // the first marker is attached to the dot
            while (Current.Kind == TokenKind.Tilde && Current.Line == memberGraceStart.Line)
            {
                memberGraceAttached &= IsDirectlyAttached(lastMarker, Current);
                lastMarker = Advance();
                memberGraceWeight--;
            }

            if (Current.Kind != TokenKind.Identifier || !IsSamePhysicalLineAsPreviousToken())
            {
                ReportErrorAcross(
                    DiagnosticCode.InvalidGraceMarker,
                    GraceEligibilityMessage,
                    memberGraceStart, Previous);
                // The rejected run owns the boundary after it (`a.~~ 7` blames
                // the run once; `7` is not additionally a separator error).
                OwnSameLineItem(Current);
                return lhs;
            }

            memberGraceAttached &= IsDirectlyAttached(lastMarker, Current);
        }

        if (Current.Kind != TokenKind.Identifier)
        {
            if (TakeReportedCharacterBeforeCurrent() is null)
            {
                ReportError(DiagnosticCode.UnexpectedToken, "Expected property name after '.'.");
                // An explicit dangling-dot report owns the following boundary. A
                // silent member fill already used its character and cannot also
                // supply the comma before an independent next item (`A.@ 1`).
                OwnSameLineItem(Current);
            }
            return lhs;
        }

        var propNameToken = Advance();
        var propName = propNameToken.StringValue!;

        Expr lexicalFallback = ResolveAt(propNameToken);
        if (!memberGraceAttached)
        {
            ReportErrorAcross(
                DiagnosticCode.InvalidGraceMarker,
                GraceMarkerAttachmentDiagnostic(propName),
                memberGraceStart!, propNameToken);
        }
        else if (memberGraceWeight != 0)
        {
            lexicalFallback = GraceFrom(lexicalFallback, memberGraceWeight, memberGraceStart!);
        }

        if (lhs is Expr.SequenceSpread)
        {
            // Fluent supply transition: `operand*.Target(...)` consumes the
            // spread items as the leading call arguments and lowers to the
            // ordinary lexical call `Target(operand*, ...)`. Postfix Grace on
            // a spread receiver is rejected before this arm. Prefix Grace on
            // the member is ordinary Grace on that lexical callee occurrence,
            // so preserve the same expression when lowering the fluent form.
            return ParseSpreadReceiverContinuation(lhs, dotToken, lexicalFallback);
        }

        OutputBundle? args = IsCallArgumentStart() ? ParseCallArgs() : null;
        var dotCall = DotCallFrom(lhs, propNameToken, args, lexicalFallback);
        return GuardExpressionChainDepth(dotCall, dotToken, lhs);
    }

    /// <summary>
    /// Parses the dot continuation after a spread expression — the fluent
    /// supply-transition form <c>operand*.Target(...)</c>. The spread
    /// receiver is an item SUPPLY, not a value, so <c>.Target</c> is not
    /// property access on the spread and structural receiver lookup never
    /// applies: the form lowers at parse time to the ordinary lexical call
    /// <c>Target(operand*, ...)</c> with the spread as the leading
    /// argument slot — the exact AST the non-fluent spelling builds — so
    /// both spellings share one evaluation path and the operand is
    /// evaluated exactly once. Further postfix continuations chain on the
    /// call result (<c>x.Calculate*.Target.Other</c>).
    /// Kept OUT of <see cref="ParsePostfix"/> so its locals and call
    /// temporaries never enlarge that hot recursive frame — the parser's
    /// nesting budget is calibrated against the native stack boundary.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParseSpreadReceiverContinuation(Expr spreadReceiver, Token dotToken, Expr callee)
    {
        OutputBundle args = IsCallArgumentStart()
            ? [spreadReceiver, .. ParseCallArgs()]
            : [spreadReceiver];

        var call = CallFrom(callee, args, spreadReceiver);
        return GuardExpressionChainDepth(call, dotToken, spreadReceiver);
    }

    // A '(' or '{' starts call arguments only when it appears on the same
    // physical line as the callable expression's last token. Same-line
    // whitespace continues a call (`F (1, 2)`, `A.B (1)`, `values.map { ... }`);
    // a physical newline never continues a closed expression into a call
    // (`F` newline `(1, 2)` is the expression list `F, (1, 2)`). Multiline calls
    // must open the delimiter before the newline; an already-open argument
    // list or brace block spans lines normally.
    private bool IsCallArgumentStart()
        => Current.Kind is TokenKind.LParen or TokenKind.LBrace
            && MayContinueClosedExpression(Current.Kind);

    /// <summary>
    /// Parses call arguments to an <see cref="OutputBundle"/> of the original
    /// written argument expressions: <c>(args)</c> or a trailing brace block.
    /// No transparent argument <see cref="Algorithm"/> is created — the
    /// receiver-owning call consumes the bundle directly and each slot
    /// evaluates in the caller's lexical context.
    /// Ordinary parentheses inside the list mean ordinary parenthesized expression
    /// syntax: a slot written <c>((expr))</c> is the slot <c>expr</c> (redundant
    /// grouping is erased by <see cref="IsRedundantGrouping"/>), while <c>(a, b)</c>
    /// is one sequence-valued slot.
    /// </summary>
    private OutputBundle ParseCallArgs()
    {
        if (Current.Kind == TokenKind.LParen)
        {
            var start = Current;
            Advance(); // consume '('
            // Heavy production: call argument lists run the call + algorithm
            // machinery each nesting level (see the recursion-budget notes).
            // The parenthesized parse mode is shared with ordinary parens so
            // algorithm-level declarations keep the same targeted rejection
            // diagnostics and recovery.
            ParsedAlgorithmBody body;
            using (EnterDelimitedProduction(TokenKind.RParen, CallArgsNestingSurcharge))
            {
                body = ParseParenthesizedBodyParts();
            }

            ExpectCloser(TokenKind.RParen);
            if (!body.HasDeclarations)
                return OutputBundle.From(body.Output);

            // Error recovery only: declarations inside call arguments were
            // already rejected with the targeted parenthesized-declaration
            // diagnostic. Retain them for downstream tooling as one recovery
            // AlgorithmExpr argument — the same recovery shape parenthesized
            // primaries use — instead of silently discarding the declarations.
            return [AlgorithmExprFrom(CreateAlgorithm(body), start)];
        }
        else
        {
            // Trailing brace-block: Algo{e} → Algo({e})
            // The brace content is a scope-owning algorithm that becomes the
            // single Expr.AlgorithmExpr argument slot, so the block is
            // resolvable as an algorithm by ResolveAlg(.algorithmExpr ...).
            // Charges the call surcharge PLUS the block surcharge: this form
            // runs both machineries per level.
            var start = Current;
            Advance(); // consume '{'
            Algorithm innerAlg;
            using (EnterDelimitedProduction(TokenKind.RBrace, CallArgsNestingSurcharge + BlockNestingSurcharge))
            {
                innerAlg = ParseScopedAlgorithm();
            }

            ExpectCloser(TokenKind.RBrace);
            var blockExpr = AlgorithmExprFrom(innerAlg, start);
            return [blockExpr];
        }
    }

    // ── Primary expressions ─────────────────────────────────────────────────

    /// <summary>
    /// PARENTHESES GROUP SYNTAX; THEY DO NOT INTRODUCE A SEMANTIC BOUNDARY. A
    /// parenthesized group whose content is exactly ONE non-spread expression slot
    /// is redundant grouping: it is that expression — whatever its kind (a name, a
    /// graced name, a literal, a call, a dot edge, a selection, a list, a block, a
    /// nested group, `()`), so <c>(E)</c> and <c>((E))</c> elaborate to the very
    /// node <c>E</c> does, and no downstream layer (binding, caching, dot-call
    /// receivers, patterned calls, optimizers) can observe the parentheses. The
    /// only groups that survive as an <see cref="Expr.Capture"/> are the ones whose
    /// parentheses DO something: several written slots (<c>(1, 2)</c>, a sequence
    /// value) and a lone spread slot (<c>(A*)</c>, the capture of an item supply
    /// into one value — <c>capture : Supply -> Value</c>; a spread is a slot-level
    /// construct, not a value expression, so its group is not redundant). This
    /// decision never depends on the kind of the inner expression.
    /// </summary>
    private static bool IsRedundantGrouping(ParsedAlgorithmBody body)
        // Declarations inside parentheses are a parse error (reported at the
        // declaration by the parenthesized body parser), so parts carrying
        // opens or properties only reach this point during error recovery;
        // they keep a scope-owning recovery tree for downstream tooling.
        => !body.HasDeclarations
            && body.Output.Count == 1
            && body.Output[0] is not Expr.SequenceSpread;

    /// <summary>
    /// Gives an expression unwrapped from redundant grouping parentheses the group's full
    /// written extent as its source span. Grouping changes neither the AST shape nor the
    /// meaning of the inner expression, but the parentheses ARE the syntactic expression
    /// the surrounding construct consumes, so diagnostics and navigation anchored on that
    /// expression must be able to point at `(1)`, not merely at `1`. Nested redundant groups
    /// accumulate naturally: each level re-spans the same node to its own extent, so
    /// `((1))` spans all five characters. The span is the ONLY thing that changes: the copy
    /// keeps every other init-only fact of the node, and a registered operator/postfix chain
    /// depth is transferred to it so the chain guard keeps counting through the group.
    /// A NAME OCCURRENCE is the one exception: the span of an <see cref="Expr.Resolve"/>
    /// (and of the graced occurrence <see cref="Expr.Grace"/> wraps) IS the identifier
    /// occurrence the semantic model builds reference, hover, and rename sites from,
    /// so <c>(a)</c> keeps the exact span of <c>a</c> — a source-position fact only;
    /// the node is the same either way.
    /// </summary>
    private Expr WithGroupExtent(Expr inner, SourceSpan groupSpan)
    {
        if (inner is Expr.Resolve or Expr.Grace)
            return inner;

        var widened = inner with { Span = groupSpan };
        if (_expressionChainDepths.TryGetValue(inner, out var chainDepth))
            _expressionChainDepths[widened] = chainDepth;
        return widened;
    }

    private Expr ParsePrimary()
    {
        // Operand-start recovery, decided before any operand is consumed: a missing
        // operand a reported character stands in, and a declaration head that a line
        // ending in an incomplete expression would otherwise swallow (see
        // RecoverAtOperandStart). Only reached off the common path: a token that
        // cannot begin an operand, one on a later line, or one sharing the line of a
        // LEADING continuation token (Q-65). A mid-line operator, comma, or dot is
        // not a row start, so `X = a + b = c` keeps the same-line stray '='.
        if ((!CanStartExpression(Current.Kind) || !IsSamePhysicalLineAsPreviousToken()
                || (GetContinuationPolicy(Previous.Kind).CanContinueAcrossLine
                    && PreviousLeadsItsPhysicalLine()))
            && RecoverAtOperandStart() is { } recovered)
            return recovered;

        switch (Current.Kind)
        {
            case TokenKind.Number:
                {
                    var token = Advance();
                    return NumAt(token);
                }

            case TokenKind.StringLiteral:
                {
                    var token = Advance();
                    return StringLiteralAt(token);
                }

            case TokenKind.InterpolatedStringStart:
                return ParseInterpolatedString();

            case TokenKind.KeywordTrue:
            case TokenKind.KeywordFalse:
                {
                    var token = Advance();
                    return BoolLiteralAt(token);
                }

            case TokenKind.Identifier:
                {
                    var token = Advance();
                    // Postfix grace '~' is same-physical-line only: a '~'-led
                    // line is a prefix-grace expression of its own, never a
                    // continuation of the previous line's identifier. A tilde
                    // before a following dot is still ordinary postfix Grace
                    // on this same bare name; the postfix loop then builds the
                    // ordinary dot continuation. The run must be directly
                    // attached (`x~`, never `x ~`): ParsePostfixGraceOnName
                    // enforces the marker attachment law.
                    if (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
                        return ParsePostfixGraceOnName(token);
                    return ResolveAt(token);
                }

            case TokenKind.Tilde:
                return ParsePrefixGracePrimary();

            case TokenKind.LParen:
                {
                    var start = Current;
                    Advance(); // consume '('
                    // Heavy production: each group level runs the block/algorithm
                    // machinery, so it carries a calibrated surcharge on the shared
                    // cumulative recursion budget.
                    ParsedAlgorithmBody body;
                    using (EnterDelimitedProduction(TokenKind.RParen, GroupNestingSurcharge))
                    {
                        body = ParseParenthesizedBodyParts();
                    }

                    ExpectCloser(TokenKind.RParen);

                    // Empty parentheses `()` construct the empty sequence value.
                    if (!body.HasDeclarations && body.Output.Count == 0)
                        return EmptySequenceFrom(start);

                    // PARENTHESES GROUP SYNTAX: a group of exactly one non-spread
                    // slot is the slot's expression itself, whatever its kind
                    // (`(x)` is `x`, `((1, 2))` is `(1, 2)`, `(())` is `()`), so
                    // no later layer can tell the group from its content. The
                    // unwrapped expression keeps its meaning and takes the group's
                    // full written extent as its source span (see WithGroupExtent).
                    if (IsRedundantGrouping(body))
                        return WithGroupExtentFrom(body.Output[0], start);

                    // Declarations inside parentheses are a parse error (reported
                    // at the declaration by the parenthesized body parser), so
                    // parts carrying opens or properties only reach this point
                    // during error recovery. The recovery tree keeps the parsed
                    // declarations truthfully as a scope-owning algorithm
                    // expression — the form the diagnostic tells the user to
                    // write (`{ ... }`) — because a Capture's OutputBundle is
                    // declaration-free by construction.
                    if (body.HasDeclarations)
                        return AlgorithmExprFrom(CreateAlgorithm(body), start);

                    // A surviving parenthesized group is a normalized capture
                    // boundary over its ordered written expression slots — a
                    // value/output boundary, not an algorithm.
                    return CaptureFrom(OutputBundle.From(body.Output), start);
                }

            case TokenKind.LBrace:
                {
                    var start = Current;
                    Advance(); // consume '{'
                    // Heavy production (see the LParen arm).
                    Algorithm alg;
                    using (EnterDelimitedProduction(TokenKind.RBrace, BlockNestingSurcharge))
                    {
                        alg = ParseScopedAlgorithm();
                    }

                    ExpectCloser(TokenKind.RBrace);
                    return AlgorithmExprFrom(alg, start);
                }

            case TokenKind.LBracket:
                {
                    // List literal `[e1, ..., en]`. The bracket
                    // content is a pure expression list (spread slots included) —
                    // never an algorithm context, so declarations are not legal
                    // inside brackets and `[]`/`[x]`/`[[x]]` all stay distinct
                    // (no `()`-style normalization or singleton unwrap).
                    // An already-open '[' spans physical lines like '(' and '{'.
                    var start = Current;
                    Advance(); // consume '['
                    // Heavy production (lighter than groups/blocks; see the LParen arm).
                    List<Expr> items;
                    using (EnterDelimitedProduction(TokenKind.RBracket, ListNestingSurcharge))
                    {
                        items = Current.Kind == TokenKind.RBracket
                            ? []
                            : ParseExpressionListOperand(allowNewlineSeparator: true);
                    }

                    ExpectCloser(TokenKind.RBracket);
                    return ListLiteralFrom(items, start);
                }

            case TokenKind.KeywordNot:
                {
                    // A `not` reaching primary position was written where the
                    // surrounding operator demands an operand tighter than the
                    // `not` tier (`1 + not x`, `a == not b`, `2 ^ not x`,
                    // `-not x`). Report the precedence rule AT the keyword, then
                    // recover by parsing the negation as if it were parenthesized
                    // — the tree the writer meant — so the rest of the row and
                    // later declarations keep parsing.
                    var token = Current;
                    ReportErrorAt(DiagnosticCode.UnexpectedToken, MisplacedNotDiagnostic, token);
                    Advance(); // consume 'not'
                    return CreateUnaryExpression(token, ParseExpression(NotPrecedence));
                }

            case TokenKind.KeywordOpen:
                {
                    var token = Current;
                    ReportError(
                        DiagnosticCode.InvalidOpenDeclaration,
                        "'open' is a declaration and cannot be used in expression position.");
                    SkipForRecovery(); // the token after it is a recovery-owned boundary
                    return PlaceholderAt(token); // error placeholder
                }

            case TokenKind.Star:
                {
                    // A prefix '*' reaching expression position is the collect
                    // marker used outside a binding pattern (`x = *values`,
                    // `F(*items)` as a call) or a stray star with no left
                    // operand. Report once for the whole star run, then recover
                    // with the following same-line operand where possible so
                    // `x = *values` degrades to `x = values` and later
                    // declarations keep parsing.
                    var starToken = Current;
                    ReportErrorAt(
                        DiagnosticCode.InvalidCollectMarker,
                        CollectMarkerInExpressionDiagnostic,
                        starToken);
                    Advance(); // consume '*'
                    while (Current.Kind == TokenKind.Star)
                        Advance(); // consume a malformed star run whole, one diagnostic

                    if (CanStartUnaryOperand(Current.Kind)
                        && IsSamePhysicalLineAsPreviousToken())
                        return ParseUnary(); // recovery: the operand the star was attached to

                    // No operand was consumed: the collect-marker diagnostic
                    // owns this boundary, including a following declaration.
                    OwnSameLineItem(Current);
                    return PlaceholderAt(starToken); // error placeholder
                }

            case TokenKind.Semicolon:
                {
                    var token = Current;
                    ReportUnsupportedSemicolon(token);
                    SkipForRecovery(); // the token after it is a recovery-owned boundary
                    return PlaceholderAt(token);
                }

            case TokenKind.Colon:
                {
                    // A ':' reaching primary position has no receiver. ':' is not KatLang
                    // syntax; the common cause is a retired colon selection written on the
                    // line after its receiver.
                    var token = Current;
                    ReportError(
                        DiagnosticCode.RetiredColonSelection,
                        "Unexpected ':'. ':' selection is not KatLang syntax: select with postfix brackets on the receiver's line, as in 'Pair[0]'.");
                    SkipForRecovery(); // the token after it is a recovery-owned boundary
                    return PlaceholderAt(token); // error placeholder
                }

            case TokenKind.Equals:
                {
                    // A '=' reaching primary position has no declaration head before
                    // it on ITS physical line. The usual cause is the declaration-head
                    // line rule (see IsHeadToken): `Foo` newline `(x) = x + 1`, `A`
                    // newline `= 1`, `Foo(x)` newline `= x + 1`, and `x, y` newline
                    // `= 1, 2` keep the previous line as the closed output row it is
                    // and reach this arm with the '='. Report the repair once; the
                    // token after the '=' is a recovery-owned boundary.
                    var token = Current;
                    ReportError(
                        DiagnosticCode.UnexpectedToken,
                        StrayEqualsFollowsSplitHead() ? StrayEqualsDiagnostic : SameLineStrayEqualsDiagnostic);
                    SkipForRecovery();
                    return PlaceholderAt(token); // error placeholder
                }

            default:
                {
                    var token = Current;
                    if (IsClosingDelimiter(token.Kind) && !IsOwedCloser(token.Kind) && IsInsideDelimitedConstruct)
                    {
                        // A closer no open construct is waiting for, met while one IS
                        // open (`(1, ]`, `{1, )}`): the operand is missing, and the
                        // innermost construct reports this very token as its mismatched
                        // closer and closes there (ExpectCloser). Consuming it as junk
                        // would leave the construct open to the end of the file and
                        // swallow every later declaration into it.
                        return PlaceholderAt(token); // error placeholder
                    }

                    ReportError(DiagnosticCode.UnexpectedToken, $"Unexpected {DescribeTokenKind(Current.Kind, includeArticle: false)}.");
                    if (IsOwedCloser(token.Kind) || token.Kind == TokenKind.EndOfFile)
                    {
                        // The token is the closer an ENCLOSING construct is waiting for (a
                        // trailing comma or a missing operand before it: `F(1, )`, `(1 + )`,
                        // `[1, ]`, `{1, }`) or the end of input. Consuming it here would leave
                        // that construct open to the end of the file, swallowing every later
                        // declaration into it. Report only; the owner closes at its closer.
                        return PlaceholderAt(token); // error placeholder
                    }

                    // No construct is open, so a closer here is a top-level stray (rule 3),
                    // and any other token is junk: consume it.
                    SkipForRecovery(); // the token after it is a recovery-owned boundary
                    return PlaceholderAt(token); // error placeholder
                }
        }
    }

    /// <summary>
    /// Operand-start recovery for <see cref="ParsePrimary"/>; null when the operand
    /// parses normally from the current token.
    /// <para>A MISSING OPERAND A REPORTED CHARACTER STANDS IN. The grammar skips the
    /// characters the lexer reported (<see cref="IsSkippedByGrammar"/>), so an operand
    /// written after one continues with the token behind it (<c>!true</c> is
    /// <c>true</c>, <c>1 + @2</c> is <c>1 + 2</c>). When what follows cannot begin the
    /// operand and the surrounding construct takes it next — a closer, the end of input,
    /// <c>,</c>, <c>;</c>, or a token continuing the expression on that line
    /// (<c>(1 + @)</c>, <c>F(1, @)</c>, <c>1 &lt; @ &lt; 2</c>) — the operand is that
    /// character: a silent placeholder at its span, never a second report. Any other
    /// follower is left to the ordinary operand path, which consumes it, so a loop that
    /// hands the same token back to this method always makes progress.</para>
    /// <para>A DECLARATION HEAD IS NEVER AN OPERAND. When the token that demanded this
    /// operand ended its line — a trailing binary operator, <c>,</c>, prefix
    /// <c>-</c> or <c>not</c>, or the <c>=</c> of a definition whose body would start on
    /// the next line — and the next line begins a declaration (<c>1 +</c> newline
    /// <c>Good = 41</c>, <c>x,</c> newline <c>y = 1, 2</c>, <c>A =</c> newline
    /// <c>B = 1</c>), or when that token is a LEADING continuation token whose own line
    /// the declaration shares (Q-65: <c>1</c> newline <c>+ Good = 41</c>), the incomplete
    /// expression is the one error, reported at the token that dangles, and the
    /// declaration is left intact for the body loop that owns it. Taking its name as the
    /// operand would tear a correctly written one-line head apart into an operand plus a
    /// stray <c>=</c> — and no valid program ever has a declaration head in operand
    /// position, so this changes recovery only. A head after a MID-line continuation
    /// token is no row start (<c>X = a + b = c</c>); unless its first token cannot begin
    /// an operand at all (<c>public</c>, a collect <c>*</c>), <see cref="ParsePrimary"/>
    /// does not route it here, so its <c>=</c> keeps the same-line stray-<c>=</c>
    /// diagnostic. The
    /// same relation keeps a declaration out of a same-line star's operand
    /// (<see cref="IsPostfixSpreadMarkerStar"/>), a semicolon's recovery slot, and a
    /// dangling <c>open</c> list. A reported character between the dangling token and the
    /// declaration stands in the operand the same way, so the lexer's report is then the
    /// only one.</para>
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private Expr.Num? RecoverAtOperandStart()
    {
        if (!CanStartExpression(Current.Kind)
            && (IsClosingDelimiter(Current.Kind)
                || Current.Kind is TokenKind.EndOfFile or TokenKind.Comma or TokenKind.Semicolon
                || MayContinueClosedExpression(Current.Kind))
            && TakeReportedCharacterBeforeCurrent(requiredLine:
                Previous.Kind == TokenKind.Bad ? Current.Line : null) is { } standIn)
            return PlaceholderAt(standIn);

        // Only a multiplication star reaches here before the end of input or a closer: a
        // star separated from its left operand at the end of its line (issue #183; an
        // attached line-final star is a spread and never needs an operand).
        if (Previous.Kind == TokenKind.Star
            && (Current.Kind == TokenKind.EndOfFile || IsClosingDelimiter(Current.Kind)))
        {
            var star = Previous;
            ReportErrorAt(DiagnosticCode.UnexpectedToken, "Expected an expression after '*'. A `*` that ends its line separated from its left operand is multiplication and needs a right operand; attach it (`A*`) to spread instead.", star);
            return new Expr.Num(0) { Span = new SourceSpan(star.Span.End, star.Span.End) };
        }

        if (!StartsDeclaration(includeCommaSpanningBindingPatterns: true))
            return null;

        if (TakeReportedCharacterBeforeCurrent() is { } reported)
            return PlaceholderAt(reported);

        var dangling = Previous;
        // A leading operator/comma and the following head may share the next
        // line. Protect that head too; this is an owned recovery boundary.
        OwnSameLineItem(Current);
        var headExplanation = IsSamePhysicalLineAsPreviousToken()
            ? "A declaration head never continues an expression."
            : "The next line begins a declaration, which never continues an expression.";
        ReportErrorAt(
            DiagnosticCode.UnexpectedToken,
            $"Expected an expression after {DescribeTokenKind(dangling.Kind)}. {headExplanation}",
            dangling);
        return new Expr.Num(0) { Span = new SourceSpan(dangling.Span.End, dangling.Span.End) };
    }

    // ── Interpolated strings (STR-02) ───────────────────────────────────────
    // The lexer fixes the structure of every double-quoted string with a hole — its Start
    // token, alternating text runs and holes, its End token, all on one physical line, and
    // every hole closed (an unterminated string is one unterminated StringLiteral token
    // instead) — so the parser only ever recovers INSIDE a hole, whose extent is known.

    private const string EmptyInterpolationHoleDiagnostic =
        "An interpolation hole cannot be empty: write one expression between '{' and '}', or write '{{' and '}}' for literal braces.";

    private const string InterpolationSpreadDiagnostic =
        "An interpolation hole holds one value, and a spread supplies items rather than one value. To write the items as one sequence value, capture them, as in \"{(xs*)}\".";

    private const string InterpolatedPatternDiagnostic =
        "A clause-head pattern needs fixed text, so it cannot contain an interpolated string. Write the text itself: a double-quoted string without holes is a literal pattern, with '{{' and '}}' for literal braces.";

    private const string InterpolatedOpenTargetDiagnostic =
        "An open target must be a literal module URL, so it cannot be an interpolated string. Write the URL itself, in single quotes or in double quotes without holes.";

    /// <summary>
    /// Parses an interpolated string — the current token is its
    /// <see cref="TokenKind.InterpolatedStringStart"/> — through its closing quote: the decoded
    /// head text, then each hole with the decoded text written after it
    /// (<see cref="Expr.InterpolatedString"/>). Kept out of <see cref="ParsePrimary"/> so its
    /// locals never enlarge that hot recursive frame.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParseInterpolatedString()
    {
        var start = Advance(); // the opening quote
        var head = TakeInterpolatedText();
        var links = new List<InterpolationLink>();
        while (Current.Kind == TokenKind.InterpolationHoleOpen)
        {
            var hole = ParseInterpolationHole();
            links.Add(new InterpolationLink(hole, TakeInterpolatedText()));
        }

        if (Current.Kind != TokenKind.InterpolatedStringEnd)
            throw new InvalidOperationException("The lexer produced an interpolated string without its closing quote.");
        Advance(); // the closing quote
        return InterpolatedStringFrom(head, links, start);
    }

    private string TakeInterpolatedText()
        => Current.Kind == TokenKind.InterpolatedStringText ? Advance().StringValue! : "";

    // Partner index of every interpolated-string boundary token — Start↔End and
    // HoleOpen↔HoleClose — built in one pass the first time a scan needs to step over a whole
    // string (most parses never do). The lexer guarantees the pairing.
    private int[]? _interpolationPartners;

    /// <summary>
    /// The index of the token paired with the interpolated-string boundary token at
    /// <paramref name="index"/>: an <see cref="TokenKind.InterpolatedStringStart"/>'s
    /// <see cref="TokenKind.InterpolatedStringEnd"/> and back, a hole's open and close. Lets a
    /// token-level scan treat a whole string as one atom in O(1).
    /// </summary>
    private int InterpolationPartner(int index)
        => (_interpolationPartners ??= BuildInterpolationPartners(_tokens))[index];

    private static int[] BuildInterpolationPartners(IReadOnlyList<Token> tokens)
    {
        var partners = new int[tokens.Count];
        var open = new Stack<int>();
        for (var index = 0; index < tokens.Count; index++)
        {
            switch (tokens[index].Kind)
            {
                case TokenKind.InterpolatedStringStart or TokenKind.InterpolationHoleOpen:
                    open.Push(index);
                    break;
                case TokenKind.InterpolatedStringEnd or TokenKind.InterpolationHoleClose:
                    if (!open.TryPop(out var opener)
                        || (tokens[opener].Kind == TokenKind.InterpolatedStringStart)
                            != (tokens[index].Kind == TokenKind.InterpolatedStringEnd))
                    {
                        throw new InvalidOperationException("The lexer produced unpaired interpolated-string tokens.");
                    }

                    partners[opener] = index;
                    partners[index] = opener;
                    break;
            }
        }

        if (open.Count != 0)
            throw new InvalidOperationException("The lexer produced unpaired interpolated-string tokens.");
        return partners;
    }

    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private Expr.InterpolatedString InterpolatedStringFrom(string head, List<InterpolationLink> links, Token start)
        => new(head, links.ToArray()) { Span = MakeSpan(start) };

    /// <summary>
    /// Parses one interpolation hole — the current token is its
    /// <see cref="TokenKind.InterpolationHoleOpen"/> — through its
    /// <see cref="TokenKind.InterpolationHoleClose"/>, and returns the hole's expression. A hole
    /// is ONE ordinary expression of the enclosing algorithm (never a scope, a slot list or a
    /// declaration site), parsed inside the hole's owned production with its ownership barrier
    /// (<see cref="EnterInterpolationHole"/>). A bare spread is the ordinary misplaced-spread
    /// error. Anything that keeps the hole from being exactly one expression — an empty hole, a
    /// hole-level <c>,</c>, <c>:</c> or <c>=</c>, a trailing token, a stray closer — is
    /// <see cref="DiagnosticCode.InvalidInterpolationHole"/>, reported once and recovered by
    /// skipping to the hole's own close (<see cref="RecoverInterpolationHoleTail"/>).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParseInterpolationHole()
    {
        var open = Advance(); // '{'
        Expr hole;
        using (EnterInterpolationHole())
        {
            if (Current.Kind == TokenKind.InterpolationHoleClose)
            {
                // A hole holding only a character the lexer reported (`"{#}"`) is explained.
                if (!HasLexicalErrorInHead(open, Current))
                    ReportErrorAcross(DiagnosticCode.InvalidInterpolationHole, EmptyInterpolationHoleDiagnostic, open, Current);
                hole = PlaceholderAt(open);
            }
            else if (!CanStartExpression(Current.Kind))
            {
                // A hole that begins with `,`, `:`, `=`, `;` or a stray closer holds no
                // expression at all: the hole reports it, never the primary-expression path.
                hole = PlaceholderAt(open);
                RecoverInterpolationHoleTail(open, reportedSince: _diagnostics.ReportedCount, leading: true);
            }
            else
            {
                var reportedBefore = _diagnostics.ReportedCount;
                hole = RejectMisplacedSpreadOperand(ParseExpression(), InterpolationSpreadDiagnostic);
                if (Current.Kind != TokenKind.InterpolationHoleClose)
                    RecoverInterpolationHoleTail(open, reportedSince: reportedBefore, leading: false);
            }
        }

        if (Current.Kind != TokenKind.InterpolationHoleClose)
            throw new InvalidOperationException("The lexer produced an interpolation hole without its closing brace.");
        Advance(); // '}'
        return hole;
    }

    /// <summary>
    /// Recovery for a hole whose expression ended before the hole's close: reports the first
    /// token that keeps the hole from being one expression and skips the rest of the hole,
    /// unparsed. The report is skipped when the hole already explained itself — the lexer
    /// reported a character inside it (a <c>#</c>, an unexpected character), or its expression
    /// parse reported a diagnostic — so a malformed hole is reported once.
    /// </summary>
    private void RecoverInterpolationHoleTail(Token open, long reportedSince, bool leading)
    {
        var offending = Current;
        var depth = 0;
        while (!(Current.Kind == TokenKind.InterpolationHoleClose && depth == 0))
        {
            if (Current.Kind == TokenKind.EndOfFile)
                throw new InvalidOperationException("The lexer produced an interpolation hole without its closing brace.");
            if (Current.Kind == TokenKind.InterpolationHoleOpen)
                depth++;
            else if (Current.Kind == TokenKind.InterpolationHoleClose)
                depth--;
            Advance();
        }

        if (_diagnostics.ReportedCount == reportedSince && !HasLexicalErrorInHead(open, Current))
            ReportErrorAt(DiagnosticCode.InvalidInterpolationHole, InterpolationHoleTailDiagnostic(offending.Kind, leading), offending);
    }

    private static string InterpolationHoleTailDiagnostic(TokenKind kind, bool leading) => kind switch
    {
        TokenKind.Comma =>
            "An interpolation hole holds one expression, so ',' cannot separate several. Write one hole per value, as in \"{a}, {b}\", or one sequence value in parentheses, as in \"{(a, b)}\".",
        TokenKind.Colon =>
            "':' is not available in an interpolation hole, and interpolation has no format specifiers. To select an item, write the selection with brackets, as in \"{xs[0]}\".",
        TokenKind.Equals =>
            "An interpolation hole holds one expression, never a declaration, so it cannot contain '='. To compare values, use '=='.",
        _ when leading =>
            $"An interpolation hole holds exactly one expression, and {DescribeTokenKind(kind)} cannot begin one.",
        _ =>
            $"An interpolation hole holds exactly one expression, but {DescribeTokenKind(kind)} follows it.",
    };

    /// <summary>
    /// Consumes, unparsed, the interpolated string that begins at the current
    /// <see cref="TokenKind.InterpolatedStringStart"/> through its matching end, and reports
    /// <see cref="DiagnosticCode.InterpolationNotAllowedHere"/> over it: recovery for a position
    /// whose grammar needs fixed text (a clause-head literal pattern, an <c>open</c> target).
    /// </summary>
    private void RejectInterpolatedStringHere(string diagnostic)
    {
        var start = Current;
        AdvancePastInterpolatedString();
        ReportErrorFrom(DiagnosticCode.InterpolationNotAllowedHere, diagnostic, start);
        OwnSameLineItem(Current);
    }

    /// <summary>
    /// Consumes, unparsed, the whole interpolated string that begins at the current
    /// <see cref="TokenKind.InterpolatedStringStart"/>, through its matching end.
    /// </summary>
    private void AdvancePastInterpolatedString()
    {
        var end = InterpolationPartner(NextSignificantIndex(_pos));
        while (NextSignificantIndex(_pos) <= end)
            Advance();
    }

    /// <summary>
    /// The stray-'=' diagnostic: the one report for a '=' that no declaration head on
    /// its own physical line precedes (the declaration-head line rule, see
    /// <see cref="IsHeadToken"/>).
    /// </summary>
    /// <summary>
    /// The precedence explanation for a `not` written where the surrounding operator
    /// demands a tighter operand (`1 + not x`, `a == not b`, `2 ^ not x`, `-not x`):
    /// `not` sits below the comparisons (comparisons > not > and > xor > or), so it can
    /// only begin an operand of `and`/`xor`/`or` or a whole expression. Reported AT the
    /// keyword; the negation is then parsed as if parenthesized (see ParsePrimary).
    /// </summary>
    private const string MisplacedNotDiagnostic =
        "Unexpected 'not'. `not` binds less tightly than the comparison, arithmetic, and power operators (comparisons > not > and > xor > or), so it cannot begin an operand here. Parenthesize the negation, as in `2 ^ (not x)` or `a == (not b)`.";

    private const string StrayEqualsDiagnostic =
        "Unexpected '='. A declaration head cannot be assembled across a physical newline. Keep `Name =` together, or keep a clause head's name and '(' together and its closing ')' and '=' together. A pattern list inside already-open parentheses and the body after '=' may span lines; deconstruction targets and '=' must share a line.";

    /// <summary>
    /// The stray-'=' diagnostic for a '=' that follows other content on its own physical
    /// line (`A = x = 1`, `[A = 1]`, `x, y, = 1, 2`): no newline split a head there, so the
    /// head-line explanation above would name a cause that is not present.
    /// </summary>
    private const string SameLineStrayEqualsDiagnostic =
        "Unexpected '='. '=' only ends a declaration head written at the start of a row (`Name =`, `Name(pattern) =`, or `x, y =`), so it cannot appear inside an expression. To compare values, use '=='.";

    /// <summary>
    /// Whether the stray '=' at the current position could have completed a declaration
    /// head that a physical newline split (the head-line explanation applies): the '='
    /// begins its line (`A` newline `= 1`, `x, y` newline `= 1, 2`), or it directly
    /// follows one parenthesized group that begins its line (`Foo` newline
    /// `(x) = x + 1`). The backward scan stays on the '=' line and stops at an earlier
    /// '=', so a line of many stray '=' costs linear work in total.
    /// </summary>
    private bool StrayEqualsFollowsSplitHead()
    {
        var equalsIndex = NextSignificantIndex(_pos);
        var line = _tokens[equalsIndex].Line;
        var before = PreviousSignificantIndex(equalsIndex);
        if (before < 0 || _tokens[before].Line < line)
            return true;
        if (_tokens[before].Kind != TokenKind.RParen)
            return false;

        var depth = 0;
        for (var index = before; index >= 0 && _tokens[index].Line == line; index = PreviousSignificantIndex(index))
        {
            var kind = _tokens[index].Kind;
            if (kind == TokenKind.InterpolatedStringEnd)
            {
                // A whole interpolated string is one atom: the delimiters and `=` inside its
                // holes are not this line's.
                index = InterpolationPartner(index);
                continue;
            }

            // The scan started inside a hole, which no head line extends past.
            if (kind is TokenKind.InterpolationHoleOpen or TokenKind.InterpolatedStringText or TokenKind.InterpolatedStringStart)
                return false;

            if (kind == TokenKind.Equals)
                return false;
            if (kind == TokenKind.RParen)
            {
                depth++;
            }
            else if (kind == TokenKind.LParen)
            {
                depth--;
                if (depth == 0)
                {
                    var start = PreviousSignificantIndex(index);
                    return start < 0 || _tokens[start].Line < line;
                }
            }
        }

        return false;
    }

    /// <summary>
    /// The nearest index before <paramref name="index"/> whose token the grammar sees (not a
    /// comment, not a reported character), or -1.
    /// </summary>
    private int PreviousSignificantIndex(int index)
    {
        for (var i = index - 1; i >= 0; i--)
        {
            if (!IsSkippedByGrammar(_tokens[i].Kind))
                return i;
        }

        return -1;
    }

