    // ── Algorithm parsing ───────────────────────────────────────────────────
    // Reads property definitions (Name = ...) and output expression lines.
    // Every non-definition expression row contributes to the algorithm's
    // Output list; definitions and output rows may be interleaved.

    // Delimiter model: `( ... )` is sequence/expression grouping and call
    // argument syntax only, `[ ... ]` is list construction, and `{ ... }` is
    // the algorithm/scope form. Only brace blocks and the root own
    // algorithm-level declarations; a declaration inside parentheses is a
    // parse error pointing the user at `{ ... }`.
    private const string OpenDeclarationInParenthesesDiagnostic =
        "An 'open' declaration is not allowed inside parentheses. Use a `{ ... }` block for a scoped algorithm.";

    private const string PropertyDeclarationInParenthesesDiagnostic =
        "A property declaration is not allowed inside parentheses. Use a `{ ... }` block for a scoped algorithm.";

    // Scoped algorithm bodies and parenthesized expression lists share the
    // same output-row grammar (comma/newline expression lists) and
    // the same declaration productions, so one low-level body loop collects
    // rows and declarations into syntactic PARTS without constructing a
    // semantic Algorithm. The two semantic entry points lower the parts
    // differently:
    //   ParseScopedAlgorithm        — brace blocks and trailing brace call
    //                                 arguments: the parts become an
    //                                 Algorithm.User that owns its
    //                                 declarations and its parameter
    //                                 analysis. ParseRootAlgorithm is the
    //                                 same lowering for the root — the one
    //                                 body with no enclosing delimiter, where
    //                                 an unmatched ')' or '}' is a recovered
    //                                 parse error rather than a terminator.
    //   ParseParenthesizedBodyParts — expression groups and call argument
    //                                 lists: declarations (open, properties,
    //                                 clause definitions, deconstruction
    //                                 bindings) report the targeted
    //                                 diagnostics above inline, and each is
    //                                 still parsed and retained in the parts
    //                                 so error recovery keeps a truthful
    //                                 tree. Valid groups lower to
    //                                 Expr.Capture over the rows, call
    //                                 argument lists lower to the
    //                                 OutputBundle of those rows, and
    //                                 declaration-carrying recovery lowers to
    //                                 a scope-owning recovery
    //                                 Expr.AlgorithmExpr (in both contexts).
    //                                 No Algorithm exists for a valid
    //                                 parenthesized body — free identifiers
    //                                 inside groups and argument bundles
    //                                 belong to the nearest enclosing
    //                                 algorithm scope.
    private readonly record struct ParsedAlgorithmBody(
        List<Expr> Opens,
        List<Property> Properties,
        List<Expr> Output)
    {
        public bool HasDeclarations => Opens.Count != 0 || Properties.Count != 0;
    }

    /// <summary>
    /// All mutable build state of ONE same-name clause family
    /// (<c>Name(pattern) = body</c> rows) while a body is being parsed: the
    /// visibility of its first clause, the clauses in written order with their
    /// whole-clause and name-token spans (index-aligned), and the
    /// match-equivalence index that makes duplicate-branch detection O(1) per
    /// clause. One family name owns exactly one builder for the lifetime of one
    /// <see cref="ParseAlgorithmBodyParts"/> call; the builder never reaches the
    /// AST — the post-loop elaboration reads it once and appends the family's
    /// property.
    /// </summary>
    private sealed class ClauseGroupBuilder
    {
        // Lookup accelerator only: the ordered Branches list stays the source of
        // truth for branch order, diagnostics, and spans.
        private readonly HashSet<Pattern> _seenPatterns;

        public ClauseGroupBuilder(string name, bool isPublic, IEqualityComparer<Pattern> matchEquivalence)
        {
            Name = name;
            IsPublic = isPublic;
            _seenPatterns = new HashSet<Pattern>(matchEquivalence);
        }

        public string Name { get; }

        /// <summary>Visibility of the FIRST clause; every later clause must agree.</summary>
        public bool IsPublic { get; }

        public List<CondBranch> Branches { get; } = [];

        /// <summary>Whole-clause spans, index-aligned with <see cref="Branches"/> (diagnostic anchors).</summary>
        public List<SourceSpan> ClauseSpans { get; } = [];

        /// <summary>Name-token spans, index-aligned with <see cref="Branches"/> (the property's declaration spans).</summary>
        public List<SourceSpan> NameSpans { get; } = [];

        /// <summary>
        /// Records one clause in written order. Returns <c>false</c> when an
        /// EARLIER clause of this family carried a match-equivalent pattern; the
        /// clause is recorded either way so error recovery keeps a truthful family.
        /// </summary>
        public bool AddClause(Pattern pattern, Algorithm body, SourceSpan clauseSpan, SourceSpan nameSpan)
        {
            var isDistinct = _seenPatterns.Add(pattern);
            Branches.Add(new CondBranch(pattern, body));
            ClauseSpans.Add(clauseSpan);
            NameSpans.Add(nameSpan);
            return isDistinct;
        }
    }

    /// <summary>
    /// Parses a scope-owning algorithm body — brace blocks and trailing brace
    /// call arguments — where declarations are legal and owned by the produced
    /// algorithm. The body stops at ')' or '}'; the caller consumes its
    /// expected closer or reports a mismatch without consuming it.
    /// </summary>
    private Algorithm.User ParseScopedAlgorithm()
        => CreateAlgorithm(ParseAlgorithmBodyParts(declarationsAllowed: true, atRoot: false));

    /// <summary>
    /// Parses one root scope through end of input. Any ')' or '}' left by
    /// nested parsing is reported and consumed within the same body loop,
    /// preserving accumulated declarations, output, and clause-family state.
    /// Recovery retains an erroneous tree for diagnostics and editor analysis.
    /// </summary>
    private Algorithm.User ParseRootAlgorithm()
        => CreateAlgorithm(ParseAlgorithmBodyParts(declarationsAllowed: true, atRoot: true));

    /// <summary>
    /// Reports an unmatched <c>)</c> or <c>}</c> at the root in KatLang terms —
    /// the written character, not the internal token kind — spanning exactly
    /// the offending token (the shared <see cref="DiagnosticCode.UnexpectedToken"/>
    /// family: a token that cannot continue the construct being parsed).
    /// </summary>
    private void ReportStrayRootCloser(Token closer)
    {
        var (written, opener) = closer.Kind == TokenKind.RParen ? (")", "(") : ("}", "{");
        ReportErrorAt(
            DiagnosticCode.UnexpectedToken,
            $"Unexpected '{written}' at the top level. There is no open '{opener}' for it to close.",
            closer);
    }

    /// <summary>
    /// Parses a parenthesized expression-list body — expression groups and
    /// call argument lists — where every declaration reports the targeted
    /// parenthesized-declaration diagnostic and is retained in the parts for
    /// recovery. The caller lowers the parts: a capture or argument bundle
    /// for a declaration-free body, one recovery algorithm block when
    /// declarations were retained.
    /// </summary>
    private ParsedAlgorithmBody ParseParenthesizedBodyParts()
        => ParseAlgorithmBodyParts(declarationsAllowed: false, atRoot: false);

    /// <summary>
    /// Constructs the semantic algorithm for parsed body parts. Used by the
    /// scoped entry point and by the declaration-carrying recovery lowering
    /// in parenthesized contexts — the recovery algorithm genuinely owns the
    /// retained declarations, which is the shape the diagnostic tells the
    /// user to write (<c>{ ... }</c>).
    /// </summary>
    private static Algorithm.User CreateAlgorithm(ParsedAlgorithmBody body)
        => new(
            Parent: null,
            ParameterPatterns: [],
            Opens: body.Opens,
            Properties: body.Properties,
            Output: body.Output);

    private ParsedAlgorithmBody ParseAlgorithmBodyParts(bool declarationsAllowed, bool atRoot)
    {
        var opens = new List<Expr>();
        var hasOpenDeclaration = false;
        var properties = new List<Property>();
        // O(1) mirror of the names already in `properties`, so duplicate-declaration
        // detection is a set lookup instead of a linear scan of the growing list.
        // Scanning `properties.Any(p => p.Name == name)` once per declaration made
        // ParseAlgorithm O(P^2) in the number of top-level declarations (a source of tens
        // of thousands of `A = ...` lines spent tens of seconds here). Kept in sync at every
        // in-loop `properties.Add`; the post-loop clause-group elaboration runs after all
        // duplicate checks, so those additions do not need mirroring.
        var declaredPropertyNames = new HashSet<string>(StringComparer.Ordinal);
        var output = new List<Expr>();
        // ONE owner per same-name clause family: every piece of build state a family
        // accumulates while its clauses are parsed lives in its ClauseGroupBuilder, keyed
        // by ordinal name. The list keeps FIRST-SEEN family order for the post-loop
        // elaboration, which is observable (appended property order, family diagnostic
        // order) — it must never depend on dictionary enumeration order.
        var clauseGroups = new Dictionary<string, ClauseGroupBuilder>(StringComparer.Ordinal);
        var clauseGroupsInSourceOrder = new List<ClauseGroupBuilder>();

        // Ordinary `Name = body` / `public Name = body`. The two spellings share every
        // mechanic — duplicate check, parenthesized-declaration diagnostic, body parse,
        // declaration span — and differ only in the consumed modifier and the
        // resulting visibility flag.
        void ParsePropertyDefinition(bool isPublic)
        {
            if (isPublic)
            {
                Advance(); // consume 'public'
            }

            var nameToken = Current;
            var name = nameToken.StringValue!;

            // Check for duplicate property definition
            if (declaredPropertyNames.Contains(name) || clauseGroups.ContainsKey(name))
            {
                ReportError(DiagnosticCode.DuplicateProperty, $"Property '{name}' is already defined.");
            }

            if (!declarationsAllowed)
            {
                ReportErrorAt(
                    DiagnosticCode.DeclarationInParentheses,
                    PropertyDeclarationInParenthesesDiagnostic,
                    nameToken);
            }

            Advance(); // consume identifier
            Advance(); // consume '='
            var body = ParseOutputLine();
            properties.Add(PropertyDeclaredAt(name, body, isPublic, nameToken));
            declaredPropertyNames.Add(name);
        }

        void ParseClauseDefinition(bool isPublic)
        {
            if (isPublic)
            {
                Advance(); // consume 'public'
            }

            var name = Current.StringValue!;
            var nameToken = Current;

            // Check for conflict: mixing normal and conditional definition
            if (declaredPropertyNames.Contains(name))
            {
                ReportError(DiagnosticCode.DuplicateProperty, $"Property '{name}' is already defined.");
            }

            if (!declarationsAllowed)
            {
                ReportErrorAt(
                    DiagnosticCode.DeclarationInParentheses,
                    PropertyDeclarationInParenthesesDiagnostic,
                    nameToken);
            }

            Advance(); // consume identifier
            Expect(TokenKind.LParen);
            var pattern = ParsePattern();
            Expect(TokenKind.RParen);

            ValidateCollectingParameterDeclarations(name, pattern, nameToken);

            Expect(TokenKind.Equals);
            var body = ParseOutputLine();

            if (!clauseGroups.TryGetValue(name, out var group))
            {
                group = new ClauseGroupBuilder(
                    name,
                    isPublic,
                    Pattern.CreateMatchEquivalenceComparer(_comparisonObservations));
                clauseGroups[name] = group;
                clauseGroupsInSourceOrder.Add(group);
            }
            else if (group.IsPublic != isPublic)
            {
                ReportErrorAt(
                    DiagnosticCode.ClauseVisibilityMismatch,
                    $"All clauses of '{name}' must use the same public modifier. Either mark every clause public or none of them.",
                    nameToken);
            }

            // The clause is always recorded (recovery keeps a truthful family); an earlier
            // match-equivalent pattern in the same family additionally reports the duplicate.
            if (!AddClauseFrom(group, pattern, body, nameToken))
            {
                ReportErrorFrom(
                    DiagnosticCode.DuplicateBranchPattern,
                    $"Duplicate branch pattern for conditional algorithm '{name}'.",
                    nameToken);
            }
        }

        // SYN-07A row boundary. The first item of a body may share the line of
        // the delimiter that opened it (`{ public X = 1 }`, `(1, 2)`). A
        // declaration inside parentheses still receives DeclarationInParentheses
        // from the declaration parser, including the first item after `(`.
        // Later items that reach this loop — a declaration head, an `open`, or
        // an output contribution — must begin a new physical line, because a
        // same-line item after closed content is exactly the boundary the
        // separator rule rejects. Expression-list slots never reach this check
        // (ParseExpressionListOperand consumes them and reports its own same-line
        // slots), so what does reach it is a declaration or a recovery leftover;
        // ReportUnseparatedSameLineItem stays silent for the boundaries a
        // recovery already owns. Recovery: the item is parsed as written.
        var itemsParsed = false;
        while (Current.Kind != TokenKind.EndOfFile)
        {
            if (Current.Kind is TokenKind.RParen or TokenKind.RBrace
                || (Current.Kind == TokenKind.RBracket && IsOwedCloser(TokenKind.RBracket)))
            {
                // A closing delimiter ends every NESTED body: the enclosing
                // group, block, or argument-list parser owns it and consumes it
                // (or reports the mismatch). A ']' is a body terminator only
                // while an enclosing list is waiting for it (`[ (1, ] `): the
                // group reports its missing ')' and the list closes at the
                // ']', exactly as the primary parser leaves an OWED closer
                // unconsumed (see IsOwedCloser) — an unowed ']' is junk the
                // expression parser reports and skips. The root has no enclosing
                // delimiter, so a closer reaching it is unmatched. Recover in
                // place: report the token at its own span, consume it, and keep
                // collecting into the SAME parts so the root stays one scope
                // (see ParseRootAlgorithm). Each recovery step consumes exactly
                // one token and reports exactly once, so a run of stray closers
                // costs linear work and one diagnostic per token.
                if (!atRoot)
                    break;

                ReportStrayRootCloser(Advance());
                // The stray closer's own diagnostic explains this boundary: the
                // item after it (`A = 1 ) 2` keeps `2` as a root row) is not
                // reported again by the separator rule.
                OwnSameLineItem(Current);
                continue;
            }

            // Skip bad tokens for error recovery (the lexer has already reported
            // the character; the token after it is a recovery-owned boundary).
            if (Current.Kind == TokenKind.Bad)
            {
                Advance();
                OwnSameLineItem(Current);
                continue;
            }

            // Only a real item has a row boundary. A stray ']', '=', or a
            // malformed 'public' has its own UnexpectedToken recovery below;
            // recommending a comma before that token would be a cascade.
            if (itemsParsed && IsSamePhysicalLineAsPreviousToken()
                && (CanStartExpression(Current.Kind)
                    || StartsDeclaration(includeCommaSpanningBindingPatterns: true)
                    || (Current.Kind == TokenKind.KeywordPublic
                        && (LookaheadIsPublicPropertyDef()
                            || LookaheadIsPublicClauseDefinition()
                            || LookaheadIsPublicOpen()))))
                ReportUnseparatedSameLineItem(Current);
            itemsParsed = true;

            // Check for invalid grace on property name: ~Name = ... or ~public Name = ...
            if (Current.Kind == TokenKind.Tilde && LookaheadThroughTildesToPropertyDef())
            {
                var firstMarker = Advance();
                var lastMarker = firstMarker;
                while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
                    lastMarker = Advance();
                ReportErrorAcross(
                    DiagnosticCode.InvalidGraceMarker,
                    "Grace operator cannot be applied to property names.",
                    firstMarker, lastMarker);
                // Fall through to normal property definition handling
            }

            // Open declaration: open target1, target2, ...
            if (Current.Kind == TokenKind.KeywordOpen)
            {
                var openToken = Current;
                if (hasOpenDeclaration)
                {
                    ReportError(
                        DiagnosticCode.InvalidOpenDeclaration,
                        "Only one 'open' declaration is allowed per algorithm.");
                }
                if (properties.Count > 0 || output.Count > 0)
                {
                    ReportError(
                        DiagnosticCode.InvalidOpenDeclaration,
                        "'open' declaration must appear before any properties or output expressions.");
                }
                hasOpenDeclaration = true;
                Advance(); // consume 'open'
                var openExprs = ParseOpenTargetList();
                NormalizeAndValidateOpenForms(openExprs);
                if (!declarationsAllowed)
                {
                    // The span covers the whole declaration, keyword through
                    // the last parsed target.
                    ReportErrorFrom(
                        DiagnosticCode.DeclarationInParentheses,
                        OpenDeclarationInParenthesesDiagnostic,
                        openToken);
                }
                opens.AddRange(openExprs);
            }
            // public open ... → reject
            else if (Current.Kind == TokenKind.KeywordPublic && LookaheadIsPublicOpen())
            {
                ReportError(
                    DiagnosticCode.InvalidOpenDeclaration,
                    "'public' cannot be applied to open declarations.");
                Advance(); // consume 'public'
                // Fall through: next iteration will parse the open declaration
                // normally. The consumed modifier's diagnostic owns the boundary
                // before `open`, so the row check does not report it again.
                OwnSameLineItem(Current);
            }
            // Check for public property definition: public Name = ...
            else if (Current.Kind == TokenKind.KeywordPublic && LookaheadIsPublicPropertyDef())
            {
                ParsePropertyDefinition(isPublic: true);
            }
            // public clause definition: public Name(...) = ...
            else if (Current.Kind == TokenKind.KeywordPublic && LookaheadIsPublicClauseDefinition())
            {
                ParseClauseDefinition(isPublic: true);
            }
            // The reserved Boolean literals in declaration-head position — `true = 1`,
            // `false(x) = x`, `public true = 1` — are keywords, never names, so they
            // can be neither declared nor shadowed. Report that intent precisely at
            // the literal instead of the stray-'=' cascade, then skip the whole head.
            else if (IsReservedLiteralDeclarationHead())
            {
                ReportReservedLiteralDeclaration();
            }
            // Check for property definition: Identifier '='
            else if (Current.Kind == TokenKind.Identifier && LookaheadIsEquals())
            {
                ParsePropertyDefinition(isPublic: false);
            }
            // Deconstruction / collecting binding pattern: x, *y, z = RHS (including
            // the collecting-led forms `*items = RHS` and `*first, rest = RHS`). A
            // plain single `name = RHS` is handled by the property branch above.
            else if ((Current.Kind is TokenKind.Identifier or TokenKind.Star)
                && LookaheadIsBindingPatternAssignment())
            {
                ParseBindingPatternAssignment(
                    properties, clauseGroups, declaredPropertyNames, declarationsAllowed, writtenRowIndex: output.Count);
            }
            // Clause definition: Name(pattern) = body
            else if (Current.Kind == TokenKind.Identifier && LookaheadIsClauseDefinition())
            {
                ParseClauseDefinition(isPublic: false);
            }
            else
            {
                // Output expression row, or an additional output contribution
                // separated from an earlier one by definitions. Within one
                // contribution, commas and — in these contexts (root output,
                // algorithm and brace bodies, explicit parenthesized groups, and
                // call argument lists) — physical newlines separate the
                // expression-list slots; a second slot on the same line without
                // a comma is the SYN-07A separator error, reported and recovered
                // as the next slot by ParseExpressionListOperand.
                var exprs = ParseExpressionListOperand(allowNewlineSeparator: true);
                AppendOutputContribution(output, exprs);
            }
        }

        // Elaborate same-name clause groups only after the full family is known.
        // This is the real ordinary-vs-conditional decision boundary: a clause family
        // is ordinary only when it contains exactly one clause and that sole
        // head is a recursive capture/sequence-value parameter pattern. For example,
        //   F(0) = 0
        //   F(x) = 1
        // must stay conditional for the whole family even though the second
        // clause would qualify in isolation.
        foreach (var group in clauseGroupsInSourceOrder)
        {
            var name = group.Name;
            var spans = group.ClauseSpans;
            var nameSpans = group.NameSpans;
            var isPublic = group.IsPublic;
            var elaboratedClauseGroup = Algorithm.ElaborateClauseGroup(group.Branches);

            if (elaboratedClauseGroup is Algorithm.User ordinaryAlg)
            {
                properties.Add(new Property(name, ordinaryAlg, IsPublic: isPublic)
                {
                    DeclarationSpans = nameSpans
                });
                continue;
            }

            var condAlg = (Algorithm.Conditional)elaboratedClauseGroup;

            for (var i = 0; i < condAlg.Branches.Count; i++)
            {
                if (PatternContainsCollectingParameter(condAlg.Branches[i].Pattern))
                {
                    ReportError(
                        DiagnosticCode.InvalidCollectingBinding,
                        $"Collecting bindings are only supported in ordinary explicit parameter lists for '{name}'.",
                        spans[i]);
                }
            }

            // Validate no Grace operators in true conditional branch bodies.
            foreach (var branch in condAlg.Branches)
            {
                if (FindGraceSpan(branch.Body.Output) is { } graceSpan)
                {
                    ReportError(
                        DiagnosticCode.InvalidGraceMarker,
                        $"Grace is not allowed in conditional branch bodies for '{name}'.",
                        graceSpan);
                }
            }

            // Validate uniform top-level pattern arity across conditional branches.
            // Nested internal pattern structure may vary.
            // Also validate uniform top-level output arity across branches.
            if (condAlg.Branches.Count > 1)
            {
                var expectedArity = condAlg.Branches[0].Pattern.TopLevelArity();
                for (int i = 1; i < condAlg.Branches.Count; i++)
                {
                    var branchArity = condAlg.Branches[i].Pattern.TopLevelArity();
                    if (branchArity != expectedArity)
                    {
                        ReportError(
                            DiagnosticCode.BranchArityMismatch,
                            $"All branches of conditional algorithm '{name}' must have the same top-level pattern arity. " +
                            $"Expected {expectedArity} (from first branch), but branch {i + 1} has arity {branchArity}.",
                            spans[i]);
                    }
                }

                var expectedOutputArity = condAlg.Branches[0].TopLevelOutputArity();
                for (int i = 1; i < condAlg.Branches.Count; i++)
                {
                    var branchOutputArity = condAlg.Branches[i].TopLevelOutputArity();
                    if (branchOutputArity != expectedOutputArity)
                    {
                        ReportError(
                            DiagnosticCode.BranchOutputArityMismatch,
                            $"All branches of conditional algorithm '{name}' must have the same top-level output arity. " +
                            $"Expected {expectedOutputArity} (from first branch), but branch {i + 1} has output arity {branchOutputArity}.",
                            spans[i]);
                    }
                }
            }

            properties.Add(new Property(name, condAlg, IsPublic: isPublic)
            {
                DeclarationSpans = nameSpans
            });
        }

        return new ParsedAlgorithmBody(opens, properties, output);
    }

    // The hull of two written extents (either may be absent): the diagnostic or node
    // covers from the earlier start to the later end.
    private static SourceSpan CombineSpans(SourceSpan left, SourceSpan right) => left.Union(right);

    private static SourceSpan? CombineSpans(SourceSpan? left, SourceSpan? right)
        => left is null
            ? right
            : right is null
                ? left
                : left.Value.Union(right.Value);

    private const string UnsupportedSemicolonExpressionMessage =
        "Semicolon is not supported as an expression separator. Use ',' between expressions on one line (a new line separates them where the context allows it), or parentheses for one sequence value.";

    // ── SYN-07A: same-line items need a separator ───────────────────────────
    // Whitespace never creates a slot boundary. Once an expression is closed,
    // a second independent slot on the same physical line needs ','; a
    // declaration must begin a new row. The rule is
    // decided at ONE ownership point for slots (StartsNextExpressionListSlot,
    // reached by every expression-list context through ParseExpressionListOperand),
    // at ONE ownership point for parameter-pattern items
    // (StartsUnseparatedPatternItem, reached by clause heads and nested
    // sequence-value patterns through ParsePatternItems), and at the body
    // loop's row check for declarations and recovery leftovers; all report
    // through this helper. Recovery admits the item where it was
    // written — as the next slot of the SAME list, as the next pattern of the
    // SAME parameter list, or as the declaration — so
    // the structure the programmer most plausibly meant survives for later
    // diagnostics and editor tooling (`P = a b` keeps `b` in P's body; it never
    // leaks to the enclosing scope; `F(a b) = a + b` keeps `b` a parameter of
    // F, so its body never leaks to the enclosing scope as unrelated rows),
    // while the parse stays invalid. The expression-list message
    // names the three repairs without guessing intent: a comma, an operator, or
    // a new line for a declaration. A parameter-pattern list has only the
    // comma — a pattern has no operator to continue with and no declaration to
    // move to a new line — so its report of the same family names that one
    // repair and the construct it applies to.
    private const string UnseparatedSameLineItemMessage =
        "Unexpected item after a closed expression on the same line. Add ',' to separate slots, add an operator to continue the expression, or start a declaration on a new line.";

    private const string UnseparatedPatternItemMessage =
        "Unexpected item after a parameter pattern on the same line. Add ',' to separate the patterns of a parameter list.";

    private void ReportUnseparatedSameLineItem(Token item, string message = UnseparatedSameLineItemMessage)
    {
        if (item.Position == _ownedSameLineItemPosition || item.Position == _reportedSameLineItemPosition)
            return;
        _reportedSameLineItemPosition = item.Position;
        ReportErrorAt(DiagnosticCode.UnseparatedSameLineItem, message, item);
    }

    // Cascade suppression: a recovery that has consumed or diagnosed a
    // malformed run calls this for the token that follows it, so the boundary
    // its diagnostic already explains is not reported a second time by the
    // separator rule. Only that one boundary is owned — a later independent
    // same-line item still receives its own diagnostic.
    private void OwnSameLineItem(Token item) => _ownedSameLineItemPosition = item.Position;

    // Consumes the current token as error recovery and marks the token after it
    // as a recovery-owned same-line boundary.
    private Token SkipForRecovery()
    {
        var skipped = Advance();
        OwnSameLineItem(Current);
        return skipped;
    }

    // ── Spread marker ───────────────────────────────────────────────
    // Expression spreading is written with the postfix spread marker `*`:
    // a same-line star after a completed expression that has no valid
    // right operand after it lowers to the one unary AST node
    // SequenceSpread(expr) (shared with Lean). The multiplication-versus-
    // spread decision is made by the NEXT significant token alone — never
    // by whitespace, attachment, or the physical newline (SYN-07B): when a
    // token that can begin a multiplication operand follows the star, on
    // the same line or on a later one, the star is infix multiplication
    // (`a*b`, `a* b`, `a *b`, `a * b`, and `a*` newline `b` all multiply),
    // so spreading before another supplied item requires a comma (`a*, b`;
    // a trailing comma continues the list across the newline: `a*,` newline
    // `b`). The star is the spread marker when the surrounding syntax
    // closes the expression before any operand could follow: a closing
    // `)`, `]`, or `}`, a comma, end of input, a token that cannot start an
    // expression (`.`, `;`, `==`, ...), or a declaration head (`a*` newline
    // `b = 1` is a spread row followed by a property definition). A spread
    // marker must then be DIRECTLY attached to its operand (the marker
    // attachment law shared with `*name`, `~name`, `name~`): the detached
    // `values *` that no operand follows is a malformed marker with a
    // targeted diagnostic (ParseSpreadMarkerContinuation), so whitespace can
    // never turn one valid reading into another — it only separates the
    // valid `values*` from the rejected `values *`. Chained spread is
    // `value**` — each further attached star nests one more unary spread
    // node, building SequenceSpread(SequenceSpread(expr)).
    // The parser only records the written layers; evaluation applies them
    // compositionally, `value**` agreeing with `(value*)*` (each layer
    // spreads the value the previous layer's supply re-captures — see
    // Evaluator.EvalSequenceSpreadCounted).
    //
    // A spread expression is legal only as a whole expression-list slot
    // (root output rows, call argument slots, parenthesized group and
    // brace-body slots, list-literal elements, definition body slots, and
    // the operand of another spread), or as the receiver of the
    // fluent dot continuation `operand*.Target(...)`, which lowers to the
    // ordinary lexical call `Target(operand*, ...)` with the spread as the
    // leading argument slot. It never participates as an operand of a
    // unary/binary operator or an indexing target/selector — those
    // placements report the targeted misplaced-spread diagnostic and
    // recover by unwrapping to the spread's operand, so no embedded
    // SequenceSpread survives in the recovered tree.
    //
    // Prefix `*` is the collect marker and is COLLECTING-BINDING syntax only
    // (`*name` in binding positions). It is not an expression operator, so a
    // prefix star reaching expression position reports the targeted
    // collect-marker diagnostic and recovers to the following operand.
    // Semicolon is not a valid way to continue or join an expression;
    // `A* ; B` is unsupported-semicolon diagnostic recovery only.
    // Every SequenceSpread the parser builds goes through
    // SequenceSpreadFrom (architecture-tested).
    private static void AppendOutputContribution(List<Expr> output, IReadOnlyList<Expr> exprs)
    {
        if (exprs.Count == 0)
            return;

        output.AddRange(exprs);
    }

    /// <summary>
    /// Parses the open-target list after the <c>open</c> keyword. `open` is
    /// a declaration/import directive, not an output expression, so its
    /// target list is a dedicated COMMA list — never semicolon sequence syntax:
    /// `open A, B, C` opens three targets, while `;` and a bare same-line
    /// second target are not separators and report a missing-comma
    /// diagnostic (the same explicit-comma rule every expression list follows
    /// since SYN-07A). The first
    /// target must begin on the same physical line as `open`. Comma keeps
    /// its normal explicit line-continuation behavior — `open A,` newline
    /// `B` and `open A` newline `, B` both continue the list — and a leading
    /// `.` continues a dotted target (`open A` newline `.B` is `open A.B`),
    /// but a plain newline never does: `open Math` newline `Math.Pi`
    /// is an open plus a report row. Each algorithm still allows at most one
    /// `open` declaration. Targets never go through generic
    /// output-precedence parsing, so no sequence construction or spread is
    /// ever built for an open target.
    /// </summary>
    private List<Expr> ParseOpenTargetList()
    {
        var targets = new List<Expr>();

        // The first target must start on the `open` line; a newline directly
        // after `open` (comments are invisible) is a missing target, and the
        // next line stays a separate statement/output row.
        if (!IsSamePhysicalLineAsPreviousToken() || !StartsOpenTargetAtom())
        {
            ReportErrorAt(
                DiagnosticCode.InvalidOpenTargetList,
                "Expected an open target after 'open' on the same physical line.",
                Previous);
            return targets;
        }

        if (ParseOpenTargetAtom() is { } first)
            targets.Add(first);

        // Comma is the only separator and may continue the list across a
        // physical newline (trailing `open A,` newline `B` or leading
        // `open A` newline `, B`), matching general comma continuation.
        while (Current.Kind == TokenKind.Comma)
        {
            var comma = Advance(); // consume ','
            if (!StartsOpenTargetAtom())
            {
                ReportErrorAt(
                    DiagnosticCode.InvalidOpenTargetList,
                    "Expected an open target after ','.",
                    comma);
                break;
            }
            if (ParseOpenTargetAtom() is { } target)
                targets.Add(target);
        }

        // Anything else on the same line after a target is a separator
        // mistake, not a following output row.
        if (IsSamePhysicalLineAsPreviousToken()
            && Current.Kind is not (TokenKind.EndOfFile or TokenKind.RParen or TokenKind.RBrace))
        {
            if (Current.Kind == TokenKind.Semicolon)
            {
                ReportErrorAt(
                    DiagnosticCode.InvalidOpenTargetList,
                    "Open target lists use ',' separators, not ';'. Write `open A, B` to open multiple targets.",
                    Current);
                Advance(); // consume ';' so it is not re-reported at statement level
                OwnSameLineItem(Current); // the leftover after ';' is this diagnostic's boundary
            }
            else
            {
                ReportErrorAt(
                    DiagnosticCode.InvalidOpenTargetList,
                    "Expected ',' between open targets. Open targets are separated by commas.",
                    Current);

                // A string open target is pure sugar with no postfix
                // continuations, so a trailing star after one (`open 'url'*`)
                // never becomes a spread target — opens must not contain a
                // SequenceSpread built from a string target. Consume the star
                // run here anyway, exactly like the ';' branch above, so the
                // leftover marker is not re-parsed at statement level and
                // re-reported as a PREFIX collect-marker error, which would
                // describe binding syntax the user never wrote.
                while (Current.Kind == TokenKind.Star)
                    Advance();

                // The missing-comma diagnostic owns this boundary: the leftover
                // is parsed by the statement level as written (`open A B` keeps
                // `B` as a row) without a second, separator-rule diagnostic.
                OwnSameLineItem(Current);
            }
        }

        return targets;
    }

    // A token that can begin an open target atom. Declaration starters are
    // excluded so recovery leaves a following declaration intact — through
    // the SAME declaration-starter relation the slot-boundary rule stops at
    // (StartsDeclaration), so the two boundary decisions cannot drift apart
    // again. (A historical independently written copy here missed the
    // binding-pattern form, so `open A,` newline `x, y = 1` swallowed `x` as
    // an open target and tore the deconstruction apart — and its recovery
    // even consumed the collect marker of a following `*y` binding.)
    //
    // The comma-spanning binding-pattern arm applies only to a candidate
    // starting a NEW physical line: inside the open's own line the list's
    // separator commas are open syntax and must not be absorbed into a
    // binding-pattern reading, while a new-line candidate is only reachable
    // through a trailing-comma continuation, where a declaration means the
    // comma was dangling (see StartsDeclaration).
    private bool StartsOpenTargetAtom()
        => CanStartExpression(Current.Kind)
            && !StartsDeclaration(
                includeCommaSpanningBindingPatterns: !IsSamePhysicalLineAsPreviousToken());

    /// <summary>
    /// Parses exactly one open target atom: a single-quoted string target
    /// (desugared through <see cref="CreateLoadOpenTarget"/>), or one plain
    /// expression (resolve, argumentless dotted path, or parenthesized block —
    /// anything else is rejected by open-form validation). A spread-marked
    /// open target (`open A*`) parses to a SequenceSpread expression and is
    /// rejected by open-form validation (spread is not an open form).
    /// </summary>
    private Expr? ParseOpenTargetAtom()
    {
        if (Current.Kind == TokenKind.StringLiteral)
        {
            // String literal sugar: open 'url' → open load('url').
            var token = Advance();
            return CreateLoadOpenTarget(token);
        }

        // One plain expression: resolve, dotted path (a leading '.' may
        // continue it across a newline via the dot whitelist), or block
        // parenthesized block. This is the expression layer, not generic
        // output-precedence parsing — no joins, slot boundaries, or spread slots.
        return ParseExpression();
    }

    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private static Expr CreateLoadOpenTarget(Token urlToken)
    {
        SourceSpan? span = urlToken.Span;
        var urlExpr = new Expr.StringLiteral(urlToken.StringValue ?? "") { Span = span };
        OutputBundle loadArgs = [urlExpr];
        // This synthetic load has no identifier token in source, so it must
        // stay spanless. Borrowing the quoted URL span would make downstream
        // source-backed semantic models report an identifier on a string token.
        var loadResolve = new Expr.Resolve("load");
        return new Expr.Call(loadResolve, loadArgs) { Span = span };
    }

    /// <summary>
    /// Checks if the token after the current identifier is '='.
    /// Used to distinguish property definitions from output expressions.
    /// </summary>
    private bool LookaheadIsEquals()
        => LookaheadIsEqualsFrom(NextSignificantIndex(_pos));

    /// <summary>
    /// Index form of <see cref="LookaheadIsEquals"/>: true when the significant
    /// token after the significant token at <paramref name="index"/> is '='
    /// AND lies on the same physical line (the declaration-head line rule).
    /// </summary>
    private bool LookaheadIsEqualsFrom(int index)
    {
        var equals = NextSignificantIndex(index + 1);
        return _tokens[equals].Kind == TokenKind.Equals
            && IsHeadToken(equals, _tokens[index].Line);
    }

    // ── The declaration-head line rule ──────────────────────────────────────
    // A declaration head — `Name =`, `Name(pattern) =`, `x, *y, z =`, `~Name =`,
    // `public Name =`, `public Name(pattern) =` — is written on ONE physical
    // line: every token of the head shares the line of its first token, the
    // one exception being the inside of a clause head's already-open `( … )`,
    // which spans lines like every open delimiter (the `)` and the `=` still
    // share a line). A physical newline therefore never assembles a head
    // implicitly: `Foo` newline `(x) = x + 1`, `A` newline `= 1`, `Foo(x)`
    // newline `= x + 1`, and `x, y` newline `= 1, 2` keep the first line as
    // the closed output row it is (a name, a call, a group, an expression
    // list) and reach the ordinary stray-`=` diagnostic on the next line —
    // they never retroactively become a clause, property, or deconstruction
    // head. Comments are invisible here as everywhere: `P # note` newline
    // `= 1` is the same two rows. Explicit continuation AFTER a recognized
    // head is unaffected and deliberate: the body of `A =` or `Foo(x) =` may
    // begin on the next line exactly like the operand of a trailing binary
    // operator, and a trailing `.` continues its dot chain the same way.
    // Every declaration lookahead consults this ONE predicate.
    private bool IsHeadToken(int index, int headLine) => _tokens[index].Line == headLine;

    // ── Star-marker diagnostics ─────────────────────────────────────────────
    // Prefix `*name` (directly attached) is the ONLY collecting-binding
    // spelling, valid only in binding positions. Postfix `expr*` (directly
    // attached, and no right operand follows the star on any line) is the
    // ONLY spread spelling, valid only as a whole expression-list slot or
    // fluent dot-chain receiver. A star that a right operand follows is infix
    // multiplication, however it is spaced; a star that no operand follows
    // and that is NOT attached to the expression before it (`values *`) is a
    // malformed spread marker — never silently a multiplication and never
    // silently a spread (MARKER ATTACHMENT LAW: structural/annotation
    // markers `*name`, `name*`, `~name`, `name~` are directly attached;
    // ordinary operators may be spaced freely).

    private static string CollectMarkerAttachmentDiagnostic(string name) =>
        $"The collect marker `*` must be directly attached to its binding name: write `*{name}`.";

    private static string SpreadMarkerAttachmentDiagnostic(Expr operand) =>
        $"The spread marker `*` must be directly attached to the expression it spreads: write `{ExprNameRenderer.Render(operand, ExprNameMode.SpreadOperand)}*` (a detached `*` that no right operand follows is not multiplication either).";

    private static string RepeatedCollectMarkerDiagnostic(string name) =>
        $"A collecting binding uses exactly one collect marker: write `*{name}`.";

    private const string CollectMarkerMissingNameDiagnostic =
        "The collect marker `*` must be followed by a binding name, as in `*items`.";

    private static string SpreadMarkerInBindingPatternDiagnostic(string name) =>
        $"Postfix `*` is the spread marker and is not valid in a binding pattern. Write `*{name}` to declare a collecting binding.";

    private const string CollectMarkerInExpressionDiagnostic =
        "Prefix `*` is the collect marker and is valid only in binding patterns (explicit parameter lists and assignment deconstruction).";

    private const string MisplacedSpreadDiagnostic =
        "A spread expression contributes items to the surrounding item supply and cannot be used as a scalar operand. Spread the whole expression instead, e.g. `(A + B)*`.";

    /// <summary>
    /// The <see cref="MisplacedSpreadDiagnostic"/> variant for `A*` newline `B*`: the
    /// first line's final `*` is multiplication because an operand follows it on the
    /// next line (the star rule is layout-independent), so the second line's spread
    /// became a scalar operand. Names the cause and distinguishes separate spread
    /// rows from capturing the first spread as one value.
    /// </summary>
    private const string LineFinalStarContinuationDiagnostic =
        "The final `*` on an earlier line continued as multiplication, making this spread expression its right operand. A spread cannot be a scalar operand. For separate spread rows, add a comma (`A*,`). Grouping (`(A*)`) also ends the row but captures its items as one value. For multiplication, remove the right operand's spread marker (`A * B`); the operands may be on different lines.";

    /// <summary>
    /// Targeted message for the indexing continuation (`A*:0`): selection
    /// needs ONE value while a spread supplies items, and the two nearby
    /// valid forms mean DIFFERENT things — `(A:0)*` selects first and then
    /// spreads the selected value, `(A*):0` captures the spread supply as one
    /// sequence value and then selects. The message names both intentions so
    /// they are not presented as interchangeable fixes.
    /// </summary>
    private const string SpreadSelectionDiagnostic =
        "Selection cannot be applied directly to a spread expression — a spread supplies items to the surrounding item supply, not one selectable value. Write `(A:0)*` to select first and then spread the selected value, or `(A*):0` to capture the spread items as one sequence value and then select; the two forms have different meanings.";

    /// <summary>
    /// Rejects a spread expression used as an operand of a larger expression
    /// (unary/binary operand, indexing target or selector). Spread is legal
    /// only as a whole expression-list slot, as the operand of another
    /// spread, or as the fluent dot-chain receiver (which lowers to a call).
    /// The default message covers scalar operand positions; the indexing
    /// continuation passes <see cref="SpreadSelectionDiagnostic"/> to
    /// distinguish select-then-spread from capture-then-select. Recovery
    /// unwraps to the innermost non-spread operand so no embedded
    /// SequenceSpread survives in the recovered tree — downstream layers
    /// keep the slot-level-only spread invariant.
    /// </summary>
    private Expr RejectMisplacedSpreadOperand(Expr expr, string diagnostic = MisplacedSpreadDiagnostic)
    {
        if (expr is not Expr.SequenceSpread spread)
            return expr;

        if (spread.Span is { } span)
            ReportError(DiagnosticCode.MisplacedSpread, diagnostic, span);
        else
            ReportError(DiagnosticCode.MisplacedSpread, diagnostic);

        var operand = spread.Operand;
        while (operand is Expr.SequenceSpread inner)
            operand = inner.Operand;
        return operand;
    }

    private readonly record struct BindingTarget(
        string Name,
        ParameterKind Kind,
        SourceSpan NameSpan,
        SourceSpan? CollectMarkerSpan);

    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private static BindingTarget BindingTargetAt(string name, ParameterKind kind, Token nameToken, Token? collectMarkerToken)
        => new(name, kind, nameToken.Span, collectMarkerToken?.Span);

    // Last FAILED binding-pattern scan: [start, break) with the breaking token
    // index exclusive. Sound to reuse because the scan is a forward DFA over the
    // immutable token stream (indexed absolutely; the parser only advances):
    // every identifier/star position strictly inside a
    // failed region is a binding-name/collect-marker position of that same
    // failed scan, so a fresh scan from it follows the identical transitions to
    // the identical breaking token and fails the same way. (A success cannot
    // hide inside a failed region: accepting at an interior `=` needs a comma
    // or collect marker before it, which the ORIGINAL scan — having traversed
    // at least as much of the region — also had, so it would have accepted
    // there too.) The breaking token itself is excluded: a scan STARTING at it
    // is a different parse (`a b, c = 1` fails from `a` at `b`, succeeds from
    // `b`). The memo only ever short-circuits a FALSE answer, and it is what
    // keeps repeated boundary checks over one identifier-comma run linear —
    // without it, every target of the multiline continuation `open a1,`
    // newline `a2,` newline ... newline `an` would rescan the remaining run,
    // turning that long open list quadratic.
    private int _bindingPatternScanFailStart = -1;
    private int _bindingPatternScanFailBreak = -1;

    /// <summary>
    /// Checks whether the tokens at the current position form a deconstruction
    /// assignment with identifier targets. A plain single <c>name =</c> is left
    /// to the ordinary property path; <c>*name =</c> is the unambiguous
    /// lone-collecting-binding form. The prefix collect marker must be
    /// directly attached to its binding name; the scan is deliberately
    /// TOLERANT of malformed marker shapes (a gap after the star, or a
    /// repeated star) so <see cref="ParseBindingPatternAssignment"/> can
    /// report the targeted attachment/malformed diagnostics — validity is
    /// enforced during parsing, never here. Targets are identifiers with an
    /// optional leading star run; anything else falls through to ordinary
    /// expression parsing.
    /// </summary>
    private bool LookaheadIsBindingPatternAssignment()
        => LookaheadIsBindingPatternAssignmentFrom(NextSignificantIndex(_pos));

    /// <summary>
    /// Index form of <see cref="LookaheadIsBindingPatternAssignment"/>: the
    /// same memoized scan, started at the significant token at
    /// <paramref name="start"/>.
    /// </summary>
    private bool LookaheadIsBindingPatternAssignmentFrom(int start)
    {
        if (start >= _bindingPatternScanFailStart && start < _bindingPatternScanFailBreak)
            return false;

        // The declaration-head line rule (IsHeadToken): the whole binding-pattern
        // head — stars, names, commas, and the '=' — shares the first token's
        // physical line. The scan fails at the first token on a later line, so
        // the failed-region memo below stays sound: every start inside the
        // region lies on that same line and would fail at the same token.
        var headLine = _tokens[start].Line;
        var index = start;
        var sawComma = false;
        var sawCollectMarker = false;

        while (true)
        {
            // Optional prefix collect-marker star run before the binding name.
            while (_tokens[index].Kind == TokenKind.Star && IsHeadToken(index, headLine))
            {
                sawCollectMarker = true;
                index = NextSignificantIndex(index + 1);
            }

            if (_tokens[index].Kind != TokenKind.Identifier || !IsHeadToken(index, headLine))
                return FailBindingPatternScan(start, index);
            index = NextSignificantIndex(index + 1);

            if (!IsHeadToken(index, headLine))
                return FailBindingPatternScan(start, index);

            switch (_tokens[index].Kind)
            {
                case TokenKind.Comma:
                    sawComma = true;
                    index = NextSignificantIndex(index + 1);
                    continue;
                case TokenKind.Equals:
                    return sawComma || sawCollectMarker
                        || FailBindingPatternScan(start, index);
                default:
                    return FailBindingPatternScan(start, index);
            }
        }
    }

    /// <summary>Records the failed scan region for the memo above; always false.</summary>
    private bool FailBindingPatternScan(int start, int breakIndex)
    {
        _bindingPatternScanFailStart = start;
        _bindingPatternScanFailBreak = breakIndex;
        return false;
    }

    /// <summary>
    /// Parses a deconstruction assignment <c>x, *y, z = RHS</c>. The
    /// lone-collecting-binding form <c>*items = RHS</c> is also supported. The right-hand side
    /// is evaluated once and its items are bound to the targets by the shared
    /// deconstruction matcher, with one optional movable collecting binding that COLLECTS
    /// its assigned items as one list (<c>CollectSegment</c>).
    /// A malformed marker shape (a gap between the star and its name, or a
    /// repeated star) reports a targeted diagnostic and binds the name as an
    /// ordinary fixed target — malformed recovery never creates a collecting
    /// binding.
    /// <paramref name="declarationsAllowed"/> is the enclosing body context
    /// (see <see cref="ParseAlgorithmBodyParts"/>): deconstruction declares
    /// properties, so inside a parenthesized body the binding pattern reports
    /// the property-in-parentheses diagnostic. <paramref name="writtenRowIndex"/> is the
    /// number of output rows the enclosing body has written so far — the structural
    /// written-order key of the hoisted right-hand side
    /// (<see cref="Algorithm.User.AssignmentDeconstructionRowIndex"/>).
    /// </summary>
    private void ParseBindingPatternAssignment(
        List<Property> properties,
        Dictionary<string, ClauseGroupBuilder> clauseGroups,
        HashSet<string> declaredPropertyNames,
        bool declarationsAllowed,
        int writtenRowIndex)
    {
        var targets = new List<BindingTarget>();
        while (true)
        {
            // Optional prefix collect-marker star run (the lookahead is
            // tolerant; exactly one directly attached star is valid syntax).
            Token? firstStarToken = null;
            var starCount = 0;
            while (Current.Kind == TokenKind.Star)
            {
                var starToken = Advance();
                firstStarToken ??= starToken;
                starCount++;
            }

            var nameToken = Current; // Identifier, guaranteed by the lookahead
            var name = nameToken.StringValue!;
            Advance(); // consume identifier

            var isCollectingBinding = false;
            Token? collectMarkerToken = null;
            if (starCount == 1 && IsDirectlyAttached(firstStarToken!, nameToken))
            {
                isCollectingBinding = true;
                collectMarkerToken = firstStarToken;
            }
            else if (starCount == 1)
            {
                ReportErrorAcross(
                    DiagnosticCode.InvalidCollectMarker,
                    CollectMarkerAttachmentDiagnostic(name),
                    firstStarToken!, nameToken);
            }
            else if (starCount > 1)
            {
                ReportErrorAcross(
                    DiagnosticCode.InvalidCollectMarker,
                    RepeatedCollectMarkerDiagnostic(name),
                    firstStarToken!, nameToken);
            }

            var kind = isCollectingBinding ? ParameterKind.Collecting : ParameterKind.Normal;
            targets.Add(BindingTargetAt(name, kind, nameToken, collectMarkerToken));

            if (Current.Kind == TokenKind.Comma)
            {
                Advance(); // consume ','
                continue;
            }

            break;
        }

        if (!declarationsAllowed)
        {
            // The span covers the whole binding pattern, first marker/name
            // through the last binding name.
            var first = targets[0];
            ReportError(
                DiagnosticCode.DeclarationInParentheses,
                PropertyDeclarationInParenthesesDiagnostic,
                CombineSpans(first.CollectMarkerSpan ?? first.NameSpan, targets[^1].NameSpan));
        }

        Expect(TokenKind.Equals);
        var rhsBody = ParseOutputLine(preserveWrittenBlock: true);

        if (targets.Count(static target => target.Kind == ParameterKind.Collecting) > 1)
        {
            // The first collecting binding stays the diagnostic subject; its
            // span covers the whole `*name`, marker included.
            var firstCollecting = targets
                .First(static target => target.Kind == ParameterKind.Collecting);
            ReportError(
                DiagnosticCode.InvalidCollectingBinding,
                "A deconstruction binding pattern may contain at most one collecting binding (`*name`).",
                CombineSpans(firstCollecting.CollectMarkerSpan, firstCollecting.NameSpan) ?? firstCollecting.NameSpan);
        }

        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var target in targets)
        {
            if (!seen.Add(target.Name)
                || declaredPropertyNames.Contains(target.Name)
                || clauseGroups.ContainsKey(target.Name))
            {
                ReportError(
                    DiagnosticCode.DuplicateProperty,
                    $"Property '{target.Name}' is already defined.",
                    target.NameSpan);
            }
        }

        AddDeconstructionProperties(targets, rhsBody, properties, declaredPropertyNames, writtenRowIndex);
    }

    /// <summary>
    /// Elaborates a deconstruction pattern into properties. The right-hand side is
    /// hoisted into one synthetic shared property (evaluated once), and each target
    /// becomes a property whose body applies an inline sequence-value-pattern
    /// helper to that shared source, returning its own bound name. The helper reuses
    /// the ordinary patterned-binding path: assignment deconstruction is an
    /// unpacking receiver, so a single sequence-valued right-hand side is opened and
    /// matched element-by-element (Python-style: <c>x, y, z = A</c> splits a stored
    /// sequence value <c>A</c>). Explicit <c>x, y, z = A*</c> supplies the same
    /// items. This unpacking is deconstruction-specific and does not change ordinary
    /// calls, which still pass <c>A</c> as one argument unless <c>A*</c> is written.
    /// Synthetic constructs carry no source spans; only the target property names are
    /// source-backed declarations. The collect-marker metadata is the one additional
    /// source-backed syntax span retained on the synthetic binding pattern.
    /// </summary>
    private void AddDeconstructionProperties(
        IReadOnlyList<BindingTarget> targets,
        Algorithm rhsBody,
        List<Property> properties,
        HashSet<string> declaredPropertyNames,
        int writtenRowIndex)
    {
        var sourceName = $"$deconstruct${_deconstructionCounter++}";
        // The hoisted right-hand side is marked with its written position so the front end
        // elaborates its rows as rows of the enclosing body, in written order (see
        // Algorithm.User.AssignmentDeconstructionRowIndex).
        properties.Add(new Property(
            sourceName,
            rhsBody is Algorithm.User rhsUser
                ? rhsUser with { AssignmentDeconstructionRowIndex = writtenRowIndex }
                : rhsBody));
        declaredPropertyNames.Add(sourceName);

        var captures = targets
            .Select(static target => (ParameterPattern)new CaptureParameterPattern(
                new ParameterDeclaration(target.Name, Span: null, target.Kind)
                {
                    CollectMarkerSpan = target.CollectMarkerSpan,
                }))
            .ToList();
        var seqPattern = new SequenceValueParameterPattern(captures);
        // Every target helper shares ONE explicit pattern list: the N-capture sequence-value
        // pattern the written targets form. Parameters/Params derive from it on demand, so
        // constructing a helper is O(1) in the capture count.
        IReadOnlyList<ParameterPattern> helperPatterns = [seqPattern];

        // One identity token shared by every target helper of this deconstruction. The evaluator
        // keys its run-scoped shared-bind cache on it so the N helpers bind the shared N-capture
        // pattern once per binding context instead of once per demanded target (O(N) not O(N^2)).
        var deconstructionGroup = new object();

        for (var targetIndex = 0; targetIndex < targets.Count; targetIndex++)
        {
            var target = targets[targetIndex];

            var helper = new Algorithm.User(
                Parent: null,
                ParameterPatterns: helperPatterns,
                Opens: [],
                Properties: [],
                Output: [new Expr.Resolve(target.Name)])
            {
                HasExplicitParameterList = true,
                AssignmentDeconstructionTarget = new AssignmentDeconstructionTarget(deconstructionGroup, targetIndex),
            };

            OutputBundle args = [new Expr.Resolve(sourceName)];

            var propertyBody = new Algorithm.User(
                Parent: null,
                ParameterPatterns: [],
                Opens: [],
                Properties: [],
                Output: [new Expr.Call(new Expr.AlgorithmExpr(helper), args)]);

            properties.Add(new Property(target.Name, propertyBody)
            {
                DeclarationSpans = [target.NameSpan]
            });
            declaredPropertyNames.Add(target.Name);
        }
    }

    /// <summary>
    /// Exact source-offset adjacency: <paramref name="second"/> starts at the
    /// code unit where <paramref name="first"/> ends, with nothing — no
    /// whitespace, comment, or newline — between them. This is the ONE
    /// attachment test of the marker attachment law: the prefix collect
    /// marker to its binding name (`*name`), the postfix spread marker to
    /// its operand's last token (`value*`, checked only after the star has
    /// been classified as a spread — see <see cref="IsPostfixSpreadMarkerStar"/>
    /// and <see cref="ParseSpreadMarkerContinuation"/>), every Grace marker
    /// to the name or neighbouring marker it belongs to (`~x`, `x~`), and the
    /// `.~` member-Grace pair. Ordinary operators never consult it.
    /// </summary>
    private static bool IsDirectlyAttached(Token first, Token second)
        => second.Position == first.Position + first.Length;

    /// <summary>
    /// The one written-Grace law: `~` decorates exactly one bare
    /// parameter/name occurrence (`~x` / `x~`). Every other operand shape —
    /// prefix on a non-name, and a postfix run after a completed compound
    /// expression such as `(x + y)~`, `f(x)~`, `x.y~`, `[x]~`, or `5~` —
    /// reports this diagnostic.
    /// </summary>
    private const string GraceEligibilityMessage =
        "Grace `~` can only be applied to a parameter or name occurrence.";

    /// <summary>
    /// The marker attachment law for Grace: every marker of a prefix run is
    /// directly attached to the next marker or to the name, and every marker
    /// of a postfix run to the name or to the previous marker (`~x`, `x~`,
    /// `~~x`, `~x~`). A gap anywhere in the occurrence (`~ x`, `x ~`,
    /// `~ ~x`) reports this diagnostic once, over the whole occurrence, and
    /// the recovered tree keeps the plain name: a detached marker decorates
    /// nothing, mirroring the collect marker's never-a-collecting-binding
    /// recovery.
    /// </summary>
    private static string GraceMarkerAttachmentDiagnostic(string name) =>
        $"The Grace marker `~` must be directly attached to the name it decorates: write `~{name}` or `{name}~`.";

    /// <summary>
    /// Consumes one same-line postfix Grace run after a bare name (the name
    /// token already consumed, <paramref name="lastToken"/> being the name or
    /// the last marker consumed so far), accumulating <paramref name="weight"/>
    /// and clearing <paramref name="attached"/> at the first gap. Returns the
    /// last consumed token so callers can span their diagnostics.
    /// </summary>
    private Token ConsumePostfixGraceRun(Token lastToken, ref int weight, ref bool attached)
    {
        var detachedPostfix = false;
        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
        {
            detachedPostfix |= !IsDirectlyAttached(lastToken, Current);
            attached &= !detachedPostfix;
            lastToken = Advance();
            weight++;
        }

        // Only a malformed POSTFIX run owns the following boundary (`x ~ y`).
        // A detached prefix has already recovered its name (`~ x`), so a later
        // item in `~ x y` still needs its own separator diagnostic at `y`.
        if (detachedPostfix)
            OwnSameLineItem(Current);

        return lastToken;
    }

    /// <summary>
    /// Builds the graced occurrence of a bare
    /// name, or reports the attachment law and recovers to the plain name when
    /// any marker of the occurrence was detached. Kept out of
    /// <see cref="ParsePrimary"/> so its locals never enlarge that hot
    /// recursive frame (native stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr CreateGracedName(Token firstToken, Token nameToken, Token lastToken, int weight, bool attached)
    {
        var resolve = ResolveAt(nameToken);
        if (!attached)
        {
            ReportErrorAcross(
                DiagnosticCode.InvalidGraceMarker,
                GraceMarkerAttachmentDiagnostic(nameToken.StringValue!),
                firstToken, lastToken);
            return resolve;
        }

        // Cancelling written markers still need the binding-effectiveness check.
        // A genuinely unmarked name stays plain; elaboration strips every marker.
        return firstToken == nameToken && lastToken == nameToken
            ? resolve
            : GraceFrom(resolve, weight, firstToken);
    }

    /// <summary>
    /// Parses the same-line postfix Grace run after an already-consumed bare
    /// name (`x~`, `x~~`): the postfix half of the one-name Grace law, with
    /// the attachment law enforced by <see cref="CreateGracedName"/>. Kept out
    /// of <see cref="ParsePrimary"/> so its locals never enlarge that hot
    /// recursive frame (native stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParsePostfixGraceOnName(Token nameToken)
    {
        var weight = 0;
        var attached = true;
        var lastToken = ConsumePostfixGraceRun(nameToken, ref weight, ref attached);
        return CreateGracedName(nameToken, nameToken, lastToken, weight, attached);
    }

    /// <summary>
    /// Reports the one-name Grace law for a same-line postfix marker run that
    /// follows a completed COMPOUND operand, consuming exactly that run. A
    /// bare name consumes its own postfix run in <see cref="ParsePrimary"/>,
    /// so a run reaching <see cref="ParsePostfix"/> is never eligible. The
    /// run is physical-line-local: it starts at the current marker (already
    /// proven to be on the operand's line) and stops before the first token
    /// on a later line, so a marker that begins the next row is never
    /// consumed here and the caller resumes on whatever follows — an
    /// ordinary dot edge, a same-line operand (a recovery-owned item that the
    /// separator rule does not report again), or the next row. The
    /// diagnostic spans the run itself, first marker through last. Kept out
    /// of <see cref="ParsePostfix"/> so its locals never enlarge that hot
    /// recursive frame (native stack-margin calibration).
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private void RejectPostfixGraceRunOnCompoundOperand()
    {
        var firstTilde = Current;
        var lastTilde = firstTilde;
        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
            lastTilde = Advance();
        ReportErrorAcross(
            DiagnosticCode.InvalidGraceMarker,
            GraceEligibilityMessage,
            firstTilde, lastTilde);
        // The rejected run owns the boundary after it: `f(x)~ c` reports the
        // Grace law once and leaves `c` as a recovery-owned item, never a
        // second separator-rule diagnostic.
        OwnSameLineItem(Current);
    }

    /// <summary>
    /// Parses a `~`-led primary: prefix Grace on the ONE bare name that
    /// follows the marker run on the run's own physical line, then any
    /// same-line postfix markers after that name (`~x~` nets to weight 0 and
    /// retains its marker until effectiveness validation). The whole run is physical-line-local — a
    /// marker on a later line is never consumed as part of this run, and a
    /// name on a later line never becomes its operand — so `~` newline `~a`
    /// reports the first line's lone marker and leaves `~a` intact as the next
    /// row's own prefix-grace expression. A run not followed by a same-line
    /// name reports the one-name Grace law over the run (first marker
    /// through last). Recovery consumes nothing beyond the run: the token
    /// after it — on this line or the next — is left for ordinary parsing
    /// (`F(1)~` newline `-1` keeps a `-1` row, never a `1` row), and the
    /// consumed run itself is the progress that keeps the caller moving; the
    /// placeholder operand carries the run's span.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]
    private Expr ParsePrefixGracePrimary()
    {
        var firstTilde = Current;
        var lastTilde = Advance(); // the run always owns its first marker
        var weight = -1;
        // The attachment law (GraceMarkerAttachmentDiagnostic): every marker
        // is directly attached to the next marker or to the name.
        var attached = true;
        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
        {
            attached &= IsDirectlyAttached(lastTilde, Current);
            lastTilde = Advance();
            weight--;
        }

        if (Current.Kind != TokenKind.Identifier || !IsSamePhysicalLineAsPreviousToken())
        {
            ReportErrorAcross(
                DiagnosticCode.InvalidGraceMarker,
                GraceEligibilityMessage,
                firstTilde, lastTilde);
            // The lone run owns the boundary after it (`~ 5` reports the Grace
            // law once; `5` is not additionally a separator error).
            OwnSameLineItem(Current);
            return PlaceholderFrom(firstTilde);
        }

        attached &= IsDirectlyAttached(lastTilde, Current);
        var nameToken = Advance();
        // Postfix grace: each same-line marker after the name increments the
        // weight; a marker on a later line never continues, including one
        // immediately before an ordinary dot.
        var lastToken = ConsumePostfixGraceRun(nameToken, ref weight, ref attached);
        return CreateGracedName(firstTilde, nameToken, lastToken, weight, attached);
    }

    /// <summary>
    /// Checks if the current tilde sequence is followed by Identifier '=' or 'public Identifier ='.
    /// Used to detect invalid grace on property definitions. The run and the
    /// declaration head share one physical line: a marker run followed by a
    /// declaration on a later line is the lone marker of ITS line (reported by
    /// <see cref="ParsePrefixGracePrimary"/>), and the declaration stays intact.
    /// <para>Linear in the run (bug-hunt B5a, K2-R3). The scan walks token indices
    /// through <see cref="NextSignificantIndex"/> from ONE cursor — never
    /// <see cref="PeekSignificant"/>, which restarts at <c>_pos</c> and is
    /// O(offset) per call, so calling it for offset 0..k over a k-marker run made
    /// one row-start run cost O(k²) — and its verdict is memoized by the run's
    /// first significant token index, so the declaration-boundary consumers (the
    /// algorithm loop and <see cref="StartsDeclaration"/>) scan one run at most
    /// once between them: a run costs O(k) in total, never O(k) per consult. The
    /// verdict is a pure function of the immutable token array from that index,
    /// so the memo can never go stale. Lookahead answers, diagnostics, spans, and
    /// the produced tree are exactly those of the offset walk.</para>
    /// </summary>
    private bool LookaheadThroughTildesToPropertyDef()
        => LookaheadThroughTildesToPropertyDefFrom(NextSignificantIndex(_pos));

    /// <summary>
    /// Index form of <see cref="LookaheadThroughTildesToPropertyDef"/>: the
    /// same memoized scan, started at the significant token at
    /// <paramref name="start"/>.
    /// </summary>
    private bool LookaheadThroughTildesToPropertyDefFrom(int start)
    {
        if (start == _graceRunScanStart)
            return _graceRunScanVerdict;

        var line = _tokens[start].Line;
        var index = start;
        while (_tokens[index].Kind == TokenKind.Tilde && _tokens[index].Line == line)
            index = NextSignificantIndex(index + 1);

        // The declaration-head line rule (IsHeadToken): the markers, the name,
        // and the '=' all share the first marker's physical line.
        var verdict = false;
        if (_tokens[index].Line == line)
        {
            var next = NextSignificantIndex(index + 1);
            if (_tokens[index].Kind == TokenKind.Identifier)
            {
                // ~Name = ...
                verdict = _tokens[next].Kind == TokenKind.Equals && IsHeadToken(next, line);
            }
            else if (_tokens[index].Kind == TokenKind.KeywordPublic
                && _tokens[next].Kind == TokenKind.Identifier
                && _tokens[next].Line == line)
            {
                // ~public Name = ...
                var equals = NextSignificantIndex(next + 1);
                verdict = _tokens[equals].Kind == TokenKind.Equals && IsHeadToken(equals, line);
            }
        }

        _graceRunScanStart = start;
        _graceRunScanVerdict = verdict;
        return verdict;
    }

    /// <summary>
    /// Checks if 'public' keyword is followed by 'open' keyword on the same
    /// physical line (the declaration-head line rule, see <see cref="IsHeadToken"/>).
    /// Used to detect and reject public open declarations.
    /// </summary>
    private bool LookaheadIsPublicOpen()
    {
        var next = NextSignificantIndex(_pos + 1); // skip 'public'
        return _tokens[next].Kind == TokenKind.KeywordOpen && IsHeadToken(next, Current.Line);
    }

    /// <summary>
    /// Checks if 'public' keyword is followed by Identifier '=' on the same
    /// physical line (the declaration-head line rule, see <see cref="IsHeadToken"/>).
    /// Used to detect public property definitions.
    /// </summary>
    private bool LookaheadIsPublicPropertyDef()
    {
        var next = NextSignificantIndex(_pos + 1); // skip 'public'
        return _tokens[next].Kind == TokenKind.Identifier
            && IsHeadToken(next, Current.Line)
            && LookaheadIsEqualsFrom(next);
    }

    /// <summary>
    /// Checks if the current identifier is followed by '(' ... ')' '='.
    /// Used to detect clause definitions: <c>Name(pattern) = body</c>.
    /// Skips comment tokens during lookahead. Handles nested parentheses and
    /// applies the declaration-head line rule.
    /// </summary>
    private bool LookaheadIsClauseDefinition()
        => LookaheadIsParenEqualsAfterName(_pos);

    /// <summary>
    /// Whether the current row begins with a reserved Boolean literal written as a
    /// declaration head — <c>true =</c>, <c>false(pattern) =</c>, optionally after
    /// <c>public</c> — under the ordinary declaration-head line rule
    /// (<see cref="IsHeadToken"/>). The literals are keywords, never names, so such a
    /// head can never be a declaration; recognizing it lets the parser name the
    /// mistake instead of reporting a stray <c>'='</c>.
    /// </summary>
    private bool IsReservedLiteralDeclarationHead()
    {
        var index = _pos;
        if (_tokens[index].Kind == TokenKind.KeywordPublic)
        {
            index = NextSignificantIndex(index + 1);
            if (!IsHeadToken(index, Current.Line))
                return false;
        }

        return _tokens[index].Kind is TokenKind.KeywordTrue or TokenKind.KeywordFalse
            && (LookaheadIsEqualsFrom(index) || LookaheadIsParenEqualsAfterName(index));
    }

    /// <summary>
    /// Reports a reserved Boolean literal used as a declaration name AT the literal, then
    /// skips the malformed head (the literal, any clause pattern list, and its '=') so the
    /// body after '=' parses as an ordinary output row; the diagnosed head owns the
    /// boundary before that row.
    /// </summary>
    private void ReportReservedLiteralDeclaration()
    {
        if (Current.Kind == TokenKind.KeywordPublic)
            Advance(); // the modifier is not the mistake; the literal is
        var spelling = Current.Kind == TokenKind.KeywordTrue ? "true" : "false";
        ReportError(
            DiagnosticCode.UnexpectedToken,
            $"'{spelling}' is the reserved Boolean literal, not a name: it cannot be declared as a property, clause, or parameter, and it cannot be shadowed.");
        while (Current.Kind is not (TokenKind.Equals or TokenKind.EndOfFile))
            Advance();
        if (Current.Kind == TokenKind.Equals)
            Advance();
        OwnSameLineItem(Current);
    }

    /// <summary>
    /// Checks if 'public' is followed by Identifier '(' ... ')' '=' (the name
    /// on the modifier's physical line, then the ordinary clause-head rule).
    /// Used to detect public clause definitions.
    /// </summary>
    private bool LookaheadIsPublicClauseDefinition()
    {
        var next = NextSignificantIndex(_pos + 1); // skip 'public'
        if (_tokens[next].Kind != TokenKind.Identifier || !IsHeadToken(next, Current.Line))
            return false;
        return LookaheadIsParenEqualsAfterName(next);
    }

    /// <summary>
    /// Checks for a clause head after the name at <paramref name="nameIndex"/>:
    /// '(' ... ')' '=' with balanced parens, skipping comment tokens. The
    /// declaration-head line rule applies (see <see cref="IsHeadToken"/>): the
    /// '(' shares the name's physical line and the '=' shares the ')'s line,
    /// while the pattern list inside the open parentheses may span lines like
    /// every already-open delimiter (`F(a,` newline `b) = a + b`).
    /// </summary>
    private bool LookaheadIsParenEqualsAfterName(int nameIndex)
    {
        var next = NextSignificantIndex(nameIndex + 1);
        if (_tokens[next].Kind != TokenKind.LParen || !IsHeadToken(next, _tokens[nameIndex].Line))
            return false;
        next++; // skip '('
        var depth = 1;
        var closeLine = 0;
        while (depth > 0)
        {
            next = NextSignificantIndex(next);
            var kind = _tokens[next].Kind;
            if (kind == TokenKind.EndOfFile)
                return false;
            if (kind == TokenKind.LParen) depth++;
            else if (kind == TokenKind.RParen)
            {
                depth--;
                closeLine = _tokens[next].Line;
            }
            next++;
        }
        next = NextSignificantIndex(next);
        return _tokens[next].Kind == TokenKind.Equals && IsHeadToken(next, closeLine);
    }

    // ── Pattern parsing (for clause definitions) ────────────────────────────

    /// <summary>
    /// Finds the <see cref="SourceSpan"/> of the first <see cref="Expr.Grace"/> node in the list.
    /// Used to reject Grace in conditional branch bodies with accurate error location.
    /// <para>MUST STAY ITERATIVE: this scan runs while clause families are still being
    /// elaborated, BEFORE the finished root reaches the <see cref="AstStructuralPreflight"/>
    /// gate in <see cref="ParseSyntax(string, PatternComparisonObservations?, int)"/>, so it
    /// can receive composed trees (in-budget chains stacked inside in-budget container
    /// levels) far deeper than any CLR-safe recursion depth.</para>
    /// </summary>
    private static SourceSpan? FindGraceSpan(IReadOnlyList<Expr> exprs)
    {
        var pending = new Stack<Expr>();
        for (var i = exprs.Count - 1; i >= 0; i--)
            pending.Push(exprs[i]);
        return ScanPendingForGraceSpan(pending);
    }

    private static SourceSpan? FindGraceSpan(Expr expr)
    {
        var pending = new Stack<Expr>();
        pending.Push(expr);
        return ScanPendingForGraceSpan(pending);
    }

    /// <summary>
    /// Shared iterative core of both <c>FindGraceSpan</c> overloads: a depth-first,
    /// source-order scan over an explicit heap stack. Children are pushed in reverse
    /// so the LIFO stack yields them left to right, keeping the original first-match
    /// span selection. Only the child positions the scan has always inspected are
    /// pushed — argument/block OUTPUT rows but never opens, properties, or patterns,
    /// and never a WRITTEN <see cref="Expr.Grace"/> node's Inner (a written grace is
    /// a match boundary: it either supplies its span or, span-less, contributes
    /// nothing). DotCall's stored fallback is visited at the member occurrence
    /// position so prefix member Grace is rejected by the same branch-body rule.
    /// </summary>
    private static SourceSpan? ScanPendingForGraceSpan(Stack<Expr> pending)
    {
        while (pending.Count > 0)
        {
            var expr = pending.Pop();
            switch (expr)
            {
                case Expr.Grace g:
                    if (g.Span is { } span)
                        return span;
                    break;
                case Expr.Binary(_, var left, var right):
                    pending.Push(right);
                    pending.Push(left);
                    break;
                case Expr.Comparison(var first, var links):
                    for (var i = links.Count - 1; i >= 0; i--)
                        pending.Push(links[i].Operand);
                    pending.Push(first);
                    break;
                case Expr.Unary(_, var operand):
                    pending.Push(operand);
                    break;
                case Expr.Index(var target, var selector):
                    pending.Push(selector);
                    pending.Push(target);
                    break;
                case Expr.SequenceConstruct(var left, var right):
                    pending.Push(right);
                    pending.Push(left);
                    break;
                case Expr.SequenceSpread(var operand):
                    pending.Push(operand);
                    break;
                case Expr.ListLiteral(var items):
                    PushInReverse(pending, items);
                    break;
                case Expr.DotCall dotCall:
                    if (dotCall.Args is { } dotArgs)
                        PushInReverse(pending, dotArgs);
                    if (dotCall.LexicalFallback is { } fallback)
                        pending.Push(fallback);
                    pending.Push(dotCall.Target);
                    break;
                case Expr.Call(var function, var args):
                    PushInReverse(pending, args);
                    pending.Push(function);
                    break;
                case Expr.AlgorithmExpr(var algorithm):
                    PushInReverse(pending, algorithm.Output);
                    break;
                case Expr.Capture(var body):
                    PushInReverse(pending, body);
                    break;
                case Expr.Resolve or Expr.Param or Expr.Num or Expr.StringLiteral or Expr.BoolLiteral
                    or Expr.EmptySequence or Expr.NativeCall:
                    break;
                // Closed hierarchies do not make switch statements exhaustive. Keep
                // this iterative scan fail-loud when a new expression shape is added.
                default:
                    throw new InvalidOperationException(
                        $"Unhandled Expr variant in {nameof(Parser)}.{nameof(ScanPendingForGraceSpan)}: {expr.GetType().Name}.");
            }
        }
        return null;

        static void PushInReverse(Stack<Expr> pending, IReadOnlyList<Expr> exprs)
        {
            for (var i = exprs.Count - 1; i >= 0; i--)
                pending.Push(exprs[i]);
        }
    }

    private static bool PatternContainsCollectingParameter(Pattern pattern)
        => pattern switch
        {
            Pattern.Bind { ParameterKind: ParameterKind.Collecting } => true,
            Pattern.SequenceValue(var items) => items.Any(PatternContainsCollectingParameter),
            _ => false,
        };

    /// <summary>Reports collecting-binding misuse in a clause head at the clause's name token.</summary>
    private void ValidateCollectingParameterDeclarations(string propertyName, Pattern pattern, Token nameToken)
    {
        if (pattern.TryGetOrdinaryClauseParameterPatterns() is not { } parameterPatterns)
        {
            if (PatternContainsCollectingParameter(pattern))
            {
                ReportErrorAt(
                    DiagnosticCode.InvalidCollectingBinding,
                    $"Collecting bindings are only supported in ordinary explicit parameter lists for '{propertyName}'.",
                    nameToken);
            }
            return;
        }

        if (ParameterPattern.HasMultipleCollectingCapturesAtAnyLevel(parameterPatterns))
        {
            ReportErrorAt(
                DiagnosticCode.InvalidCollectingBinding,
                "Only one collecting binding is allowed per pattern level.",
                nameToken);
        }
        else if (ParameterPattern.HasRepeatedCaptureNameIncludingCollecting(parameterPatterns))
        {
            ReportErrorAt(
                DiagnosticCode.InvalidCollectingBinding,
                "Repeated parameter names cannot include collecting bindings.",
                nameToken);
        }
    }

    /// <summary>
    /// Parses a clause-head pattern for ordinary recursive parameter patterns
    /// or conditional algorithm branches.
    /// Patterns are comma-separated at the top level (creating a sequence-value pattern
    /// when more than one element), with support for:
    /// - integer literals (including negative)
    /// - identifier binders
    /// - nested parenthesized sequence-value patterns
    /// </summary>
    private Pattern ParsePattern()
    {
        var items = ParsePatternItems();
        if (items.Count != 1)
            return new Pattern.SequenceValue(items);

        return items[0] is Pattern.SequenceValue ? new Pattern.SequenceValue(items) : items[0];
    }

    private List<Pattern> ParsePatternItems()
    {
        var items = new List<Pattern>();
        items.Add(ParsePatternAtom());

        while (true)
        {
            if (Current.Kind == TokenKind.Comma)
                Advance(); // consume ','
            else if (!StartsUnseparatedPatternItem())
                break;

            items.Add(ParsePatternAtom());
        }

        return items;
    }

    /// <summary>
    /// SYN-07A for parameter-pattern lists — the ONE boundary decision of
    /// <see cref="ParsePatternItems"/> (clause heads <c>F(a, b) = …</c> and
    /// nested sequence-value patterns <c>(x, *y)</c>): true when the current
    /// token begins another pattern item on the SAME physical line as the
    /// pattern just parsed, without the comma the list requires. The item is
    /// reported at its first token — the pattern-worded report of the
    /// <see cref="DiagnosticCode.UnseparatedSameLineItem"/> family — and then
    /// admitted as the next pattern of THIS list, so <c>F(a b) = a + b</c>
    /// recovers as the clause head <c>F(a, b)</c>: its <c>)</c> and <c>=</c>
    /// are then found where they were written, the body stays F's body, and
    /// nothing leaks into the enclosing scope as unrelated rows or implicit
    /// parameters. A boundary a pattern-atom recovery already owns
    /// (<see cref="OwnSameLineItem"/>) is admitted silently, exactly like the
    /// expression-list rule. A token on a later line is never admitted here:
    /// parameter lists have no newline separator, so it reaches the ordinary
    /// closing-delimiter check unchanged. What can begin a pattern item is
    /// the atom grammar's own starter set (<see cref="CanStartPatternAtom"/>),
    /// with one refinement for the star: a star that no operand can follow is
    /// a (misplaced) spread marker on the pattern before it, never the collect
    /// marker of a next binding — the same classifier the atom grammar and the
    /// expression-level star decision use — so it is left to the closing
    /// delimiter path and keeps the marker diagnostics the pattern grammar
    /// owns (<c>F(a *)</c>, <c>F(1*)</c>). A star an operand follows begins a
    /// collecting binding missing its comma (<c>F(a *b)</c> recovers as
    /// <c>F(a, *b)</c>), and the marker grammar then reports a detached or
    /// nameless marker on its own (<c>F(a * b)</c>, <c>F(a *2)</c>).
    /// </summary>
    private bool StartsUnseparatedPatternItem()
    {
        if (!IsSamePhysicalLineAsPreviousToken() || !CanStartPatternAtom(Current.Kind))
            return false;

        if (Current.Kind == TokenKind.Star && !CanStartMultiplicationOperand(PeekSignificant(1).Kind))
            return false;

        ReportUnseparatedSameLineItem(Current, UnseparatedPatternItemMessage);
        return true;
    }

    /// <summary>
    /// THE pattern-atom starter set: exactly the token kinds
    /// <see cref="ParsePatternAtomCore"/> parses as the beginning of a pattern
    /// item (its non-default arms). The switch's default arm guards the
    /// relation in the fail-loud direction — a starter without an arm throws —
    /// and <c>SameLineSeparatorTests</c> pins the classification of every
    /// <see cref="TokenKind"/>, so the predicate and the grammar cannot drift
    /// apart. Deliberately narrower than <see cref="CanStartExpression"/>: a
    /// pattern has no <c>not</c>, block, or list form.
    /// </summary>
    private static bool CanStartPatternAtom(TokenKind kind) => kind switch
    {
        TokenKind.Star          // collecting binding `*name`
        or TokenKind.Tilde      // rejected Grace, recovered to its name
        or TokenKind.Number
        or TokenKind.Minus      // negative literal
        or TokenKind.StringLiteral
        or TokenKind.KeywordTrue   // Boolean literal pattern
        or TokenKind.KeywordFalse
        or TokenKind.Identifier
        or TokenKind.LParen => true, // nested sequence-value pattern
        _ => false,
    };

    /// <summary>
    /// Parses a single atomic pattern element:
    /// - number literal → Pattern.LitInt
    /// - negative number → Pattern.LitInt with negated value
    /// - identifier → Pattern.Bind
    /// - ( pattern ) -> nested sequence-value pattern
    /// Grace `~` is rejected in clause-head patterns.
    /// </summary>
    private Pattern ParsePatternAtom()
    {
        // Clause-head pattern nesting recurses through here (the nested `(pattern)`
        // case), so enforce the shared parser recursion budget once per level.
        using var level = EnterNestingLevel();
        return ParsePatternAtomCore();
    }

    /// <summary>
    /// Builds a named binding pattern with optional collecting metadata.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private static Pattern CreateBindingPattern(
        Token nameToken,
        ParameterKind kind = ParameterKind.Normal,
        Token? collectMarkerToken = null)
        => new Pattern.Bind(nameToken.StringValue!)
        {
            NameSpan = nameToken.Span,
            ParameterKind = kind,
            CollectMarkerSpan = collectMarkerToken?.Span,
        };

    /// <summary>
    /// Parses a collecting binding <c>*name</c> at the start of a pattern
    /// atom (the star is not yet consumed). The collect marker must be
    /// DIRECTLY attached to its binding name — a gap reports the targeted
    /// attachment diagnostic, a repeated star reports the repeated-marker
    /// diagnostic, and a star without a name reports the missing-name
    /// diagnostic. Malformed recovery binds the name as an ordinary fixed
    /// binding (or a placeholder) and never introduces a collecting binding.
    /// </summary>
    private Pattern ParseCollectingBindingPatternAtom()
    {
        var markerToken = Advance(); // consume '*'

        // Repeated markers (`**items`): consume the run, report once, and
        // never create a collecting binding from the malformed shape.
        if (Current.Kind == TokenKind.Star)
        {
            var lastStar = markerToken;
            while (Current.Kind == TokenKind.Star)
                lastStar = Advance();

            if (Current.Kind == TokenKind.Identifier)
            {
                var repeatedNameToken = Advance();
                ReportErrorAcross(
                    DiagnosticCode.InvalidCollectMarker,
                    RepeatedCollectMarkerDiagnostic(repeatedNameToken.StringValue!),
                    markerToken, repeatedNameToken);
                return CreateBindingPattern(repeatedNameToken);
            }

            ReportErrorAcross(
                DiagnosticCode.InvalidCollectMarker,
                CollectMarkerMissingNameDiagnostic,
                markerToken, lastStar);
            return new Pattern.Bind("_error_");
        }

        if (Current.Kind != TokenKind.Identifier)
        {
            ReportErrorAt(DiagnosticCode.InvalidCollectMarker, CollectMarkerMissingNameDiagnostic, markerToken);

            // Consume one malformed same-line pattern atom where possible so a
            // following comma/closing delimiter remains available to the caller.
            // Malformed syntax must not introduce collecting-binding semantics
            // into the recovered tree.
            if (Current.Kind is not (TokenKind.Comma
                or TokenKind.RParen
                or TokenKind.RBrace
                or TokenKind.EndOfFile)
                && Current.Line == markerToken.Line)
                return ParsePatternAtom();

            return new Pattern.Bind("_error_");
        }

        var nameToken = Advance();
        var name = nameToken.StringValue!;

        if (!IsDirectlyAttached(markerToken, nameToken))
        {
            ReportErrorAcross(
                DiagnosticCode.InvalidCollectMarker,
                CollectMarkerAttachmentDiagnostic(name),
                markerToken, nameToken);
            // A detached marker is not a collecting binding; the name stays
            // an ordinary fixed binding in the recovered tree.
            return CreateBindingPattern(nameToken);
        }

        var hadPostfixGrace = false;
        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
        {
            hadPostfixGrace = true;
            Advance();
        }
        if (hadPostfixGrace)
            ReportErrorAt(
                DiagnosticCode.InvalidGraceMarker,
                "Collecting bindings cannot use `~` reordering.",
                nameToken);

        return CreateBindingPattern(nameToken, ParameterKind.Collecting, markerToken);
    }

    private Pattern ParsePatternAtomCore()
    {
        switch (Current.Kind)
        {
            case TokenKind.Star:
                return ParseCollectingBindingPatternAtom();

            case TokenKind.Tilde:
                {
                    var firstTilde = Current;
                    var lastGraceToken = Current;
                    while (Current.Kind == TokenKind.Tilde && Current.Line == firstTilde.Line)
                        lastGraceToken = Advance(); // skip prefix tildes
                    if (Current.Kind == TokenKind.Identifier && Current.Line == firstTilde.Line)
                    {
                        var token = Advance();
                        lastGraceToken = token;
                        while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
                            lastGraceToken = Advance(); // skip postfix tildes
                        ReportErrorAcross(
                            DiagnosticCode.InvalidGraceMarker,
                            "Grace is not allowed in clause-head patterns.",
                            firstTilde, lastGraceToken);
                        return CreateBindingPattern(token);
                    }

                    // No identifier follows: the diagnostic covers the marker
                    // run itself; the recovered atom reports its own errors.
                    ReportErrorAcross(
                        DiagnosticCode.InvalidGraceMarker,
                        "Grace is not allowed in clause-head patterns.",
                        firstTilde, lastGraceToken);
                    // Try to parse remaining atom for recovery. `~*name` reaches
                    // the collecting-binding atom below, so the grace error keeps
                    // the collecting binding.
                    return ParsePatternAtom();
                }

            case TokenKind.Number:
                {
                    var token = Advance();
                    return new Pattern.LitInt(token.NumValue);
                }

            case TokenKind.Minus:
                {
                    Advance(); // consume '-'
                    if (Current.Kind != TokenKind.Number)
                    {
                        ReportError(DiagnosticCode.UnexpectedToken, "Expected number after '-' in pattern.");
                        // The diagnosed token owns this boundary: `F(-x)`
                        // reports the missing number once, and `x` is not
                        // additionally an unseparated pattern item.
                        OwnSameLineItem(Current);
                        return new Pattern.Bind("_error_");
                    }
                    var token = Advance();
                    return new Pattern.LitInt(-token.NumValue);
                }

            case TokenKind.StringLiteral:
                {
                    var token = Advance();
                    return new Pattern.LitString(token.StringValue ?? "");
                }

            case TokenKind.KeywordTrue:
            case TokenKind.KeywordFalse:
                {
                    // The reserved Boolean literals are literal patterns, never binders:
                    // `F(true) = …` matches the Boolean value `true` only.
                    var token = Advance();
                    return new Pattern.LitBool(token.Kind == TokenKind.KeywordTrue);
                }

            case TokenKind.Identifier:
                {
                    var token = Advance();
                    var name = token.StringValue!;

                    Token? lastPostfixTilde = null;
                    while (Current.Kind == TokenKind.Tilde && MayContinueClosedExpression(TokenKind.Tilde))
                        lastPostfixTilde = Advance();

                    if (lastPostfixTilde is not null)
                        ReportErrorAcross(
                            DiagnosticCode.InvalidGraceMarker,
                            "Grace is not allowed in clause-head patterns.",
                            token, lastPostfixTilde);

                    // Postfix `*` after a binding name is spread syntax, never
                    // binding syntax. Report the targeted marker-side diagnostic
                    // when the star is clearly meant as a marker — nothing that
                    // could begin a multiplication operand follows it (the ONE
                    // classifier the expression-level star decision uses, so
                    // spacing and line breaks never matter here either); a star
                    // followed by an operand-like token is left to the caller:
                    // the pattern list reads it as the collect marker of a next
                    // binding missing its comma (StartsUnseparatedPatternItem,
                    // `F(a *b)`), and the marker grammar then reports a detached
                    // or nameless marker on its own (`F(a * b)`, `F(a *2)`).
                    if (Current.Kind == TokenKind.Star
                        && MayContinueClosedExpression(TokenKind.Star))
                    {
                        var looksLikeMarker = !CanStartMultiplicationOperand(PeekSignificant(1).Kind);
                        if (looksLikeMarker)
                        {
                            var lastStar = Advance();
                            while (Current.Kind == TokenKind.Star
                                && MayContinueClosedExpression(TokenKind.Star))
                                lastStar = Advance(); // consume a malformed star run whole
                            ReportErrorAcross(
                                DiagnosticCode.InvalidCollectMarker,
                                SpreadMarkerInBindingPatternDiagnostic(name),
                                token, lastStar);
                            return CreateBindingPattern(token);
                        }
                    }

                    return CreateBindingPattern(token);
                }

            case TokenKind.LParen:
                {
                    Advance(); // consume '('
                    var items = ParsePatternItems();
                    Expect(TokenKind.RParen);
                    // Parentheses in patterns are structural at every nesting level:
                    // (a, b) -> SequenceValue([a, b]); (x) -> SequenceValue([x]);
                    // ((a, b)) -> SequenceValue([SequenceValue([a, b])]).
                    return new Pattern.SequenceValue(items);
                }

            default:
                {
                    if (CanStartPatternAtom(Current.Kind))
                        throw new InvalidOperationException($"Pattern-atom starter {Current.Kind} has no ParsePatternAtomCore arm.");

                    ReportError(DiagnosticCode.UnexpectedToken, $"Unexpected {DescribeTokenKind(Current.Kind, includeArticle: false)} in a pattern.");
                    SkipForRecovery(); // the token after it is a recovery-owned boundary
                    return new Pattern.Bind("_error_");
                }
        }
    }

    // ── Output line parsing ─────────────────────────────────────────────────
    // Reads comma-separated expressions (spread slots via the attached
    // postfix spread marker `expr*`).

    /// <summary>
    /// Parses a property body as an algorithm: the comma-separated expressions
    /// become the algorithm's output list.
    /// If the body is a single algorithm-valued block expression, return its
    /// algorithm directly (enables nested property access like X.Y where
    /// X = { Y = ... }). Plain sequence values such as <c>(a, b)</c> stay wrapped
    /// as a single block output so callers can distinguish one sequence value
    /// from multiple top-level outputs.
    /// Assignment deconstruction preserves a written block inside its shared RHS wrapper.
    /// </summary>
    private Algorithm ParseOutputLine(bool preserveWrittenBlock = false)
    {
        // Definition bodies are line-bounded: a newline ends the body and never
        // continues it as another expression-list row. An expression on a
        // following line is parsed by the surrounding output/algorithm context,
        // not absorbed into this body. A same-line comma, an already-open
        // delimiter, a same-line trailing/leading binary operator, and a
        // leading '.' (method-chain layout) still continue the body. A second
        // same-line item without a comma is the SYN-07A separator error and is
        // RECOVERED INTO THIS BODY as its next slot (`P = a b` keeps `b` in P),
        // never leaked to the enclosing scope as an output row. A ';' is
        // invalid expression syntax and reports the unsupported-semicolon
        // diagnostic; any tokens consumed after it are error recovery, not a
        // valid continuation.
        var exprs = ParseExpressionListOperand(allowNewlineSeparator: false);

        // Unwrap only scope-owning algorithm expressions (brace blocks and
        // recovery blocks with declarations/opens): `X = { ... }` merges the
        // brace algorithm into the property body. A plain parenthesized
        // capture such as `X = (a, b)` stays one captured value boundary —
        // the distinction is now structural (AlgorithmExpr vs Capture).
        if (!preserveWrittenBlock && exprs.Count == 1
            && exprs[0] is Expr.AlgorithmExpr(var innerAlg))
            return innerAlg;

        return new Algorithm.User(
            Parent: null,
            ParameterPatterns: [],
            Opens: [],
            Properties: [],
            Output: exprs);
    }

    /// <summary>
    /// Normalizes and validates open expressions. The list arriving here
    /// comes from ParseOpenTargetList's dedicated comma-list parsing — one
    /// individual target per entry, matching Lean's per-target model. A
    /// spread-marked target (`open A*`) parses to a SequenceSpread and is
    /// rejected here by open-form validation before evaluator or runtime
    /// involvement — spread is not an open form.
    /// DotCall(obj, name, null) is the canonical form for dotted paths in opens.
    /// Rejects DotCall with args as invalid.
    /// Lean: Expr.openForm? — only Block, Resolve, and argumentless DotCall
    /// are open forms; everything else is rejected.
    /// </summary>
    private void NormalizeAndValidateOpenForms(List<Expr> exprs)
    {
        for (var i = 0; i < exprs.Count; i++)
            exprs[i] = NormalizeOpenExpr(exprs[i]);

        foreach (var expr in exprs)
        {
            if (expr is Expr.Capture)
            {
                // A surviving multi-slot or spread group is a VALUE boundary, not an
                // algorithm: `open` consumes algorithm/namespace identity, and
                // a capture never exposes the identity of what it encloses.
                ReportOpenFormError(CapturedOpenTargetDiagnostic, expr);
            }
            else if (!IsOpenForm(expr))
            {
                var kind = OpenExprKind(expr);
                ReportOpenFormError($"Invalid open form: '{kind}' is not allowed in open declarations.", expr);
            }
        }
    }

    internal const string CapturedOpenTargetDiagnostic =
        "Invalid open form: a parenthesized group is a captured value, not an algorithm. Open the algorithm directly (open M) or use a `{ ... }` block.";

    // Open-form diagnostics must point at the offending open target, not at
    // whatever token follows the open declaration.
    private void ReportOpenFormError(string message, Expr expr)
    {
        if (expr.Span is { } span)
            ReportError(DiagnosticCode.BadOpenForm, message, span);
        else
            ReportError(DiagnosticCode.BadOpenForm, message);
    }

    /// <summary>
    /// Recursively normalizes an open expression:
    /// - DotCall(obj, name, null) is the canonical no-arg form (kept as-is)
    /// - DotCall(obj, name, args) → report error (call-like syntax not allowed in opens)
    /// - Recurse through the DotCall target and stored fallback/name occurrence;
    ///   AlgorithmExpr/Capture nodes are kept as-is.
    /// A SequenceSpread target falls through unchanged (never rebuilt here,
    /// which would bypass CreateSequenceSpread) and is rejected by the
    /// open-form validation that follows.
    /// </summary>
    private Expr NormalizeOpenExpr(Expr expr)
    {
        switch (expr)
        {
            case Expr.Grace grace:
                // Grace annotates implicit parameter ORDER; an open target
                // consumes structural algorithm identity, where no parameter
                // inference exists, so a grace-marked target is not an open
                // form. This covers written prefix/postfix Grace on a target
                // occurrence (`open ~A`, `open A~`, `open A~.B`) and prefix
                // Grace on a dot member occurrence (`open A.~B`). Recovery
                // unwraps the individual name occurrence, so no Grace node
                // ever survives open elaboration.
                ReportOpenFormError(
                    "Invalid open form: 'grace' is not allowed in open declarations.",
                    grace);
                return NormalizeOpenExpr(grace.Inner);

            case Expr.DotCall dotCall when dotCall.Args is null:
                return dotCall with
                {
                    Target = NormalizeOpenExpr(dotCall.Target),
                    LexicalFallback = dotCall.LexicalFallback is { } fallback
                        ? NormalizeOpenExpr(fallback)
                        : null,
                };

            case Expr.DotCall dotCall:
                ReportOpenFormError(
                    $"Invalid open form: call-like dotCall '.{dotCall.Name}(...)' is not allowed in open declarations.",
                    expr);
                // Recovery: the argumentless path the target names (`open A.X()` recovers
                // as `open A.X`), so the one report above is the whole diagnosis and the
                // open-form validation that follows sees a valid form — never a second
                // report for the same target.
                return NormalizeOpenExpr(dotCall with { Args = null });

            case Expr.AlgorithmExpr or Expr.Capture:
                // Inline algorithm targets stay as-is and are valid open
                // forms. A capture target — a group with several slots or a
                // lone spread slot (`open (A, B)`, `open (A*)`; a redundant
                // group such as `open (M)` is simply `open M` by the time it
                // is parsed) — also stays as-is structurally, but the
                // open-form validation that follows rejects it: a capture is a
                // value boundary, not an algorithm.
                return expr;

            default:
                return expr;
        }
    }

    /// <summary>
    /// Predicate for valid open forms at parse time.
    /// Lean: Expr.openForm? — only AlgorithmExpr, Resolve, and
    /// argumentless DotCall post-elaboration. Spread is NOT an open form (a
    /// spread-marked target such as `open A*` is rejected here), and a
    /// Capture is NOT an open form (`open (M, M)` is a captured value target,
    /// rejected with the targeted captured-open diagnostic above).
    /// DotCall with args is NOT a valid open form.
    /// load calls (Call(Resolve("load"), _)) are allowed as *surface* open forms because
    /// the load elaboration pass will rewrite them to AlgorithmExpr nodes before open
    /// resolution. After elaboration, no load calls or StringLiteral nodes remain —
    /// see Lean postElabInvariant (rejects both structurally).
    /// load is NOT a core Expr constructor; it is surface syntax only.
    /// </summary>
    // An open target consumes structural algorithm identity, so only
    // argumentless dot paths qualify. Grace on either the receiver or member
    // occurrence is reported and unwrapped by NormalizeOpenExpr first.
    private static bool IsOpenForm(Expr e)
        => e.IsCoreOpenForm() || e.TryGetUnresolvedLoadArguments(out _);

