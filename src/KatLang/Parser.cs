namespace KatLang;

/// <summary>
/// The KatLang front end without evaluation. <see cref="Parse(string)"/>,
/// <see cref="Parse(string, RunOptions?)"/>, and <see cref="ParseAsync"/> run the complete
/// front end <see cref="KatLangEngine"/> uses — parsing, <c>load</c> elaboration, parameter
/// detection, implicit-argument resolution, and property-exposure resolution — and return
/// the elaborated program with its diagnostics as a <see cref="ParseResult"/>. Only those
/// complete entry points are public; the individual passes are not, because a partially
/// elaborated tree would evaluate differently from the same source run through the engine.
/// <para>Implementation: a recursive-descent parser with precedence climbing
/// (<see cref="ParseSyntax(string)"/> produces the raw AST, where every identifier is an
/// <see cref="Expr.Resolve"/> node). Clause definitions <c>Name(pattern) = body</c> are
/// collected by same-name family during parsing and classified only after the whole family
/// is known: a family elaborates to ordinary <see cref="Algorithm.User"/> only when it
/// contains exactly one clause and that sole head is a recursive capture/sequence-value
/// parameter pattern; multi-clause families and literal/mixed heads elaborate to
/// <see cref="Algorithm.Conditional"/>.</para>
/// </summary>
public sealed class Parser
{
    private readonly IReadOnlyList<Token> _tokens;
    private readonly DiagnosticBag _diagnostics;

    // Where every lexical error starts, in source order — recorded by the lexer whether or not
    // the bag stored its diagnostic, so clause-head recovery never depends on the budget.
    private readonly IReadOnlyList<SourcePosition> _lexicalErrorStarts;

    // Optional, parse-scoped observer of clause-family duplicate-detection work. Null for every
    // production parse (no observation requested); a test measuring the indexed duplicate-detection
    // work passes one through an observed entry. It only feeds the clause-group duplicate indexes
    // (PatternMatchEquivalenceIndex), so it cannot affect the AST, diagnostics, or spans.
    private readonly PatternComparisonObservations? _comparisonObservations;

    // Source-processing cancellation observed inside clause-family duplicate detection (SEC-03):
    // the configured host token, checked FIRST so a host cancellation always carries its identity,
    // then the caller's active token (the module loader's materialization-linked token). Both are
    // None on the raw, non-cancellable parse entries. Per-parse instance state, never ambient.
    private readonly CancellationToken _sourceProcessingCancellationToken;
    private readonly CancellationToken _activeCancellationToken;
    private int _pos;

    // Passive per-parse count of token-index steps: one per consumed token (Advance)
    // and one per significant-index probe (NextSignificantIndex). It is the
    // deterministic cost model the marker-run linearity regressions read through
    // ParserTraversalObservations; it never influences parsing.
    private long _tokenSteps;

    // One-entry memo of the most recent LookaheadThroughTildesToPropertyDef scan,
    // keyed by the run's first significant token index (see that method).
    private int _graceRunScanStart = -1;
    private bool _graceRunScanVerdict;

    // Per-parse counter for the synthetic shared-source property generated by
    // deconstruction binding patterns (`x, *y, z = RHS`). The right-hand side is
    // evaluated once into this shared property; each target then unpacks from it.
    // Reset per parser instance so the elaborated AST stays deterministic across
    // re-parses.
    private int _deconstructionCounter;

    // SYN-07A separator-rule bookkeeping (see ReportUnseparatedSameLineItem).
    // A recovery that consumes or diagnoses a malformed run leaves the token
    // after it as the start of a same-line item that its own diagnostic
    // already explains; it records that token's source position here so the
    // separator rule stays silent for exactly that boundary. The second field
    // makes the report idempotent per item start, so the expression-list
    // operand and the body loop can both observe one boundary without
    // reporting it twice.
    private int _ownedSameLineItemPosition = -1;
    private int _reportedSameLineItemPosition = -1;

    // A skipped run may fill one missing piece, never two. Source traversal is monotone.
    private int _lastReportedCharacterFill = -1;
    private int _recoveryBinderCounter;

    private Parser(
        IReadOnlyList<Token> tokens,
        DiagnosticBag diagnostics,
        IReadOnlyList<SourcePosition> lexicalErrorStarts,
        PatternComparisonObservations? comparisonObservations,
        CancellationToken sourceProcessingCancellationToken,
        CancellationToken activeCancellationToken)
    {
        _tokens = tokens;
        _diagnostics = diagnostics;
        _lexicalErrorStarts = lexicalErrorStarts;
        _comparisonObservations = comparisonObservations;
        _sourceProcessingCancellationToken = sourceProcessingCancellationToken;
        _activeCancellationToken = activeCancellationToken;
    }

    // ── Parser recursion-depth budget ───────────────────────────────────────
    // Deeply nested surface input — parentheses, brackets, braces, calls, prefix
    // operators, right-associative power, and clause-head patterns — drives the
    // recursive-descent parser into a fatal, host-terminating StackOverflowException.
    // This budget converts such pathological input into ONE structured,
    // source-positioned diagnostic instead of a process crash.
    //
    // METRIC: one CUMULATIVE weighted counter of live parser recursion, in "parser
    // stack units", threaded through every recursive grammar mechanism for the WHOLE
    // parse. It NEVER resets when entering a nested container, operator chain,
    // pattern, call, or property — composed constructs (an operator chain restarting
    // inside each container level, containers inside containers of different kinds)
    // charge the one counter, so their stack costs add exactly like their frames do.
    // Base charges: ParseExpression +1 and ParseUnary +1 (every expression level),
    // ParsePatternAtom +1 (clause-head pattern nesting). Right-associative `^`
    // recursion re-enters ParseUnary from ParsePower (which charges nothing of
    // its own), so a `^` chain holds ONE live unit per level — the same live
    // accounting the pre-ParsePower right-recursion through ParseExpression
    // had. Heavy productions whose
    // per-level machinery measurably consumes more native stack carry SURCHARGES
    // (see the *NestingSurcharge constants) so that one unit costs at most ~1.25 KB
    // of Debug parser stack on every shape.
    //
    // CEILING: 384 units, non-bypassable and deliberately NOT configurable. It was
    // calibrated by per-shape process-isolated probes on dedicated 1 MiB threads
    // (the documented minimum supported stack): measured native crash boundaries are
    // parenthesized groups and brace blocks ~4.7 KB/level (crash at 211-225 levels ≈
    // 460 weighted units), call argument nesting ~3.5 KB/level, list literals
    // ~2.8 KB/level, clause patterns ~1.2 KB/level, prefix unary ~1 KB/level, and
    // mixed-container alternation tracks the SUM of its per-shape costs. At 384
    // units every shape peaks at ≤ ~480 KB — under HALF the 1 MiB envelope (≥2.1x
    // margin, Debug; Release frames are smaller still) — with the remainder as
    // headroom for engine/front-end caller frames and platform/JIT variation.
    //
    // NESTED-MODULE DEBT: parsing a downloaded module begins while module-loader
    // traversal frames are still live, so <see cref="ParseSyntax(string, int)"/>
    // accepts an initial debt (in these same units) that pre-charges the counter;
    // the loader converts its live traversal levels into debt conservatively
    // (see ModuleLoader). A parse that starts in debt simply has less budget.
    //
    // This metric is DISTINCT from: EvaluationLimits.MaxAstDepth / MaxSupportedAstDepth
    // (weighted STRUCTURAL depth of the finished AST, judged after parsing),
    // AstStructuralPreflight.RawSyntaxMaxAstDepth (the raw post-parse tree gate),
    // EvaluationLimits.MaxDepth (runtime algorithm invocations), MaxExpressionChainDepth
    // (iteratively parsed chain AST depth — chains consume O(1) parser recursion, so a
    // maximal 256-operator chain is unaffected by this budget), and the
    // SourceProcessingLimits source-size ceilings. This is a C#-parser host-robustness
    // concern only: the Lean model does not describe surface parsing, and every
    // in-budget program parses identically (same AST, spans, and diagnostics).
    internal const int MaxNestingDepth = 384;
    private int _nestingDepth;
    private StateScopeStack _stateScopes;

    // Closing delimiters currently owed to an enclosing construct, per delimiter kind
    // (`(` groups and call argument lists, `[` list literals, `{` brace bodies and
    // trailing-brace call arguments). Primary-expression recovery consults them so
    // that a closer an enclosing construct is waiting for is NEVER consumed as junk
    // (`F(1, )`, `(1 + )`, `[1, ]`, `{1, }`): the owner closes its construct at the
    // written closer and every later declaration stays in the scope it was written
    // in. A closer no enclosing construct is waiting for closes the innermost
    // construct as a mismatch; only a root stray is consumed as junk.
    private int _openParens;
    private int _openBrackets;
    private int _openBraces;

    // Interpolation holes currently open (STR-02). A hole's extent is fixed by the lexer
    // (every InterpolationHoleOpen has its InterpolationHoleClose on the same line), so a hole
    // is an OWNERSHIP BARRIER: entering one saves and zeroes the three counters above — a
    // closer written inside a hole can never close a construct opened outside it — and the
    // hole's own close is the one closer it is owed (see EnterInterpolationHole).
    private int _openInterpolationHoles;

    // Per-level surcharges for the heavy productions, calibrated by the same probes:
    // a parenthesized group or brace block runs the block/algorithm machinery each
    // level (~4.7 KB Debug ⇒ 4 total units with the two base charges), a call
    // argument list adds its call machinery (~3.5 KB ⇒ 3 units; the trailing-brace
    // call form charges BOTH surcharges because it runs the call AND block
    // machineries ⇒ 5 total units per level — deliberately conservative, bounding
    // trailing-brace chains at 76 levels; see the exact-boundary pins in
    // ParserNestingDepthTests and the ParserRecursionBudget probe), a list
    // literal adds its element-list machinery (~2.8 KB ⇒ 3 units), and a postfix
    // selector list `R[ ... ]` runs the same element-list machinery from the
    // postfix loop (⇒ 3 units, the list literal's charge).
    private const int GroupNestingSurcharge = 2;
    private const int BlockNestingSurcharge = 2;
    private const int CallArgsNestingSurcharge = 1;
    private const int ListNestingSurcharge = 1;
    private const int SelectionNestingSurcharge = 1;

    // An interpolated string and its hole run the string/hole machinery on top of the hole's
    // expression levels (ParseInterpolatedString → ParseInterpolationHole → ParseExpression),
    // so each hole level carries a surcharge on the same cumulative budget, calibrated by the
    // same 1 MiB probes (ParserNestingDepthTests' interpolation shape).
    private const int InterpolationHoleNestingSurcharge = 2;

    /// <summary>
    /// The stable prefix of the parser recursion-budget diagnostic. The module
    /// loader classifies a nested module's budget rejection by the diagnostic's
    /// structured <see cref="DiagnosticCode.NestingTooDeep"/> code (translating it
    /// into its own <c>load:</c> source-processing diagnostic at the load site);
    /// this constant remains the stable message wording.
    /// </summary>
    internal const string NestingTooDeepMessage = "Nesting is too deep for the parser to process safely.";

    // Flat left-associative binary and postfix syntax is parsed iteratively, but it
    // produces a left-deep AST that the frontend's recursive visitors must traverse.
    // Keep that AST depth on the same conservative scale as the ~289 structural
    // levels admitted by MaxNestingDepth. This is per expression chain: independent
    // output rows, comma-separated slots, and list items each start from depth zero.
    internal const int MaxExpressionChainDepth = 256;
    private readonly Dictionary<Expr, int> _expressionChainDepths =
        new(ReferenceEqualityComparer.Instance);

    private abstract class ParserLimitExceededException : Exception { }
    private sealed class NestingLimitExceededException : ParserLimitExceededException { }
    private sealed class ExpressionChainLimitExceededException : ParserLimitExceededException { }

    /// <summary>
    /// Aborts the whole parse with a single structured diagnostic when the recursion
    /// budget is exceeded: the check of the pre-charged loader debt at the root, and the
    /// check every admitted level runs through <see cref="EnterNestingLevel"/> /
    /// <see cref="EnterDelimitedProduction"/>.
    /// </summary>
    private void GuardNestingDepth()
    {
        if (_nestingDepth > MaxNestingDepth)
            ThrowNestingTooDeep();
    }

    private void ThrowNestingTooDeep()
    {
        ReportError(
            DiagnosticCode.NestingTooDeep,
            NestingTooDeepMessage +
            " Reduce the depth of nested parentheses, brackets, braces, calls, operators, or patterns.");
        throw new NestingLimitExceededException();
    }

    /// <summary>
    /// One admitted base level of the shared recursion budget — the chokepoint charge of
    /// every expression level, every unary level, and every clause-head pattern level.
    /// Released exactly once by <see cref="Dispose"/>, always from a <c>using</c>, so the
    /// release runs on the ordinary return, on recovery, and on a budget exception's
    /// unwind alike; the counter can therefore never be left charged by a level that
    /// forgot its release. The default value (never handed out by
    /// <see cref="EnterNestingLevel"/>, which throws instead of returning a refused level)
    /// releases nothing.
    /// </summary>
    private readonly struct NestingLevel(Parser parser, StateScopeStack.Ticket ticket) : IDisposable
    {
        public void Dispose()
        {
            if (parser is null)
                return;
            parser._stateScopes.Exit(ticket);
            parser._nestingDepth--;
        }
    }

    /// <summary>
    /// Admits and charges ONE base unit of the recursion budget, returning the level
    /// the caller MUST dispose from a <c>using</c>. A refused enter mutates nothing: the
    /// budget diagnostic aborts the parse before the unit is charged, so no release is
    /// owed for a level that was never admitted.
    /// </summary>
    private NestingLevel EnterNestingLevel()
    {
        if (_nestingDepth >= MaxNestingDepth)
            ThrowNestingTooDeep();

        var ticket = _stateScopes.Enter();
        _nestingDepth++;
        return new NestingLevel(this, ticket);
    }

    /// <summary>
    /// One admitted heavy delimited production: a parenthesized group or call argument
    /// list (<c>(</c>), a brace body or trailing-brace call argument (<c>{</c>), or a list
    /// literal (<c>[</c>). Entry charges the production's calibrated surcharge on the
    /// shared recursion budget AND registers the closer the production is now owed
    /// (<see cref="IsOwedCloser"/>); <see cref="Dispose"/> releases exactly those two
    /// changes, once, always from a <c>using</c> that ends where the production's body
    /// parse ends — before the closer is consumed, exactly like the <c>finally</c> it
    /// replaces. The default value releases nothing.
    /// </summary>
    private readonly struct DelimitedProduction(Parser parser, TokenKind closer, int surcharge, StateScopeStack.Ticket ticket) : IDisposable
    {
        public void Dispose()
        {
            if (parser is null)
                return;

            parser._stateScopes.Exit(ticket);
            parser._nestingDepth -= surcharge;
            parser.ReleaseOwedCloser(closer);
        }
    }

    /// <summary>
    /// Enters a heavy delimited production (<see cref="DelimitedProduction"/>): charges
    /// <paramref name="surcharge"/> on top of the base chokepoint units the body's
    /// expression levels will charge and registers the owed <paramref name="closer"/>.
    /// A refused enter mutates nothing: admission precedes both changes.
    /// </summary>
    private DelimitedProduction EnterDelimitedProduction(TokenKind closer, int surcharge)
    {
        // Validate every potentially rejecting input before acquiring the state scope.
        if (closer is not (TokenKind.RParen or TokenKind.RBracket or TokenKind.RBrace))
            throw new ArgumentOutOfRangeException(nameof(closer), closer, "Not a closing delimiter.");
        if (surcharge < 0)
            throw new ArgumentOutOfRangeException(nameof(surcharge));
        if (surcharge > MaxNestingDepth - _nestingDepth)
            ThrowNestingTooDeep();

        var ticket = _stateScopes.Enter();
        RegisterOwedCloser(closer);
        _nestingDepth += surcharge;

        return new DelimitedProduction(this, closer, surcharge, ticket);
    }

    /// <summary>
    /// Whether <paramref name="kind"/> is a closing delimiter some enclosing construct is
    /// still waiting for (see <see cref="_openParens"/>).
    /// </summary>
    private bool IsOwedCloser(TokenKind kind) => kind switch
    {
        TokenKind.RParen => _openParens > 0,
        TokenKind.RBracket => _openBrackets > 0,
        TokenKind.RBrace => _openBraces > 0,
        TokenKind.InterpolationHoleClose => _openInterpolationHoles > 0,
        _ => false,
    };

    private static bool IsClosingDelimiter(TokenKind kind)
        => kind is TokenKind.RParen or TokenKind.RBracket or TokenKind.RBrace or TokenKind.InterpolationHoleClose;

    /// <summary>Whether any delimited construct (group, call arguments, list, brace body, interpolation hole) is open.</summary>
    private bool IsInsideDelimitedConstruct
        => _openParens + _openBrackets + _openBraces + _openInterpolationHoles > 0;

    /// <summary>
    /// Whether the parser is at HOLE LEVEL: directly inside an interpolation hole, with no
    /// group, list, selector list, call argument list or brace body opened since the hole began
    /// (the hole's ownership barrier zeroed their counters). The hole-level restrictions apply
    /// only here: a hole holds ONE expression, and interpolation has no format specifiers, so a
    /// <c>:</c> that begins a hole or follows the hole's completed expression is the hole's own
    /// report, never the retired colon selection (a selection in a hole is written with brackets,
    /// <c>"{xs[0]}"</c>). A <c>:</c> where the hole's expression still needs an operand
    /// (<c>"{a + :0}"</c>, <c>"{-:0}"</c>) is that operand's own <c>RetiredColonSelection</c>, and the
    /// hole adds no second report — exactly as a misplaced <c>,</c> or <c>=</c> there is the
    /// operand's own report.
    /// </summary>
    private bool IsAtInterpolationHoleLevel
        => _openInterpolationHoles > 0 && _openParens + _openBrackets + _openBraces == 0;

    /// <summary>
    /// One admitted interpolation hole: charges <see cref="InterpolationHoleNestingSurcharge"/>
    /// on the shared recursion budget, registers the hole's close as owed, and raises the hole's
    /// OWNERSHIP BARRIER — the enclosing constructs' owed-closer counters are saved and zeroed,
    /// so a closer written inside the hole is never taken for an enclosing construct's closer
    /// (<c>F("{ ) }")</c> reports the <c>)</c> inside the hole and leaves <c>F(</c> open on its
    /// own terms). <see cref="Dispose"/> restores exactly those changes, once, from a
    /// <c>using</c>. The default value restores nothing.
    /// </summary>
    private readonly struct InterpolationHoleProduction(
        Parser parser,
        int openParens,
        int openBrackets,
        int openBraces,
        StateScopeStack.Ticket ticket) : IDisposable
    {
        public void Dispose()
        {
            if (parser is null)
                return;

            parser._stateScopes.Exit(ticket);
            parser._nestingDepth -= InterpolationHoleNestingSurcharge;
            parser._openInterpolationHoles--;
            parser._openParens = openParens;
            parser._openBrackets = openBrackets;
            parser._openBraces = openBraces;
        }
    }

    /// <summary>
    /// Enters an interpolation hole (<see cref="InterpolationHoleProduction"/>). A refused enter
    /// mutates nothing: admission precedes every change.
    /// </summary>
    private InterpolationHoleProduction EnterInterpolationHole()
    {
        if (InterpolationHoleNestingSurcharge > MaxNestingDepth - _nestingDepth)
            ThrowNestingTooDeep();

        var ticket = _stateScopes.Enter();
        var production = new InterpolationHoleProduction(this, _openParens, _openBrackets, _openBraces, ticket);
        _openParens = 0;
        _openBrackets = 0;
        _openBraces = 0;
        _openInterpolationHoles++;
        _nestingDepth += InterpolationHoleNestingSurcharge;
        return production;
    }

    // ── Delimiter ownership (the #9 recovery law) ───────────────────────────
    // A closing delimiter is resolved by exactly one owner, never consumed as junk
    // while a construct is open:
    //   1. Every nested body, list, operand, and head parse ENDS at a closing
    //      delimiter of any kind and leaves it for the innermost open construct.
    //   2. That construct resolves it (ExpectCloser): its own closer is consumed; a
    //      closer an ENCLOSING construct is waiting for is reported and left for that
    //      owner, which closes there (the constructs in between report their missing
    //      closers); a closer NO open construct is waiting for is reported as the
    //      mismatch it is and consumed as this construct's closer (`(1, 2]`).
    //   3. With no construct open, a closer is a top-level stray, reported and
    //      consumed in place so later source stays in the root scope.
    // Consequence: every closer closes at least one open construct, so a region
    // whose delimiters balance by COUNT (whatever their kinds) closes every construct
    // it opens, and no later declaration can be swallowed by a wrong closer.

    /// <summary>
    /// Closes the construct whose own closer is <paramref name="closer"/> (rule 2 of
    /// the delimiter-ownership law): consumes it when present; otherwise reports the
    /// missing closer and, when the token found instead is a closing delimiter that no
    /// enclosing construct is waiting for, consumes it as this construct's closer. An
    /// owed closer and every non-closer are left in place. Called after the
    /// production's own owed-closer registration was released, so
    /// <see cref="IsOwedCloser"/> sees only the enclosing constructs.
    /// </summary>
    [System.Runtime.CompilerServices.MethodImpl(LeafFrame)]
    private void ExpectCloser(TokenKind closer)
    {
        if (Current.Kind == closer)
        {
            Advance();
            return;
        }

        ReportError(
            DiagnosticCode.UnexpectedToken,
            $"Expected {DescribeTokenKind(closer)} but found {DescribeTokenKind(Current.Kind)}.");
        if (IsClosingDelimiter(Current.Kind) && !IsOwedCloser(Current.Kind))
        {
            // The mismatched closer closes this construct: its diagnostic above also
            // explains whatever follows it on the line.
            Advance();
            OwnSameLineItem(Current);
        }
    }

    private void RegisterOwedCloser(TokenKind closer)
    {
        switch (closer)
        {
            case TokenKind.RParen: _openParens++; break;
            case TokenKind.RBracket: _openBrackets++; break;
            case TokenKind.RBrace: _openBraces++; break;
            default: throw new ArgumentOutOfRangeException(nameof(closer), closer, "Not a closing delimiter.");
        }
    }

    private void ReleaseOwedCloser(TokenKind closer)
    {
        switch (closer)
        {
            case TokenKind.RParen: _openParens--; break;
            case TokenKind.RBracket: _openBrackets--; break;
            case TokenKind.RBrace: _openBraces--; break;
            default: throw new ArgumentOutOfRangeException(nameof(closer), closer, "Not a closing delimiter.");
        }
    }

    /// <summary>
    /// Records the binary/postfix depth of a newly constructed expression and aborts
    /// before a recursive frontend visitor can receive an excessively deep AST.
    /// Child depths are looked up by reference so record structural equality never
    /// recursively walks the very chain this guard is protecting.
    /// </summary>
    private Expr GuardExpressionChainDepth(
        Expr expression,
        Token operatorToken,
        Expr firstChild,
        Expr? secondChild = null)
    {
        var childDepth = ExpressionChainDepth(firstChild);
        if (secondChild is not null)
            childDepth = Math.Max(childDepth, ExpressionChainDepth(secondChild));

        return RegisterExpressionChainDepth(expression, operatorToken, childDepth);
    }

    /// <summary>
    /// The chain-depth guard for a comparison chain: one level over the DEEPEST of its
    /// operands. A chain's operands are siblings (the chain is one flat node however
    /// many links it has), so a long chain costs one level, exactly like one binary node.
    /// </summary>
    private Expr GuardComparisonChainDepth(Expr.Comparison chain, Token operatorToken)
    {
        var childDepth = ExpressionChainDepth(chain.First);
        foreach (var link in chain.Links)
            childDepth = Math.Max(childDepth, ExpressionChainDepth(link.Operand));

        return RegisterExpressionChainDepth(chain, operatorToken, childDepth);
    }

    private Expr RegisterExpressionChainDepth(Expr expression, Token operatorToken, int childDepth)
    {
        var depth = childDepth + 1;
        if (depth > MaxExpressionChainDepth)
        {
            ReportErrorAt(
                DiagnosticCode.ExpressionChainTooDeep,
                "Expression operator or postfix chain is too deep for the frontend to process safely. " +
                "Break the expression into named intermediate properties.",
                operatorToken);
            throw new ExpressionChainLimitExceededException();
        }

        _expressionChainDepths.Add(expression, depth);
        return expression;
    }

    private int ExpressionChainDepth(Expr expression)
        => _expressionChainDepths.TryGetValue(expression, out var depth) ? depth : 0;

    // ── Entry points ─────────────────────────────────────────────────────────

    internal static SyntaxParseResult ParseSyntax(string source)
        => ParseSyntax(source, comparisonObservations: null);

    /// <summary>
    /// Raw parse that reports into an operation's diagnostic bag — the front end's parse of the
    /// main program, whose lexical and syntax diagnostics open the operation's one bounded list
    /// (<see cref="DiagnosticBag"/>).
    /// </summary>
    internal static SyntaxParseResult ParseSyntax(string source, DiagnosticBag diagnostics)
        => ParseSyntaxCore(
            source,
            comparisonObservations: null,
            initialNestingDebt: 0,
            traversalObservations: null,
            diagnostics,
            CancellationToken.None,
            CancellationToken.None);

    /// <summary>
    /// Raw parse that begins with part of the parser recursion budget already spent.
    /// The module loader uses this when parsing a DOWNLOADED module: that parse runs
    /// while the loader's own traversal frames are still live on the stack, so the
    /// loader pre-charges a conservative debt (in the same cumulative parser stack
    /// units) for those frames. A parse that starts in debt has proportionally less
    /// nesting budget and reports the same established nesting diagnostic at the
    /// crossing token; in-budget sources parse identically.
    /// </summary>
    internal static SyntaxParseResult ParseSyntax(string source, int initialNestingDebt)
        => ParseSyntax(source, comparisonObservations: null, initialNestingDebt);

    /// <summary>
    /// The configured front end's and the module loader's parse: into an operation's diagnostic
    /// bag (for a module, a bag of the run's diagnostic capacity, so even a module whose own
    /// diagnostics are summarized at its load site never holds more than one list's worth while it
    /// is classified), starting at <paramref name="initialNestingDebt"/> (see
    /// <see cref="ParseSyntax(string, int)"/>), and observing source-processing cancellation inside
    /// clause-family duplicate detection: <paramref name="sourceProcessingCancellationToken"/> is the
    /// configured host token, observed first so a host cancellation keeps its identity, and
    /// <paramref name="activeCancellationToken"/> the caller's active token (the loader's
    /// materialization-linked token; <see cref="CancellationToken.None"/> otherwise).
    /// <paramref name="comparisonObservations"/> is null in production.
    /// </summary>
    /// <exception cref="OperationCanceledException">A supplied token was cancelled during the parse.</exception>
    internal static SyntaxParseResult ParseSyntax(
        string source,
        int initialNestingDebt,
        DiagnosticBag diagnostics,
        PatternComparisonObservations? comparisonObservations,
        CancellationToken sourceProcessingCancellationToken,
        CancellationToken activeCancellationToken)
        => ParseSyntaxCore(
            source,
            comparisonObservations,
            initialNestingDebt,
            traversalObservations: null,
            diagnostics,
            sourceProcessingCancellationToken,
            activeCancellationToken);

    /// <summary>
    /// Raw parse that additionally records clause-family duplicate-detection work into
    /// <paramref name="comparisonObservations"/> and observes <paramref name="cancellationToken"/>
    /// inside duplicate detection. Test/measurement-only entry: the observed and unobserved paths
    /// share this one implementation, so the AST, diagnostics, and spans are identical — only the
    /// passive counts differ.
